// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **배에 자리가 생겼나** (v153 · 뼈대만 · 게임을 안 부른다)
//
//    node tools/space-move.js
//
//  ★ 사장님 (2026-08-14) 세 말씀이 **뿌리가 하나**였다:
//    「**앞으로 이동 중인데 적은 그대로 뒤에 있는데?**」
//    「**그대로 서 있는 자세에서 뒤집는거면 문제가 있는거 아냐?**」
//    「**자유자재로 움직이는게 더 실감나지 않을까?**」
//
//  ══ v152 까지 이랬다 ═══════════════════════════════════════════════════
//
//      전속으로 앞으로 가는 동안 (진짜 브라우저에서 잰 값)
//        −10°  위성    192 → 173  (−19m)   가까워져야  ✔
//        118°  파편    150 → 131  (−19m)   거의 그대로 ✘
//       −132°  표류선  118 →  99  (−19m)   ★ 멀어져야  ✘
//
//  **방위와 상관없이 전부 똑같이 −19m.** v152 가 **깎는 속도**를 고쳤지만
//  **방향은 여전히 없었다** — 「앞으로 간다」가 「모두의 거리를 똑같이
//  깎는다」였기 때문이다.
//
//  ★★★ 이 검사는 **부호와 방향**을 묻는다. 속도(얼마나)는 `space-drive.js`
//    가 이미 묻고 있고, 여기서 또 물으면 **재는 곳이 둘**이 된다.
// ══════════════════════════════════════════════════════════════════════════
import { pointOf, polarOf, flyBy, closestPass, wrap } from '../web/space/js/game/frame.js';

let bad = 0;
const ok = (c, m) => { console.log(`  ${c ? '✔' : '✘'} ${m}`); if (!c) bad++; };
const near = (a, b, tol = 1e-6) => Math.abs(a - b) <= tol;

console.log('배에 자리가 생겼나 (뼈대만 · 게임을 안 부른다)');

console.log('\n[1] ★★★ **각↔자리가 정확한 왕복인가** — 「거의 반대」면 안 된다');
{
  //  ★★ 이 파일이 스스로 적어 둔 경고다 (`relOf` 주석) — 두 입구가 **거의**
  //    같은 것이 제일 나쁘다. 늘 틀리면 금방 잡히는데, **정면에서만 맞으면**
  //    검사도 통과하고 눈에도 안 띄다가 기수를 든 순간 어긋난다.
  //  ★★★ 그래서 **정면 하나로 검증하지 않는다** (CLAUDE.md 규칙 넷 중 셋째).
  //    v98 의 「그냥 빼기」가 정확히 정면에서만 맞았다
  const cases = [];
  for (const az of [0, 37, 90, 143, 180, -37, -90, -143]) {
    for (const el of [0, 25, -25, 60, -60]) {
      for (const dist of [12, 150, 900]) cases.push({ az, el, dist });
    }
  }
  let worst = 0, worstAt = null;
  for (const t of cases) {
    const r = polarOf(pointOf(t));
    const dAz = Math.abs(wrap(r.az - t.az));
    //  ★ 극(el ±90)에서는 방위가 뜻을 잃는다 — 여기 쓰는 각에는 극이 없다
    const e = Math.max(dAz, Math.abs(r.el - t.el), Math.abs(r.dist - t.dist) / t.dist);
    if (e > worst) { worst = e; worstAt = t; }
  }
  console.log(`   ${cases.length} 가지를 왕복 — 제일 어긋난 곳 ${worst.toExponential(2)}`
    + ` (${worstAt.az}° · ${worstAt.el}° · ${worstAt.dist}m)`);
  ok(worst < 1e-9,
    '★★★ **`polarOf` 가 `pointOf` 의 정확한 반대다** — 틀고 · 들고 · 뒤집어 놓고 다 잰다.'
    + ' 정면만 재면 v98 의 「그냥 빼기」처럼 **정면 0도, 들면 5도**가 되고 그건 안 잡힌다');
}

console.log('\n[2] ★★★ **앞으로 가면 뒤가 멀어지나** — 이 판의 알맹이');
{
  //  ★ v152 까지 여기가 전부 「−19m」이었다. 부호가 통째로 없었다
  const step = { fwd: 20 };
  const rows = [
    ['정면', 0, '가까워져야', (d0, d1) => d1 < d0 - 19],
    ['비스듬 앞', 45, '가까워져야', (d0, d1) => d1 < d0],
    ['정측면', 90, '거의 그대로', (d0, d1) => Math.abs(d1 - d0) < 2],
    ['비스듬 뒤', 135, '★ 멀어져야', (d0, d1) => d1 > d0],
    ['정후방', 180, '★ 멀어져야', (d0, d1) => d1 > d0 + 19],
  ];
  for (const [name, az, want, test] of rows) {
    const t = { az, el: 0, dist: 150 };
    const n = flyBy(t, step);
    const d = n.dist - t.dist;
    console.log(`   ${name.padEnd(9)} (${String(az).padStart(4)}°)  150.0 → ${n.dist.toFixed(1)}`
      + `  (${d >= 0 ? '+' : ''}${d.toFixed(1)}m)  ${want}`);
    ok(test(t.dist, n.dist), `${name} — ${want}`);
  }
  ok(true, '★★★ 위 다섯이 **한 함수(`flyBy`)에서 저절로** 나온다 — 방위별로 따로 적지 않았다.'
    + ' 따로 적기 시작하면 그게 곧 「자리를 아는 곳」이 둘이 되는 것이다');
}

console.log('\n[3] ★★★ **스쳐 지나가나** — 「빠른 전개」는 여기서 나온다');
{
  //  ★ 사장님 「**비행전투rpg니깐 빠른 속도로 전개가 되어야해**」
  //  ★★ 속도만 올리면 「전부 똑같이 빨리 다가온다」가 될 뿐이다. **지나쳐
  //    버리는 일**이 생겨야 속도가 속도로 느껴진다 — 그리고 그건 숫자를
  //    올려서가 아니라 **자리가 생겨야** 나온다
  let t = { az: 12, el: 0, dist: 300 };
  const seen = [];
  for (let i = 0; i < 40; i++) { t = flyBy(t, { fwd: 12 }); seen.push({ d: t.dist, az: t.az }); }
  const min = Math.min(...seen.map((s) => s.d));
  const at = seen.findIndex((s) => s.d === min);
  console.log(`   12° · 300m 을 향해 40걸음 — 제일 붙은 곳 ${min.toFixed(1)}m (${at + 1}걸음째)`
    + ` · 끝에 ${seen.at(-1).d.toFixed(1)}m · 방위 ${seen.at(-1).az.toFixed(0)}°`);
  ok(at > 0 && at < seen.length - 1,
    '★★★ **줄다가 늘어난다** — 지나쳐 버린다. 옛 모형에는 이 일이 **일어날 수가 없었다**');
  ok(Math.abs(seen.at(-1).az) > 90,
    `★★ **지나친 뒤에는 뒤에 있다** (${seen.at(-1).az.toFixed(0)}°) — 방위가 저절로 넘어간다.`
    + ' 「지나갔다」를 따로 판정하지 않는다');
  const cpa = closestPass({ az: 12, el: 0, dist: 300 }, 12);
  console.log(`   CPA — 이대로 가면 ${cpa.dist.toFixed(1)}m 까지 · ${cpa.sec.toFixed(1)}초 뒤`);
  ok(near(cpa.dist, min, min * 0.05),
    `★★★ **CPA 가 실제로 붙는 거리와 같다** (${cpa.dist.toFixed(1)} vs ${min.toFixed(1)})`
    + ' — 계기가 말하는 값과 실제로 벌어지는 일이 갈라지면 그 계기는 그 뒤로 아무도 안 믿는다');
  ok(closestPass({ az: 12, el: 0, dist: 300 }, 0).sec === Infinity,
    '★ **안 가고 있으면 「언제」가 없다** — 0 으로 나눠서 이상한 숫자를 만들지 않는다');
}

console.log('\n[4] ★★★ **회피가 자리를 옮기나** — 사장님 「그대로 서 있는 자세에서 뒤집는거면」');
{
  //  ★★★ 지금 회피(`dodge-table.js`)는 A/D(요) · Q/E(롤)로 **방향만** 바꾼다.
  //    판정에 속도가 한 글자도 안 들어가서 **서 있어도 완벽 회피가 된다.**
  //    회피는 방향을 바꾸는 일이 아니라 **자리를 옮기는 일**이므로, 옮겨진
  //    자리가 뼈대에서 정말 나오는지부터 여기서 못박는다
  const t = { az: 0, el: 0, dist: 60 };
  const push = flyBy(t, { right: 18 });
  console.log(`   정면 60m 짜리를 오른쪽으로 18m 밀었다 — 방위 ${push.az.toFixed(1)}° · ${push.dist.toFixed(1)}m`);
  ok(push.az < -5,
    `★★★ **옆으로 밀면 표적이 반대쪽으로 간다** (${push.az.toFixed(1)}°) — 배가 오른쪽으로 갔으니`
    + ' 정면에 있던 것은 **왼쪽**에 남는다. 이것이 「피했다」의 실체다');
  //  ★ 밀어도 **거리는 거의 안 준다** — 피하는 것과 다가가는 것은 다른 일이다
  ok(push.dist > t.dist,
    `★★ 옆으로만 밀면 **거리는 오히려 는다** (${push.dist.toFixed(1)}m) — 빗변이니까.`
    + ' 「피했는데 더 가까워지는」 일이 안 생긴다');
  //  ★★ 서 있으면? — 뼈대에서는 **걸음이 0 이면 아무 일도 안 난다**
  const still = flyBy(t, { fwd: 0, right: 0, up: 0 });
  ok(near(still.dist, t.dist, 1e-9) && near(still.az, t.az, 1e-9),
    '★★★ **안 움직이면 자리가 안 바뀐다** — 굴리기만 해서는 못 피한다는 것이'
    + ' 여기서 **저절로** 나온다. 회피 판정이 이 뼈대를 물면 「서 있는데 완벽 회피」가 사라진다');
}

console.log('\n[5] ★★ **왕복하면 제자리인가** — 새는 데가 없나');
{
  let t = { az: 33, el: 17, dist: 220 };
  const o = { ...t };
  for (let i = 0; i < 50; i++) t = flyBy(t, { fwd: 7, right: 3, up: -2 });
  for (let i = 0; i < 50; i++) t = flyBy(t, { fwd: -7, right: -3, up: 2 });
  const e = Math.max(Math.abs(wrap(t.az - o.az)), Math.abs(t.el - o.el), Math.abs(t.dist - o.dist));
  console.log(`   100걸음 왕복 — 어긋남 ${e.toExponential(2)}`);
  ok(e < 1e-9,
    '★★ **갔다 오면 제자리다** — 매 걸음 각↔자리를 오가므로 여기가 새면 오래 날수록'
    + ' 조금씩 틀어진다. 그런 것은 **한 판 다 돌기 전에는 안 보인다**');
}

console.log('\n[6] ★★★ **게임에 아직 안 물렸다** — 뼈대만 세운 판이다');
{
  //  ★ 이 저장소 규칙: ①뼈대 → ②뼈대만 시뮬 → ③갈아 끼우기 → ④화면과 대조.
  //    지금은 ①② 다. **③ 을 안 했다는 것을 검사가 말하게** 해 둔다 —
  //    안 그러면 「초록이니까 됐다」로 읽히고, 그게 죽은 초록이다
  console.log('   ※ `stepSky` 는 아직 `t.dist -= …` 로 돈다 (③ 은 다음 걸음)');
  ok(true, '★★★ **여기까지가 「게임에 붙일 자격」이다** — 관계가 맞는 것과'
    + ' 게임이 그 관계대로 도는 것은 다른 말이고, 뒤는 `space-drive.js [9]` 처럼'
    + ' **`main.js` 를 읽어서** 따로 물어야 한다');
  //  ══ ★★★ **한 번 물려 봤고, 되돌렸다** — 그 까닭을 남긴다 ══════════════
  //
  //  v153 에 `stepSky` 를 이것으로 갈아 끼워 봤다. **뒤가 정말 멀어졌다** —
  //  진짜 브라우저에서 −10° 앞은 −17m, 120° 는 +9m, −134° 는 +13m.
  //  사장님이 짚으신 것이 바로 고쳐진 것이다.
  //
  //  ★★★ 그런데 **전투가 거의 사라졌다.** `space-war` 가 잡았다:
  //
  //      회차에 맞는 것   12대 (목표 20~90)   ← 물리기 전에는 통과였다
  //      싸움 횟수        3번
  //      전투에 든 시간   0.9% (목표 40~55%)
  //
  //  ★★ 까닭이 명백하다 — **자리가 생기면 대부분이 멀찍이 스쳐 지나간다.**
  //    옛 모형에서는 어디에 뜨든 **곧장 나에게로** 왔으므로 전투 밀도가
  //    거리 하나로 정해졌다. 이제는 **빗나가는 것이 기본**이다.
  //    (12° · 300m 짜리도 62m 까지만 붙고 지나가 버린다 — [3] 참고)
  //
  //  ★ 앞쪽에 더 태어나게(`spawnFront`) 해 봤지만 **더 나빠졌다** (12→2대).
  //    즉 「태어나는 자리」로 될 일이 아니고, **적이 어떻게 붙는가**
  //    (`stepEngage` · `closes` · `standoff`)를 통째로 다시 잡아야 한다.
  //
  //  ★★★ 그래서 **되돌렸다.** 「뒤가 멀어진다」를 얻으려고 「전투가 있다」를
  //    잃으면 그건 고친 것이 아니다. 이 저장소가 태운 판들이 다 그 모양이었다.
  //    뼈대는 여기 서 있으므로 **다음 판은 전투 밀도부터** 잡고 물린다.
  ok(true, '★★★ **한 번 물려 봤고 되돌렸다** — 뒤는 정말 멀어졌는데 `space-war` 가'
    + ' 「회차에 12대 맞는다 (20~90)」로 빨개졌다. **자리가 생기면 대부분이 빗나가서**'
    + ' 전투 밀도가 통째로 무너진다. 하나를 얻고 하나를 잃으면 고친 것이 아니다');
}

