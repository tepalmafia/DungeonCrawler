// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **레이더가 정교한가 · 직관적인가** — 고증 다섯 (v75)
//
//    python3 tools/serve.py 8391 &
//    node tools/space-radar.js [포트]
//
//  ★ 사장님 「레이더 시스템을 더 **정교하게 직관적으로** 만들어줘.
//            **오른쪽 왼쪽이 아니고.** 실제 레이더 시스템을 고증해서」
//
//  ★★ v74 까지 레이더가 말하는 것은 **방위 하나**였다. v73 에 세 축을 다
//    열어 놓고(360도) 계기는 **평면 하나**였던 셈이라, 적이 아래에 있어도
//    화면에는 「왼쪽」이라고만 떴다 — 어디로 얼마나 돌릴지 알 수가 없다.
//
//  여기서 묻는 것 다섯 (`game/radar-table.js` 머리말의 고증 그대로):
//    [1] **위아래를 말하나** — PPI 에 못 담는 축을 숫자로 내나
//    [2] **접근율을 말하나** — 부호 하나가 곧 추격 곡선이다
//    [3] **모양으로 나누나** — 색만으로 나누면 어두울 때 죽는다
//    [4] ★★★ **저쪽이 나를 겨누면 알려 주나** (RWR)
//    [5] **「왼쪽/오른쪽」이 없어졌나**
//
//  ★ 앞의 넷은 **규칙**이라 브라우저 없이 재고, 마지막에 **실제 화면**을
//    한 번 띄워 계기가 정말 그리는지 본다 — 「표에만 있고 화면에는 없는」
//    것이 이 저장소가 제일 자주 밟는 함정이다.
// ══════════════════════════════════════════════════════════════════════════
import {
  SYMBOL, RINGS, READ, RWR, rwrLevel, elWord, vcWord, bearing, callOut,
} from '../web/space/js/game/radar-table.js';

let fail = 0;
const ok = (c, m) => { console.log((c ? '  ✔ ' : '  ✘ ') + m); if (!c) fail++; };

console.log('\n레이더 — 정교한가 · 직관적인가 (고증 다섯)');

// ══════════════════════════════════════════════════════════════════════════
console.log('\n[1] ★★★ **위아래를 말하나** — 여기가 「오른쪽 왼쪽이 아니고」의 답이다');
{
  ok(elWord(22) === '+22°', `위에 있으면 **+22°** (${elWord(22)})`);
  ok(elWord(-18) === '−18°', `아래에 있으면 **−18°** (${elWord(-18)})`);
  // ★ 거의 수평이면 안 적는다 — 군더더기는 정교함이 아니다
  ok(elWord(1) === null, `거의 수평이면 **안 적는다** (${READ.elMin}도 미만)`);
  ok(elWord(undefined) === null, '값이 없으면 안 적는다');
}

// ══════════════════════════════════════════════════════════════════════════
console.log('\n[2] ★★ **접근율을 말하나** — 부호 하나가 곧 추격 곡선이다 (BFM.md)');
{
  ok(vcWord(34) === '▲34', `다가오면 **▲34** (${vcWord(34)}) — 선도 추격이 되고 있다`);
  ok(vcWord(-21) === '▼21', `멀어지면 **▼21** (${vcWord(-21)}) — 지연 추격이다`);
  ok(vcWord(0.5) === null, `0 근처는 **안 적는다** (${READ.vcMin} 미만) — 잡음이다`);
  ok(vcWord(null) === null, '모르면 안 적는다 — 원뿔 밖은 거리를 모른다');
}

// ══════════════════════════════════════════════════════════════════════════
console.log('\n[3] ★★ **모양으로 나누나** — 색만으로 나누면 어두울 때 제일 먼저 죽는다');
{
  const shapes = new Set(Object.values(SYMBOL).map((s) => s.shape));
  ok(shapes.size >= 4,
    `심볼이 **${shapes.size}가지 모양**이다 (${[...shapes].join(' · ')}) —`
    + ' 색약인 사람에게도, 정전(장면 E)에도 남는다');
  ok(SYMBOL.search.shape !== SYMBOL.track.shape,
    '★ **수색과 추적이 다른 모양**이다 — 「있는 줄만 안다」와 「거리까지 안다」는'
    + ' 다른 것이고, 그 차이가 모양으로 보여야 한다');
  ok(SYMBOL.lock.shape !== SYMBOL.track.shape,
    '물린 것도 다른 모양이다 (마름모) — 조준경의 네모와도 갈라 뒀다');
  ok(RINGS.length === 3, `거리 고리가 ${RINGS.length}개다 — 둘이면 어림이 안 되고 넷이면 글자가 겹친다`);
}

// ══════════════════════════════════════════════════════════════════════════
console.log('\n[4] ★★★ **저쪽이 나를 겨누면 알려 주나** (RWR · 실제 전투기의 그 계기)');
{
  ok(rwrLevel(0) === null, '안 겨누면 안 뜬다');
  ok(rwrLevel(0.2) === null, `조금 겨눈 것으로는 안 뜬다 (${RWR.from} 미만) — 늘 떠 있으면 경고가 아니다`);
  ok(rwrLevel(0.55) === 'warn', `절반쯤 겨누면 **경고** (${rwrLevel(0.55)})`);
  ok(rwrLevel(0.9) === 'hot', `거의 다 겨누면 **급하다** (${rwrLevel(0.9)}) — 곧 쏜다`);
  ok(RWR.from > 0 && RWR.from < RWR.hot && RWR.hot < 1,
    `★★ 뜨는 때(${RWR.from})와 급해지는 때(${RWR.hot})가 **쏘기 전**이다 —`
    + ' 쏘는 순간에 뜨면 그건 경고가 아니라 부고다');
}

// ══════════════════════════════════════════════════════════════════════════
console.log('\n[5] ★★★ **「왼쪽/오른쪽」이 없어졌나** — 사장님이 짚으신 그 말');
{
  const w = callOut('요격기', -146, -22);
  console.log(`   지금 뭐라고 하나: 「${w}」`);
  ok(!/왼쪽|오른쪽/.test(w),
    '★★★ **「왼쪽」·「오른쪽」이라고 안 한다** — 그 말은 얼마나 돌릴지를 안 준다');
  ok(/\d+°/.test(w), '**각도가 숫자로** 들어 있다 — 얼마나 돌릴지가 그 자리에서 나온다');
  ok(/위|아래|수평/.test(w), '★★ **위아래를 말한다** — 세 축이 열린 뒤로 이게 빠지면 반쪽이다');
  ok(/좌|우|정면/.test(w),
    '그런데 **도는 방향은 글자로** 남긴다 — 숫자만 주면 어느 쪽이 가까운지'
    + ' 한 번 더 생각해야 한다');
  console.log(`   정면: 「${callOut('요격기', 0, 0)}」`);
  console.log(`   오른쪽 뒤 아래: 「${callOut('포함', 138, -31)}」`);
  ok(bearing(-146) === '214' && bearing(0) === '000',
    `방위는 **000~359** 로 센다 (${bearing(-146)} · ${bearing(0)}) — 항공·항해가 쓰는 그대로`);
}

console.log('');
console.log(fail ? `✘ ${fail} 군데` : '✔ 전부 통과 — 방위만 말하던 계기가 세 축을 다 말한다');
console.log('');
console.log('  ※ **「보기 좋은가」는 여기서 안 나온다.** 여기서 나오는 것은');
console.log('     「위아래를 말하나 · 접근율을 말하나 · 모양으로 나누나 ·');
console.log('     겨누면 알려 주나 · 왼쪽/오른쪽이 없어졌나」뿐이다.');
console.log('     화면에 정말 그려지나는 space-endtoend.js 가 손으로 본다.');
process.exit(fail ? 1 : 0);
