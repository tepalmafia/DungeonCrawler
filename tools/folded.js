//
//      빨강 넷 (walk · bay · guard · chase)
//          갈 수 없는 곳을 가라고 하니 당연히 빨갛다. **낡은 빨강은
//          새 빨강을 덮는다** — v120 의 조종간 · v121 의 정렬이 그랬다.
//
//      ★★★ 초록 다섯 (run · door · carry · repair · suit)
//          **이쪽이 더 나쁘다.** 「걸어오는 동안 문이 다 열린다」와
//          「9초를 뛰면 숨이 바닥난다」가 **초록으로** 떠 있었다.
//          걸을 몸이 자리에 없는데도. 낡은 검사가 죽은 설계를 지킨다.
//
//  ══ ★★ 왜 지우지 않나 ════════════════════════════════════════════════
//
//  `space-reach.js` 는 v116 에 지웠는데, 지우면 **걷기가 돌아와도 같이
//  안 돌아온다.** `space-fit.js` 가 고장 아홉을 두고 「지우지 않는다 —
//  걷기가 돌아오면 저절로 되살아난다」고 한 것과 같은 규약을 검사에도 쓴다.
//
//  ★ 접힌 줄 아는 곳은 **`pilot-table.js FOLDED_CHECKS` 하나**다.
//    도구마다 제 조건을 적으면 걷기가 돌아왔을 때 아홉 군데를 다 풀어야
//    하고, 한 군데만 빠뜨려도 조용히 죽는다
// ══════════════════════════════════════════════════════════════════════════
import { foldedWhy } from '../web/space/js/game/pilot-table.js';

/**
 * ★★★ 접혀 있으면 **아무것도 안 재고 0 으로 끝낸다.**
 *
 *   ★ 브라우저를 띄우기 **전에** 부른다 — 띄운 뒤면 접힌 검사도 30초씩 먹는다
 * @param name 이 도구 이름 (`space-walk` 처럼 확장자 없이)
 */
export function bailIfFolded(name) {
  const f = foldedWhy(name);
  if (!f) return false;
  console.log(`${name} — **접혀 있습니다** (v124)\n`);
  console.log(`   재던 것 : ${f.what}`);
  console.log(`   왜 접혔나: ${f.why}`);
  console.log('');
  console.log('   ★ 지운 것이 아닙니다. `game/pilot-table.js` 의 `PILOT.canStand` 가');
  console.log('     true 로 돌아오면 **이 검사도 같이 깨어납니다** —');
  console.log('     접힌 목록은 `FOLDED_CHECKS` 한 곳에 있고');
  console.log('     `tools/space-fit.js` 가 목록과 파일을 대조합니다.');
  process.exit(0);
}
