/** 파일 이름 → 자리 (`assets/models/raider.glb`) */
export const pathOf = (key) => `${MODEL_ROOT}${key}${RULES.ext}`;

/**
 * ★★ **크기를 맞춘다** — 모델이 얼마로 나왔든 표가 정한 길이로.
 *
 *   ★ 이것이 「크기는 안 맞춰도 된다」의 실체다. 생성 AI 는 단위 상자로
 *     뽑거나 cm 로 뽑거나 제각각인데, 그때마다 사장님이 블렌더를 여셔야
 *     한다면 그건 받는 자리가 아니다
 *
 * @param bboxLong 모델의 제일 긴 변 (m)
 * @param key      자리 이름
 */
export function fitScale(key, bboxLong) {
  const want = SLOTS[key]?.long;
  if (!want || !bboxLong || bboxLong <= 1e-6) return 1;
  return want / bboxLong;
}

/** 사람이 읽는 한 줄 — 검사와 문서가 같은 것을 쓴다 */
export function slotWord(key) {
  const s = SLOTS[key];
  if (!s) return key;
  return `${key}${RULES.ext} — ${s.long}m · ${s.what}`;
}

