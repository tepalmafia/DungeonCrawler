//  진짜 자리 위에** 그린다 (`space-align.js` 가 0.01도로 지킨다).
//  판을 옆으로 옮기면 그 그림이 통째로 어긋나 **「창밖의 저것」과
//  「계기의 저것」이 갈라진다** — 이 저장소가 네 판(v91·v93·v95·v98)을
//  태운 바로 그 병이다. 옮길 수 있는 것은 **읽는 창**뿐이다.
//
//  ★ three.js 를 안 쓴다 — `tools/space-layout.js` 가 읽는다.
// ══════════════════════════════════════════════════════════════════════════
