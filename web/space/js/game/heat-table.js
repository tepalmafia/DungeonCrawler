// ══════════════════════════════════════════════════════════════════════════
//  ★★ 열 저장고 — **배는 열을 버릴 수는 있어도 없앨 수는 없다** (v58)
//
//  ★ 사장님: 「냉각을 켜면 전력이 모자라서 센서를 못 키는게 말이 돼?」
//
//  ★★ 무엇이 틀려 있었나 (docs/space/REAL.md §2-A·B·I)
//     ① 회로 셋 중 둘만 켜졌다. 주 추진은 수십 MW, 냉각 펌프는 수 kW,
//        센서 수신기는 수백 W 다 — **전구를 켜면 엔진이 꺼지는 자동차**였다.
//        게다가 방향까지 반대였다: 추진이 열을 제일 많이 내므로 그때
//        냉각이 제일 필요한데, 규칙이 바로 그때 냉각을 막았다
//     ② **밸브가 닫혀 있는데 냉각 회로만으로 열이 내려갔다** (−0.9/초).
//        진공에서 열을 버리는 길은 **복사뿐**이다. 라디에이터가 닫혀
//        있으면 냉각 회로는 열을 **옮길 뿐 못 버린다**
//     ③ 자국이 「냉각 −9 · 라디에이터 +17」로 부호가 반대였다.
//        둘 다 열을 버리는 일인데
//
//  ★★ 셋을 **한 개념**으로 고친다 — 열이 **두 칸**이 된다
//
//        선체 온도    지금 뜨거운가 · **자국이 여기서 나온다**
//        열 저장고    배 안에 **쌓인 총열.** 안 버리면 안 준다
//
//        추진 ON        → 선체 +++
//        냉각 회로 ON   → 선체 −−, 저장고 ++   (★ 없애는 게 아니라 옮긴다)
//        라디에이터 열림 → 저장고 −−−, 자국 +++ (★ 여기서만 진짜로 나간다)
//        저장고 가득    → 냉각이 안 먹는다. 선체가 오른다
//
//     그래서 **전력 제한을 없앨 수 있다.** 셋 다 켜진다. 묶는 것은 전력이
//     아니라 **열**이다 — 다 켜면 저장고가 빨리 차고, 차면 라디에이터를
//     열어야 하고, 열면 자국이 폭발한다. **긴장은 그대로인데 이유가 생겼다.**
//     규칙을 외우는 대신 **이해하면 답이 나온다.**
//
//     그리고 「우주에서 스텔스는 불가능하다」(CHASE2)와 미션 「숨죽이기」가
//     이제 안 부딪힌다 — **잠깐은 숨을 수 있고, 저장고가 차면 못 숨는다.**
//     실제 우주선 은폐 개념이 정확히 이것이다.
//
//  ★ three.js 를 안 쓴다 — `tools/space-heat.js` 가 브라우저 없이 읽는다
// ══════════════════════════════════════════════════════════════════════════

/**
 * ★ 값을 **박자에서 거꾸로 잡았다.** (기획서에 쓴 「90~150초」는 재기 전에
 *   쓴 값이라 틀렸다 — 실제로 굴려 보니 그 값이면 회차당 라디에이터를
 *   30번 여닫아야 했고, 그건 「하루종일 열만 내리나」로 되돌아가는 것이다.
 *   PLANNING.md §4 ② 「재기 전에 쓰지 않는다」를 또 어겼고, 이번엔
 *   `space-heat.js` 가 그 자리에서 잡았다.)
 *
 *   거꾸로 잡은 차례:
 *     ① 회차(약 98분)에 라디에이터를 **6~12번** 연다 → 한 돌이 8~16분
 *     ② 한 돌 = 채우는 시간 + 버리는 시간
 *     ③ 채우기 400초 · 버리기 200초 → 한 돌 10분 → 회차에 **10번**
 *     ④ 채우기 400초를 만들려면 `max = moveRate × 400`
 *
 * @property max       저장고 용량. **화면에는 %로만 보인다** — 이 숫자가
 *                     몇인지는 아무 뜻이 없고, **몇 분을 버티나**가 뜻이다
 * @property start     시작. 텅 빈 채로 시작하면 첫 구간에 아무 일도 안 난다
 * @property moveRate  냉각 회로가 초당 옮기는 양 (선체 → 저장고).
 *                     **추진이 내는 열(1.96)보다 조금 커야** 선체가 잡힌다 —
 *                     작으면 냉각을 켜도 선체가 오르고, 그러면 냉각이 장식이다
 * @property dumpRate  라디에이터가 초당 버리는 양 (저장고 → 우주).
 *                     `moveRate` 보다 **세 배쯤** 커야 한다 — 비슷하면
 *                     열어 두어도 안 비워지고, 그러면 열어 둔 채 잊게 된다
 * @property fullAt    이 위로는 **냉각이 안 먹는다.** 1.0 이 아닌 이유:
 *                     딱 100%에서 끊기면 「왜 갑자기 안 되지」가 되고,
 *                     96% 부터 서서히 약해지면 **차 오는 것이 손에 잡힌다**
 * @property warn      이 위로는 계기가 붉어진다
 */
export const SINK = {
  max: 840,
  start: 90,
  // ★ 2.10 → 2.20. **추격이 186초**로 목표(90~180)를 넘겨서 올렸다.
  //   까닭이 재미있다 — 냉각이 추진을 **7%** 로 겨우 이기니 선체가
  //   0.14/초로만 식었고, 그래서 추격 내내 선체가 뜨거워 자국이 안 내려갔다.
  //   「겨우 이긴다」는 뜻은 맞았는데 **너무 겨우**였다.
  //   2.20 이면 12% 여유 → 140초. 2.50(27%)이면 98초로 너무 쉬워진다
  moveRate: 2.20,
  dumpRate: 6.3,
  fullAt: 0.96,
  warn: 0.70,
};

/**
 * ★ **저장고가 차면 선체가 못 식는다** — 얼마나 못 식나.
 *   `fullAt`(96%)에서 1.0 이고 100%에서 0 이 된다. 뚝 끊지 않는 이유는
 *   위 `fullAt` 주석과 같다 — **끊기기 전에 무거워져야** 사람이 눈치챈다
 */
export function coolEfficiency(sink) {
  const t = sink / SINK.max;
  if (t <= SINK.fullAt) return 1;
  return Math.max(0, 1 - (t - SINK.fullAt) / (1 - SINK.fullAt));
}

/** 계기에 뜨는 말 — **숫자가 아니라 「얼마나 남았나」**로 읽혀야 한다 */
export const SINK_WORD = (sink) => {
  const t = sink / SINK.max;
  if (t >= SINK.fullAt) return '가득 — 버려야 한다';
  if (t >= SINK.warn) return '차 온다';
  if (t <= 0.08) return '비었다';
  return '쌓이는 중';
};
