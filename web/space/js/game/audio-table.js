//
//  ★ 떨림과 소리가 같은 표를 읽는다
//    화면 떨림이 2.0초에 돌아오고 소리가 3.15초에 돌아오면, 둘 다 맞는데
//    합쳐 놓으면 어긋난 느낌만 남는다. **위상이 어긋나는 것은 화면으로
//    원인을 못 찾는 종류**라 숫자를 한 곳에 둔다.
//
//  ★ three.js 도 WebAudio 도 안 쓴다 — node 가 브라우저 없이 읽는다.
