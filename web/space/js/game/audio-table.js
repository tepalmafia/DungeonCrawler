/**
 * ★ 뿌리친 직후 3초 — **이 게임에서 제일 기분 좋아야 하는 순간.**
 *
 *   0.00  추격음이 끊긴다 (cut)
 *   0.40  배경이 hush 까지 내려간다 — **평소보다 조용하다.** 이게 핵심이다
 *   0.55  안도의 두 음 (chime). 덕킹을 안 받으므로 **정적 위에 홀로 뜬다**
 *   1.50  그대로 머문다 (hold)
 *   3.15  천천히 돌아온다 (back). 빠르면 「돌아왔다」가 아니라 「끊겼다 이어졌다」다
 *
 *   내려가는 건 빠르고 올라오는 건 느리다. 반대로 하면 안도가 아니라
 *   불안이 된다 — 소리가 슬금슬금 사라지는 건 무언가 다가올 때의 모양이다.
 */
export const ESCAPE = {
  cut: 0.22,
  hush: 0.16, hushAt: 0.40, hold: 1.10, back: 1.65,
  chimeAt: 0.55, chimeGap: 0.40, chimeLen: 1.5,
  chime: [174.6, 261.6],    // F3 → C4. 5도 — 「풀렸다」로 들리는 사이
  /** 이 3초 동안 화면 떨림 배수. **평소보다도 적다** — 손이 떨림을 멈춘다 */
  shake: 0.25,
  /** 총 길이. 떨림·조명이 이 값을 같이 읽는다 */
  get total() { return this.hushAt + this.hold + this.back; },
};

/** 추격 중에는 배가 더 떤다 — 뿌리쳤을 때의 낙차를 만드는 쪽이 이것이다 */
export const SHAKE = { calm: 1, chase: [1.4, 2.6] };

/**
 * 보상 3초의 **모양 하나.** 뿌리친 뒤 t초일 때 0~1 을 준다 —
 * **0 이 제일 조용한 바닥, 1 이 평소.** 크기 자체가 아니라 「어디쯤인가」다.
 *
 * ★ 소리(덕킹)와 떨림이 **이 모양 하나를 같이 읽는다.** 각자 비슷하게
 *   구현해 두면 언젠가 한쪽만 고쳐지고, 그때 나는 어긋남은 화면으로는
 *   원인을 못 찾는다 — 「뭔가 이상한데 뭔지 모르겠다」로만 남는다.
 *   소리 쪽은 이 값을 hush~1 로, 떨림 쪽은 ESCAPE.shake~1 로 펴서 쓴다.
 */
export function envelope(t) {
  const E = ESCAPE;
  if (!(t >= 0)) return 1;
  if (t < E.hushAt) return 1 - t / E.hushAt;
  if (t < E.hushAt + E.hold) return 0;
  if (t < E.total) return (t - E.hushAt - E.hold) / E.back;
  return 1;
}
