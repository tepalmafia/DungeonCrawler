// ══════════════════════════════════════════════════════════════════════════
//  ★★ 우주복 — **진공에 사람이 그냥 서 있었다** (v62 · REAL.md §2-C · §4-C)
//
//  ★ 무엇이 틀렸었나
//    v45 에서 에어록 바깥문을 달면서 **사람은 그대로 뒀다.** 문을 열면
//    그 칸은 진공인데, 안에 선 사람은 우주복 없이 **125초** 동안 윈치를
//    잡고 있었다. 진공에서 사람은 **15초면 의식을 잃는다.**
//
//    그리고 벌이 「배 공기가 준다」였다. **에어록은 배와 격리된 칸**이다 —
//    격리가 안 되면 그건 에어록이 아니라 구멍이다. 배 전체 공기가 줄면
//    문 하나 여는 것이 배 전체를 죽이는 일이 되고, 그러면 아무도 안 연다.
//
//  ★★ 그래서 시계를 **두 개로 가른다**
//
//      | | 무엇의 시계 | 얼마 | 다 되면 |
//      |---|---|---|---|
//      | `LOCK.air` | **에어록 한 칸** | 12초에 빈다 | 진공이다 — 그게 정상이다 |
//      | `SUIT.air` | **등에 진 것** | 5분 | 배가 억지로 끌어들인다 |
//
//    문을 열면 그 칸이 비는 것은 **벌이 아니다.** 벌은 「우주복 없이 열었다」
//    쪽에만 붙는다 (`grace` 4초 뒤 자동으로 닫힌다).
//
//  ★★ **왜 늘 입고 다니지 않나** — 이게 이 표의 핵심이다
//    입는 데 22초가 들고, 입고 있으면 **손이 둔하다**(`handMult`).
//    수리가 거의 두 배로 더디다. 그래서 「나갈 때만 입는다」가 되고,
//    「지금 입어야 하나」가 결심이 된다. 벌이 숫자가 아니라 **못 하게
//    되는 일**로 오는 것이 이 저장소의 규약이다 (물건 들기 · 굶주림과 같다).
//
//  ★ three.js 를 안 쓴다 — tools/space-suit.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const SUIT = {
  /**
   * ★ 입는 데 드는 초 — **잡고 있어야 한다.**
   *
   *   22초는 짧지 않다. 일부러다 — 「멈춰서 캔다」의 진짜 값이 여기 붙는다.
   *   지금까지 채굴은 「에어록에 가서 잡는다」였고 준비가 0초였다.
   *   실제 EVA 준비는 몇 시간이고, 22초는 그것을 게임 길이로 접은 값이다
   *   (③ 일부러 접은 것 · REAL.md §8).
   */
  wearFor: 22,
  /** 벗는 데. 입는 것보다 빠르다 — 실제로도 벗는 쪽이 빠르다 */
  takeOff: 8,

  /**
   * ★ 등에 진 공기 (초). **배 공기와 무관하다** — 그게 우주복이다.
   *
   *   ★ **400 이라고 기획서에 적었다가 재 보고 300 으로 내렸다.**
   *     윈치 한 통이 50초고 한 통에 위험이 26 쌓인다 (`WINCH.riskRise`).
   *     400초면 여덟 통인데, 네 통째에 위험이 100 에 붙으므로 **공기는
   *     한 번도 안 문다.** 안 무는 시계는 계기만 늘리는 것이라 없느니만
   *     못하다. 300 이면 다섯 통 남짓 — **위험이 먼저 오되, 잊으면
   *     공기가 온다.** 그 순서가 맞다: 공기는 「잊었을 때의 벌」이다.
   */
  air: 300,
  /** 이 밑이면 경고한다 (초) — 돌아올 시간은 준다 */
  low: 70,
  /** 배 안에서 초당 이만큼 찬다. 300초를 25초에 — 다시 나가려면 기다린다 */
  refill: 12,

  /**
   * ★★ **장갑이 두껍다** — 입고 있으면 수리가 이만큼만 나아간다.
   *
   *   이 한 칸이 「왜 늘 안 입고 다니나」의 답 전부다. 0.55 면 수리가
   *   거의 두 배로 더디다. 굶주림(`FOOD.handMult` 0.45)과 같은 규약이고,
   *   **몸 상태는 손으로 나온다**(PLAN §5-2)를 안 깬다.
   */
  handMult: 0.55,
  /** 걸음도 둔하다. 크게 안 깎는다 — 방 사이가 늘면 템포가 무너진다 */
  moveMult: 0.86,

  /**
   * ★ **안 입고 열면 몇 초 뒤 배가 억지로 닫나** (칸이 빈 뒤부터).
   *
   *   0 으로 두면 「열자마자 죽는다」라 실수를 배울 수가 없고, 길게 두면
   *   우주복이 장식이 된다. 4초면 **한 번 겪고 배운다.**
   *   죽이지 않는 이유: 이 게임은 죽음으로 가르치지 않는다 — 벌은 늘
   *   **기다림**이다 (`LOCK.lockout` 45초).
   */
  grace: 4,
};

/** 우주복이 지금 무슨 상태인가 — **숫자로 안 띄운다** */
export function suitWord(s) {
  if (s.wearing > 0) return '우주복을 입는 중';
  if (s.doffing > 0) return '우주복을 벗는 중';
  if (!s.on) return '우주복 걸이';
  if (s.air <= 0) return '공기 없음';
  if (s.air <= SUIT.low) return '공기가 얼마 없습니다';
  return '우주복 착용';
}

/** 남은 공기를 분으로 — 계기에만 쓴다 */
export const airMin = (s) => s.air / 60;
