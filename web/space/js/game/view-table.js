const rad = (d) => (d * Math.PI) / 180;

/**
 * ★★★ **설계 눈점 (DEP)** — 앉았을 때 눈이 오는 자리.
 *   `helm-table.js HELM_SEAT` 이 이 값을 읽는다. **두 곳에 적으면 갈라진다.**
 *
 * ★ v66 에서 0.45m 더 앞으로 (−7.85 → −8.30). 유리가 가까울수록 각이 크다
 */
export const DEP = { x: 0, y: 1.20, z: -8.30 };

/** 천장 높이 — `world/ship.js` 의 H 와 같아야 한다 */
export const CEIL = 2.7;

/**
 * ★★★ **비어 있어야 하는 원뿔** — 이 판의 알맹이다.
 *
 *   눈에서 방위각 ±`yaw` 도 · 앙각 `el` 도 위쪽에는 **구조재가 하나도
 *   없어야 한다.** F-16 이 「틀 없는(frameless)」 버블인 이유가 이것이고,
 *   `space-view.js` 가 캐노피·지붕·링 프레임·계기·HUD 를 **전부 모아**
 *   이 원뿔 안에 뭐가 있는지 묻는다.
 *
 * @property yaw 좌우로 몇 도까지 비어야 하나
 * @property el  아래로 몇 도까지 비어야 하나 (음수 = 수평 아래).
 *               **기수 너머 내려다보는 각**과 같은 값이다 — 차양이
 *               이 선에 놓이므로, 두 값을 따로 두면 반드시 갈라진다
 */
export const CLEAR = { yaw: 60, el: -17 };

/**
 * 캐노피가 꺾이는 여섯 점 (x, z). **평면 하나가 아니라 꺾인 띠**다.
 *
 * ★★ **점마다 기둥(멀리언)이 선다.** 그러므로 모든 점은 `CLEAR.yaw` **밖**에
 *   있어야 한다. v65 는 앞 멀리언이 ±1.05 (= 43도) 라 **정면 안쪽**이었다.
 *   ±1.60 이면 61도다 — 겨우 밖이 아니라 확실히 밖으로 민다.
 */
export const CANOPY = [
  [-3.00, -7.55],
  [-2.55, -8.98],
  [-2.05, -9.34],
  [2.05, -9.34],
  [2.55, -8.98],
  [3.00, -7.55],
];

/**
 * 유리의 위아래 끝 (m).
 *
 * ★ **위끝이 천장이다** (v66). v65 까지 2.62 였고 그 위로 「위 선체띠 +
 *   위 창틀」이 있었다 — 즉 **위쪽이 잘려 있었다.** 정면에서는 유리가
 *   천장까지 올라가고, 천장에는 머리 위 창이 뚫려 있으므로 **끊기지
 *   않고 90도까지 이어진다.** 그게 버블이다.
 * ★ 아래끝은 0.58 → 0.45. 옆으로 내려다보는 각(F-16 40도)이 여기서 난다
 */
export const GLASS_Y = { sill: 0.45, head: CEIL };

/**
 * ★★ **눈썹 차양(glareshield)의 윗면** — 여기 위로 밖을 본다.
 *
 *   **손으로 안 적는다.** 앉은 눈에서 `CLEAR.el` 도 아래 · 계기판 거리
 *   만큼 앞. 그래야 「기수 너머 몇 도」와 「차양이 몇 미터」가 절대 안 갈라진다.
 *
 *   v61 까지 이 값이 **1.47** 이었다 — 앉은 눈보다 27cm **위**였고, 그래서
 *   앉으면 눈앞이 계기였다. DEP 로 짓는다는 것은 눈높이만 정하는 것이
 *   아니라 **눈 아래로 계기를 내리는 것**까지다.
 */
export const PANEL_DIST = 0.78;

/**
 * ★★★ **차양은 평평하지 않다 — 「내려다보는 각」이 어디서나 같은 곡면이다.**
 *
 *   처음엔 높이 하나(`BROW_Y`)로 두고 계기판을 그 높이로 쭉 둘렀다.
 *   그랬더니 **바깥쪽이 눈에는 더 높아 보였다** — 같은 높이라도 멀면
 *   내려다보는 각이 얕아지기 때문이다 (`atan(dy/거리)`). 검사가
 *   「계기판 0·1·3·4 가 원뿔을 막는다」로 잡아 줬다.
 *
 *   실제 조종석의 차양이 **좌우로 갈수록 뚝 떨어지고** 옆 콘솔이
 *   낮은 이유가 정확히 이것이다. 그래서 높이를 자리마다 계산한다 —
 *   **어디서 봐도 딱 17도 아래**가 되게.
 */
export const browAt = (x, z) => +(DEP.y
  - Math.hypot(x - DEP.x, z - DEP.z) * Math.tan(rad(-CLEAR.el))).toFixed(3);

/** 한 숫자가 필요할 때 쓰는 값 — **정면 한복판**의 차양 높이 */
export const BROW_Y = browAt(0, DEP.z - PANEL_DIST);

/**
 * ★ 계기판 한 칸이 **올라올 수 있는 제일 높은 높이.**
 *   칸의 네 귀퉁이 중 **제일 낮게 나오는 값**을 쓴다 — 가운데로 재면
 *   귀퉁이가 원뿔을 뚫는다 (검사가 그걸로 두 번 잡았다)
 */
export const PANEL_PAD = 0.22;
export const browSeg = (a, b) => Math.min(
  browAt(a[0], a[1] - PANEL_PAD), browAt(b[0], b[1] - PANEL_PAD),
);

/**
 * 계기판이 그리는 호. **충돌도 이 값을 읽는다** — 두 곳에 적으면 갈라진다.
 *
 * ★★ **가운데 칸(±0.45)은 비운다.** 조종간이 그 앞에 서 있고 HUD 가 그
 *   위에 뜬다 — F-15 · F-22 · Su-27 이 가운데 조종간을 쓰면서 계기판을
 *   좌우로 가르는 이유가 정확히 이것이다. 화면을 여기 박으면 **조종간
 *   그림자에 가려** 절반이 안 읽힌다 (재 보니 0.41m 폭이 가린다).
 *
 * ★ 타원 호다 — 앞뒤 반지름 `PANEL_DIST`, 좌우 반지름 2.40
 */
const panelZ = (x) => +(DEP.z - PANEL_DIST * Math.sqrt(Math.max(0, 1 - (x / 2.20) ** 2))).toFixed(3);
export const CONSOLE_PTS = [-1.55, -0.95, -0.34, 0.34, 0.95, 1.55].map((x) => [x, panelZ(x)]);

/** ★ 화면을 안 다는 칸 — 가운데. `world/cockpit.js` 가 읽는다 */
export const PANEL_GAP = 2;

/**
 * ★★ **계기판이 좁아졌다** (v66 · ±2.30 → ±1.55).
 *
 *   실제 전투기의 주계기판은 **폭 0.5m 남짓**이다 (F-16 은 125mm MFD 셋).
 *   우리 것은 4.6m 였다 — 방 전체를 두른 계기판이라 「우주선」이 아니라
 *   「관제실」이었고, 무엇보다 **바깥쪽이 시야를 먹고 있었다.**
 *   좁히고, 남는 좌우는 **옆 콘솔**(낮다)이 맡는다 — 스로틀이 그리로 간다.
 */

/** 대시 얼굴의 높이 (차양 아래로 이만큼) — **자리마다 위끝이 다르다** */
export const FACE_H = 0.44;
/** 대시 얼굴의 가운데 높이 — 한 숫자가 필요할 때 */
export const DASH_Y = +(BROW_Y - FACE_H / 2).toFixed(3);
/** 스위치 선반 — 대시 아래. **항로 갈래 판이 여기 앉는다** */
