// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **탄두** — 이 게임의 목적 (v71 · docs/space/WAR.md §3·§4)
//
//  ★ 사장님: 「적을 뚫고 가면서 여기저기에 흩어져있는 **핵탄두 재료를
//            모아서 적 행성에 투하**하는게 목적이야 …
