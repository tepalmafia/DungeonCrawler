//  ══ ★★ 왜 기관실인가 ═════════════════════════════════════════════════
//
//  기관실이 `z 10~16` 으로 **배의 제일 뒤**다 (조종석 −9). 새 방을 안
//  만들고 **후미 격벽에 크레이들**을 단다 — 방이 늘면 왕복이 길어지고,
//  왕복이 길어지면 전투 중심이 안 된다.
//
//  ★★★ 그리고 거기가 **제일 좋은 자리**다. 기관실은 **열의 심장**이다:
//    추진을 켜면 이 방이 제일 뜨겁고, 냉각이 고장 나면 여기부터 오른다.
//    거기에 탄두를 두면 —
//
//        **추진을 켤 때마다 탄두가 데워진다.**
//
//    「빨리 가고 싶다 ↔ 탄두를 식혀야 한다」가 **매 순간** 생긴다.
//    방을 하나도 안 늘리고 긴장 하나를 얻는다. v58 의 열 계통이 그대로
//    값을 한다 — 새 계통을 만드는 것이 아니라 **있던 것에 얹는 것**이다.
//
//  ══ ★ 다섯 칸이 곧 진행도 ═══════════════════════════════════════════════
//
//    재료를 얻으면 **손에 들고 기관실까지 걸어가** 꽂는다 (`carry.js` 규약).
//    꽂히면 칸에 불이 들어온다 — **진행도를 글로 안 알려준다.**
//    다섯이 다 차면 탄두가 살아나고, 그때부터 무장 절차가 열린다.
//
//  ★ three.js 를 안 쓴다 — `tools/space-head.js` 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

