/** 한 손에 이보다 많이 몰리면 「배치가 아니라 시험」이다 */
export const HAND_MAX = 3;

/**
 * ★★★ **톡과 꾹을 가르는 시간** (초).
 *
 *   ★ 0.22 로 잡았다. 근거:
 *     · 사람이 「눌렀다 뗀다」를 하는 시간이 보통 **0.08~0.15초**다
 *       (타자 치는 손). 그러니 0.22 면 톡이 꾹으로 새지 않는다
 *     · 반대로 「밀고 싶다」고 마음먹고 누르면 **0.3초 안에는 안 뗀다**
 *     · 급가속이 `BOOST.fade` 2.6초짜리라 0.22초는 그 **8%** 다 —
 *       밀리는 느낌이 늦었다고 느낄 자리가 아니다
 *   ★★ 0.35 로도 재 봤는데, 그때는 「짧게 밀고 싶은」 0.3초짜리 조정이
 *     통째로 톡으로 먹혔다. 그건 급가속을 못 쓰게 만드는 값이다
 */
export const TAP = { hold: 0.22 };

/**
 * ★★ **한 걸음** — 누름 상태에서 「톡인가 꾹인가」를 낸다.
 *
 *   ★ 시계를 여기서 든다. 게임이 제 방식으로 또 세면 재는 곳이 둘이 된다
 *
 * @param st   { t, fired, was } — 처음엔 `makeTap()`
 * @param down 지금 눌려 있나
 * @returns { tap, rush } — `tap` 은 **뗄 때 한 번**, `rush` 는 **누르는 동안**
 */
export const makeTap = () => ({ t: 0, fired: false, was: false });

export function tapStep(st, down, dt) {
  let tap = false;
  if (down) {
    st.t += dt;
    // 넘기는 순간부터 「꾹」이다 — 떼는 것을 안 기다린다.
    // ★ 기다리면 밀기가 손을 뗀 뒤에 시작해서 「먹통」으로 읽힌다
    if (st.t >= TAP.hold) st.fired = true;
  } else {
    // 뗐다 — 넘긴 적이 없으면 **톡**이다
    if (st.was && !st.fired) tap = true;
    st.t = 0; st.fired = false;
  }
  st.was = down;
  return { tap, rush: down && st.fired };
}

