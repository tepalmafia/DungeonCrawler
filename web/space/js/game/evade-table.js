/** 탄이 나는 총 시간 — 새 숫자를 안 만든다 */
export const FLY = ENEMY_FIRE.fly;
/** 빗나가려면 쌓을 양 — 새 숫자를 안 만든다 */
export const NEED = DODGE.need;

/**
 * 지금이 창 안인가 (`left` = 닿기까지 남은 초).
 * @param wide ★★ v115 — **「반사」 특성이 창을 넓힌다** (`growth-table.js`).
 *   양쪽으로 벌린다 — 한쪽만 벌리면 「늦게 꺾어도 된다」나 「일찍 꺾어도
 *   된다」 한쪽만 되어 특성의 뜻이 반쪽이 된다
 */
export const inWindow = (left, wide = 0) =>
  left >= EVADE.window[0] - wide / 2 && left <= EVADE.window[1] + wide / 2;
/** 지금이 완벽한 자리인가 */
export const isPerfect = (left) => left >= EVADE.perfect[0] && left <= EVADE.perfect[1];

/**
 * ★★★ **이번 걸음에 얼마나 쌓나.**
 *
 * @param left  닿기까지 남은 초
 * @param push  옆으로 민 양 0~1 (마우스 · `evadeGain` 이 이미 잰 값)
 * @param roll  굴린 양 0~1 (Q/E)
 * @param burst 급기동인가
 * @returns 초당 쌓이는 양
 */
export function gainAt(left, { push = 0, roll = 0, burst = false, burstMult = 2.4, wide = 0 } = {}) {
  const win = inWindow(left, wide);
  const per = isPerfect(left);
  const k = per ? EVADE.perfectMult : (win ? EVADE.mult : 1);
  // ══ ★★★ **배수는 굴리기에만 준다** ═══════════════════════════════════
  //
  //  ★ 처음에 밀기에도 배수를 줬다가 태웠다. 그러면 **끝까지 밀고만 있어도**
  //    1.33 이 쌓여 빗나가고, v84 가 세운 저울(「조종간만으로는 못 피한다.
  //    급기동을 써야 하고 급기동은 추진제를 태운다」)이 **조용히 죽는다.**
  //    새 계통을 얹으면서 옛 계통을 깨뜨리는 것이 이 저장소가 제일 자주
  //    밟는 함정이다 (v107 이 전투력을 갈아엎으며 옛 칸을 남긴 것과 같다).
  //
  //  ★★ 그리고 이 편이 뜻도 맞는다: **밀기는 「얼마나」, 굴리기는 「언제」**다.
  //    밀기에 타이밍 배수를 주면 둘이 같은 물건이 된다
  let g = push;
  g += roll * (win ? EVADE.roll * k : EVADE.rollOutside);
  return g * (burst ? burstMult : 1);
}

/** 쌓인 양으로 빗나가나 */
export const missed = (got) => got >= NEED;

/**
 * ★★ **못 피했을 때 피해가 얼마나 주나** (0~1 배수).
 *   쌓은 만큼 준다 — 다 못 채워도 헛일이 아니다
 */
export const hurtMult = (got) =>
  Math.max(1 - EVADE.soften, 1 - EVADE.soften * Math.min(1, got / NEED));

/**
 * ★★★ **고리** — 화면이 타이밍을 말하는 방법 (사장님 「타이밍을 어떻게 줄지」).
 *
 *   ★ 숫자를 띄우면 안 읽힌다. **줄어드는 고리**가 표적 표시에 닿는 순간이
 *     「지금」이다 — 리듬 게임이 다 쓰는 것이고, 눈이 그것을 잘 읽는다.
 *
 * @returns { r, band } r 은 고리 반지름 배수(1 → 크다 · 0 → 붙었다),
 *                      band 는 'wait' | 'now' | 'perfect' | 'late'
 */
export function ringAt(left, wide = 0) {
  const r = Math.max(0, Math.min(1, left / EVADE.ringFrom));
  const band = isPerfect(left) ? 'perfect'
    : (inWindow(left, wide) ? 'now' : (left > EVADE.window[1] + wide / 2 ? 'wait' : 'late'));
  return { r, band };
}

