/**
 * 조준선 이름을 가르침의 `at` 으로 줄인다.
 * ★ 이름이 제각각이라 여기서 한 번 접는다 — `chart0`·`panel:workshop` 은
 *   뒤가 붙고, 차단기는 아예 회로 이름(`thrust`)으로 온다.
 *   **접는 자리를 한 곳으로 몰아 둔다.** 안 그러면 가르침마다 이름을 알아야
 *   하고, 조준선 이름이 바뀌면 조용히 안 뜨게 된다.
 */
const BREAKERS = new Set(['thrust', 'cool', 'sensor']);
export function aimKind(aim) {
  if (!aim) return null;
  const s = String(aim);
  if (s.startsWith('chart')) return 'chart';
  if (s.startsWith('panel')) return 'panel';
  if (BREAKERS.has(s)) return 'breaker';
  return s;
}
