  // 엔진 진동. **너무 크면 멀미가 난다.** 1인칭에서 화면 흔들림은
  // 조금만 넘겨도 못 하는 게임이 된다 — 눈에 겨우 보이는 정도로 둔다.
  shake: 0.0035,    // 흔들리는 폭 (유닛)
