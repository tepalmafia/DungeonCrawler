//  ★ 사장님 (2026-08-13) 「**앞으로 이동은 기본 베이스로 하고 가속화는
//    스테미나 방식으로 해서 사용할 수 있도록 해줘. 엔진 과열이 되서 속도가
//    느려진다는 컨셉으로**」
//
//  ══ 지금까지는 **스로틀이 0 에서 시작했다** ═══════════════════════════
//
//  `throttle-table.js` 는 −0.45 ~ 1 짜리 축이고 가운데가 0 이다. 즉 켜면
//  배가 **서 있고**, W 를 눌러야 나아갔다. 그런데 이 게임의 목적 한 줄은
//  **「뚫는다 · 채운다 · 떨군다」**이고, 뚫는 것은 **가고 있는 것**이 전제다.
//  서 있는 것이 기본이면 매 회차 첫 동작이 「출발」이 되고, 그건 여정이
//  아니라 시동이다.
//
//  ★★★ 그래서 **가운데가 순항**이다 (`base`). 내리면 늦추고 더 내리면
//    역추진이다 — v101 에 사장님이 만들라고 하신 역추진은 그대로 산다.
//    바뀌는 것은 **「아무것도 안 하면 어떻게 되나」** 하나다.
//
//  ══ ★★★ 가속은 **쓰면 주는 것**이다 ══════════════════════════════════
//
//  급가속은 여태 추진제만 먹었다 (`BOOST.fuel`). 추진제는 회차 단위로
//  천천히 주는 값이라 **지금 이 순간의 결심**이 안 된다 — 「지금 태울까」가
//  안 생긴다.
//
//  ★★ 스태미나는 **초 단위로** 준다. 그래서 「여기서 태우면 다음 모퉁이에
//    못 태운다」가 성립하고, 그게 사장님이 말씀하신 「스태미나 방식」이다.
//
//  ★★★ 그리고 **바닥나는 벌이 「못 쓴다」가 아니라 「느려진다」**이다 —
//    사장님 「엔진 과열이 되서 속도가 느려진다는 컨셉으로」.
//    못 쓰게만 막으면 그건 회색 단추이고, 느려지면 **몰던 방식이 다음
//    구간에 남는다.** 이 저장소가 영구 손상(v?)에서 쓴 것과 같은 규약이다.
// ══════════════════════════════════════════════════════════════════════════

export const DRIVE = {
  /**
   * ★★★ **아무것도 안 하면 이만큼 간다** (스로틀 0~1).
   *   0.38 — 「가고 있다」로 읽히되 전투에서 몰아붙이기에는 모자란 값이다.
   *   1 로 두면 스로틀이 할 일이 없어지고, 0 이면 매 회차가 시동으로 시작한다
   */
  base: 0.38,
  /**
   * ★★ **가속 여력** (0~1). 초 단위로 준다 — 그래야 「지금 태울까」가 된다
   *
   *  @property drain 급가속 중 초당 주는 양 (1 이면 2.4초에 바닥)
   *  @property regen 안 쓸 때 초당 차는 양 (바닥에서 다 차는 데 6.7초)
   *  @property floor 이보다 적으면 **못 태운다** — 0 이면 톡톡 끊어 쓴다
   */
  stam: { drain: 0.42, regen: 0.15, floor: 0.12 },
  /**
   * ★★★ **과열** — 여기가 사장님 말씀의 알맹이다.
   *
   *  @property from  열이 이 몫(0~1)을 넘으면 최대 속도가 깎이기 시작한다
   *  @property cap   완전히 과열됐을 때의 최대 스로틀 — **0 이 아니다.**
   *                  0 이면 멈춰서 식기를 기다리는 게임이 되고, 그건 벌이
   *                  아니라 정지다. 느리게라도 **가고는 있어야** 한다
   *  @property boostHeat 급가속 1초가 올리는 열 (0~1 몫)
   */
  over: { from: 0.72, cap: 0.45, boostHeat: 0.085 },
  what: '전진이 기본 · 가속은 스태미나 · 과열되면 느려진다',
};

/** 처음 상태 */
export const makeDrive = () => ({
  /** 가속 여력 (0~1) */
  stam: 1,
  /** 지금 급가속 중인가 */
  boosting: false,
  /** 과열로 깎인 몫 (0 없음 ~ 1 완전) — 계기가 읽는다 */
  over: 0,
});

/**
 * ★★★ **열이 이만큼이면 최대 스로틀이 얼마인가.**
 *
 *   ★ 게임도 검사도 이 함수 하나를 부른다. 계통이 제 방식으로 다시 재면
 *     「계기는 70%인데 배는 100%로 간다」가 난다
 * @param heat01 열이 찬 몫 (0~1)
 */
export function capOf(heat01) {
  const k = Math.max(0, Math.min(1, (heat01 - DRIVE.over.from) / (1 - DRIVE.over.from)));
  return { cap: 1 + (DRIVE.over.cap - 1) * k, over: +k.toFixed(3) };
}

/**
 * ★★★ **한 프레임.**
 *
 * @param want    사람이 밀어 둔 스로틀 (−0.45~1). **기본은 `DRIVE.base`**
 * @param boost   급가속 키를 누르고 있나
 * @param heat01  열이 찬 몫 (0~1)
 * @returns `{ throttle, cap, stam, over, boosting, heatAdd }`
 */
export function stepDrive(d, dt, { want = DRIVE.base, boost = false, heat01 = 0 } = {}) {
  // ── 여력: 태우면 줄고, 안 태우면 찬다 ────────────────────────
  //  ★ **바닥에서는 못 켠다.** 그래야 「아껴 뒀다 한 번에」가 성립한다
  const can = boost && d.stam > (d.boosting ? 0 : DRIVE.stam.floor);
  d.boosting = can;
  d.stam = can
    ? Math.max(0, d.stam - DRIVE.stam.drain * dt)
    : Math.min(1, d.stam + DRIVE.stam.regen * dt);

  // ── 과열: 열이 넘으면 최대 속도가 깎인다 ─────────────────────
  const { cap, over } = capOf(heat01);
  d.over = over;

  // ★ 뒤로 가는 것은 안 깎는다 — 과열은 **밀어붙이는 것**을 막는 것이지
  //   물러나는 것을 막는 것이 아니다. 막으면 갇힌다
  const throttle = want > 0 ? Math.min(want, cap) : want;
  return {
    throttle: +throttle.toFixed(4),
    cap: +cap.toFixed(3),
    stam: +d.stam.toFixed(3),
    over,
    boosting: can,
    /** 이 프레임에 오르는 열 몫 — 열 계통이 더한다 */
    heatAdd: can ? DRIVE.over.boostHeat * dt : 0,
  };
}

/** 사람이 읽는 한 줄 — 계기가 쓴다 */
export function driveWord(s) {
  if (s.over >= 0.99) return '과열 — 최대 속도가 절반입니다';
  if (s.over > 0.02) return `과열 시작 — 최대 ${Math.round(s.cap * 100)}%`;
  if (s.boosting) return `급가속 — 여력 ${Math.round(s.stam * 100)}%`;
  if (s.stam < 0.35) return `여력 ${Math.round(s.stam * 100)}% — 차는 중`;
  return '순항';
}
