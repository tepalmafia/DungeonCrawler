// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **급가속** — 쫓아 붙는다 (v73 · docs/space/BFM.md)
//
//  ★ 사장님: 「**급가속을 해서 적을 쫓을 때는 빛무리가 쏟아져오거나
//             속도감이 느껴지도록** 만들어야해. **급가속 조작은 따로** 하도록」
//
//  ══ 왜 따로인가 ═══════════════════════════════════════════════════════
//
//  급기동(Shift)은 **기수를 돌리는** 것이고, 급가속은 **앞으로 튀어나가는**
//  것이다. 둘은 다른 일이다 — 공중전에서도 「각을 만드는 것」과
//  「따라잡는 것」은 다른 결심이고, 하나로 묶으면 고를 것이 없어진다.
//
//      Shift  급기동 — 기수를 2.4배 빨리 돌린다 (추력기)
//      ★ R    **급가속** — 앞으로 밀어붙인다 (주엔진)
//
//  ══ ★★ 고증 — 우주에서 「급가속」이 무엇인가 ═══════════════════════════
//
//  비행기의 애프터버너는 연료를 배로 태워 추력을 올린다. 우주선도 같다 —
//  다만 **공기 저항이 없으므로 속도가 안 떨어진다.** 즉 한 번 밀면
//  **계속 빨라지고**, 멈추려면 반대로 태워야 한다.
//
//  ★ 그래서 게임에서는 **「밟는 동안만」**으로 둔다. 계속 빨라지게 두면
//    2시간 뒤 배가 광속으로 가고, 그건 재미가 아니라 버그로 보인다.
//    대신 **놓으면 서서히 줄어든다** — 관성으로 미끄러지는 느낌.
//
//  ══ ★★★ 값 셋 — 공짜면 늘 밟는 것이 답이다 ═══════════════════════════
//
//      ① **추진제**를 크게 태운다
//      ② **열**이 오른다 — 주엔진을 세게 물면 뜨겁다 (v58 열 계통)
//      ③ **자국**이 커진다 — 밝게 타는 것은 멀리서도 보인다
//
//    셋 다 이미 있는 축이다. **새 자원을 안 만든다.**
//
//  ★ three.js 를 안 쓴다 — `tools/space-boost.js` 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

