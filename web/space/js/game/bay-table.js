/**
 * 방 이름의 **두 글자 접두.** 세 글자를 넘기면 랙 앞판에서 안 읽힌다
 * (0.9m 짜리 판에 「에어록 3」은 글자가 뭉갠다).
 */
export const PREFIX = {
  cockpit: '조종',
  spine: '통로',
  observ: '관측',
  workshop: '정비',
  garden: '온실',
  airlock: '에어',
  engine: '기관',
};

/** 점검 패널이 갖는 번호. **일곱 방 전부 같다** — 그래야 규칙이 된다 */
export const PANEL_BAY = 1;

/** 랙은 2번부터. 1번은 패널 몫이다 */
export const FIRST_RACK = 2;

/**
 * 베이 하나의 이름. `bay('engine', 3)` → `'기관 3'`
 *
 * ★ 번호를 두 자리로 안 채운다(`03`). 실제 배는 채우지만, 여기서는
 *   **소리 내어 부르는 것**이 목적이라 「기관 삼」이 짧아야 한다.
 */
export function bay(room, n) {
  const p = PREFIX[room];
  if (!p) return null;
  return `${p} ${n}`;
}

/**
 * 그 방의 베이 번호를 **한 벌로** 만든다 — 패널 1번 + 랙 n개.
 * 세상(`world/ship.js`)과 검사(`tools/space-bay.js`)가 **같은 것**을
 * 읽어야 한다. 두 곳에 적으면 반드시 갈라진다 (CLAUDE.md).
 */
export function bays(room, rackCount) {
  const out = [{ n: PANEL_BAY, text: bay(room, PANEL_BAY), kind: 'panel' }];
  for (let i = 0; i < rackCount; i++) {
    const n = FIRST_RACK + i;
    out.push({ n, text: bay(room, n), kind: 'rack' });
  }
  return out;
}

/**
 * 번호가 **읽히는 크기**인가. 랙 앞판은 폭 0.9m 이고 사람은 보통
 * 1.5~3m 앞에 선다. 글자 높이가 이보다 작으면 「번호가 있긴 하다」로
 * 끝나고, 그건 안 붙인 것과 같다.
 *
 * ★ 이 숫자는 눈대중이 아니다. 사람 눈이 글자를 알아보는 한계가
 *   시야각 **약 5분(0.083도)** 이고, 편하게 읽으려면 그 서너 배는 있어야
 *   한다. 3m 앞에서 0.25도면 높이 **1.3cm** — 그 두 배를 잡았다.
 */
export const PLATE = {
  /** 글자 높이 (m) */
  glyph: 0.075,
  /** 판 크기 (m) — 글자가 판에 꽉 차면 못 읽는다 */
  w: 0.34,
  h: 0.11,
  /** 이 거리까지는 읽혀야 한다 (m) */
  readAt: 3.2,
};
