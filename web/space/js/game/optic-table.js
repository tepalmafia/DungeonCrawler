// ══════════════════════════════════════════════════════════════════════════
//  광학 창 — **당겨서 본다. 그리고 부서지는 것을 본다** (v79)
//
//  ★ 사장님 「멀리있는 적을 레이더 말고 **확대**하거나 그럴 방법은 없어?」
//    「**격추시 적 기체가 부서지는 화면**도 보여주고. 화면 상단이나 시야에
//     방해되지 않는 곳에. **3D 모습**으로」
//
//  ★★ **두 요구가 같은 기계다.** 당겨 보는 것과 격추 장면을 보여 주는 것은
//    둘 다 「**두 번째 카메라가 찍은 그림을 작은 판에 띄운다**」이다.
//    따로 지으면 판이 둘, 카메라가 둘, 자리 다툼이 하나 는다. 하나만 짓고
//    **평소에는 표적을 비추고, 격추 순간에 그 자리에 머문다.**
//
//  ── 왜 필요한가 (v79 에 재고 시작했다) ─────────────────────────────
//
//  조종간을 잡으면 화각이 **세로 94도**로 넓어진다 (`helm-table.js FLY_VIEW`).
//  1920 폭에서 가로 125도 · **15.4 화소/도**다. 그 자로 재면:
//
//    | 종류   | 40m      | 90m      | 140m(사거리 끝) | 220m(나는 자리) |
//    |--------|----------|----------|-----------------|-----------------|
//    | 요격기 | 2.06도 32px | 0.92도 14px | 0.59도 **9px** | 0.38도 **6px** |
//    | 포함   | 3.67도 56px | 1.63도 25px | 1.05도 16px    | 0.67도 10px    |
//    | 무인기 | 1.60도 25px | 0.71도 11px | 0.46도 **7px** | 0.29도 **4px** |
//
//  존슨 기준으로 **탐지 2px · 인식 8px · 식별 13px**이다. 즉 사거리 끝의
//  요격기(9px)는 **「뭔가 있다」까지만** 되고 「무엇인가」가 안 된다.
//  모양을 읽으려면 40px 은 있어야 하고, 그건 **4.4배**다.
//
//  ★ v79 ① 의 각지름 바닥(`target-table.js SEEN`)은 **점이 안 되게** 한
//    것이지 **읽히게** 한 것이 아니다. 둘은 다른 일이다 — 바닥은 「저기
//    있다」를 만들고, 이 창은 「저것이 요격기다」를 만든다.
//
//  ── 공짜가 아니어야 한다 ────────────────────────────────────────
//
//  이 저장소가 계통마다 묻는 것이 있다 — **「늘 켜는 게 답이면 선택이
//  아니다」** (`space-run.js` 의 달리기, `space-fuel.js` 의 추진제).
//  당겨 보는 것도 늘 당겨 놓는 것이 답이면 그냥 화각을 좁힌 것과 같다.
//
//  값은 **떨림**으로 치른다. 배율 M 으로 보면 각속도도 M 배로 보인다 —
//  실제 망원 렌즈가 그렇다(초점거리가 길수록 손떨림이 커 보인다). 그래서
//  **기동 중에는 높은 배율이 안 읽힌다.** 뚫고 들어가기 전에 멈춰서 보고,
//  붙은 다음에는 창밖과 조준경으로 싸운다 — 그 순서가 이 게임의 순서다.
//
//  ★ 스텔스는 안 깬다. 광학은 **수동**이다 (안 쏘고 받기만 한다). 능동
//    레이더를 끄고도 이 창은 산다 — 그게 이 창이 레이더의 대안인 이유다.
//
//  ★ three.js 를 안 쓴다.
// ══════════════════════════════════════════════════════════════════════════

import { WEAPONS } from './combat-table.js';
import { KINDS } from './target-table.js';
import { mightOf, lootOf } from './might-table.js';

/** 조종 중 화각 (세로 도) — `helm-table.js FLY_VIEW.fov` 와 같은 값이다.
 *  ★ 두 곳에 적는 것이 아니라 **여기서만 계산에 쓴다** (표시용). 실제
 *    카메라 화각은 저쪽이 정한다 */
export const WIDE_FOV = 94;

export const OPTIC = {
  /**
   * 판의 **광학 기준** 가로세로 (화소).
   * ★ 이 값은 배율 계산의 기준이다 (`fovOf`) — 그림의 해상도가 아니다.
   *   둘을 같은 숫자로 두면 「선명하게 하려고 해상도를 올렸더니 배율이
   *   바뀌는」 일이 난다. 해상도는 `rtScale` 이 따로 든다
   */
  w: 420,
  h: 300,
  /** 그림은 이만큼 더 촘촘히 그린다 — 화면 가득 켰을 때 흐리지 않게 */
  rtScale: 2,

  /**
   * ★★★ **저절로 당긴다** (사장님 2026-08-09 「적을 **거리에 맞게 자동
   *   확대**되고 스크린에는 **거리가 표시**되도록」).
   *
   *   손으로 배율을 돌리게 하면 그건 일이 하나 는 것이다. 이 게임에서
   *   사람 손은 이미 조종간·무기·차단기로 꽉 차 있다. **거리는 기계가
   *   아는 값**이므로 기계가 맞춘다 — 사람은 **보고 정하기만** 한다.
   *
   *   표적이 판 높이의 이만큼으로 보이게 맞춘다 (0~1)
   */
  want: 0.25,

  /**
   * ★★ **무한정은 아니다** (사장님 「무한정 확대는 아니고 **미사일이나
   *   탄두에 따라 그 확대가 결정됨**」).
   *
   *   ★★★ 한도를 **무기의 사거리에서 뽑는다.** 손으로 적지 않는 이유는
   *     늘 같다 — 사거리를 고치면 배율도 따라와야 하는데, 두 곳에 적으면
   *     한쪽만 고쳐진다. 그리고 이 규칙은 **말이 된다**:
   *     **당길 수 있는 만큼이 쏠 수 있는 만큼**이다. 조준경은 무기에
   *     딸린 것이지 창문이 아니다 — 실제 조준 포드도 탄의 탐색기와
   *     묶여 있다.
   *
   *   사거리 이만큼마다 1배 (레이저 90m → 4배 · 열추적 120m → 5배 ·
   *   유도탄 240m → 11배)
   */
  perRange: 22,
  capMin: 2,
  capMax: 12,

  /**
   * ★★ **떨림 한계** — `배율 × 조종입력` 이 이 값이면 아주 흐리다.
   *
   *   ★ 배율과 입력을 **곱한다.** 처음엔 분모에도 배율을 넣었더니
   *     4배와 11배의 흐림이 0.48 대 0.65 로 거의 같았다 — 그러면
   *     「높이 당기면 못 본다」가 성립하지 않는다. 실제 망원 광학은
   *     **각속도가 배율만큼 커 보인다**, 그냥 곱이 맞다.
   *
   *   조종 입력(pitch·yaw·roll 절댓값의 합, 0~약 3)을 그대로 쓴다.
   *   각속도를 쓰지 않는 이유: 각속도는 three 쪽 계산이라 표가 못 읽는다.
   *   **입력은 순수한 숫자**라 `tools/space-optic.js` 가 브라우저 없이 잰다
   */
  shake: 3.0,

  /** 흐림이 이 값을 넘으면 **못 읽는다**로 친다 (0~1) */
  blind: 0.72,

  /** 격추 장면을 이만큼 비춘다 (초) */
  replay: 2.6,

  /**
   * ★★ **격추 되감기 동안의 배율** — 자동에 맡기지 않는다.
   *
   *   처음엔 되감기 중에도 `autoZoom` 을 그대로 썼더니, 격추한 자리가
   *   가까워서 **4배로 당긴 채 폭발 한가운데**를 비췄다 — 화면이 통째로
   *   하얀 덩어리가 되어 **무엇이 부서졌는지 안 보였다.** 격추 화면을
   *   만든 뜻이 정확히 그 반대다.
   *
   *   ★ 낮게 잡아 **잔해와 튄 조각이 같이 들어오게** 한다
   */
  killZoom: 1.8,

  /** 이 거리 밖은 광학으로도 안 잡는다 (m) */
  reach: 400,

  /** 배율이 이 속도로 따라간다 (초당 배) — 툭 바뀌면 렌즈가 아니라 스위치다 */
  ramp: 6.0,
};

/**
 * ★★★ **배율은 「맨눈보다 몇 배 크게 보이나」다** — 카메라 화각의 비가 아니다.
 *
 *   처음엔 화각을 M 으로 나눠서 배율을 정했다. 재 보니 **11배가 실제로는
 *   1.85배**였다. 판이 화면보다 작기 때문이다:
 *
 *     맨눈   1080화소 / 94도  = 11.5 화소/도
 *     판     300화소 / 11.1도 = 27.0 화소/도   ← 「11배」로 당긴 것
 *
 *   즉 **작은 판에 좁은 화각을 넣으면 배율이 판 크기에 먹힌다.** 「11배로
 *   당겼는데 창밖과 별로 다르지 않다」가 그 상태다 — 이 저장소가 늘
 *   겪는 「고쳤는데 화면이 그대로다」의 한 종류다.
 *
 *   ★ 그래서 **배율을 사람이 뜻하는 대로** 정의한다: 배율 M 이면
 *     **판에서 M 배 크게 보인다.** 판의 화각은 거기서 거꾸로 나온다.
 *
 *   ★ 기준 화면 높이 1080 을 쓴다. 창을 키우면 맨눈 쪽도 같이 커지므로
 *     비는 거의 안 변한다 — 한 숫자로 잡아 두는 편이 표를 순수하게 둔다
 */
export const REF_H = 1080;

export function fovOf(step) {
  const m = Math.max(0.05, step || 1);
  return (OPTIC.h * WIDE_FOV) / (m * REF_H);
}

/** ★ 이 무기로는 몇 배까지 당기나 — **사거리에서 뽑는다** */
export function capOf(weaponKey) {
  const w = WEAPONS[weaponKey];
  const r = w?.rMax ?? 90;
  return Math.max(OPTIC.capMin, Math.min(OPTIC.capMax, Math.round(r / OPTIC.perRange)));
}

/** 실제 크기 (m) — 화면에 세우는 크기와 **같은 식**을 쓴다 (`targets.js`) */
export const sizeOf = (kind) => (KINDS[kind]?.size ?? 1) * 1.6;

/**
 * ★★★ **이 거리면 몇 배로 당기나** — 자동.
 * @returns 1 ~ capOf(weapon)
 */
export function autoZoom(kind, dist, weaponKey) {
  const cap = capOf(weaponKey);
  const s = sizeOf(kind);
  const d = Math.max(1, dist || 1);
  const deg = 2 * Math.atan(s / 2 / d) * 180 / Math.PI;
  // 판 높이의 `want` 만큼으로 보이려면 판 화각이 deg/want 여야 한다
  const wantFov = Math.max(0.2, deg / OPTIC.want);
  return +Math.max(1, Math.min(cap, (OPTIC.h * WIDE_FOV) / (wantFov * REF_H))).toFixed(2);
}

/** 이 거리의 이 크기가 판에서 몇 화소로 보이나 */
export function pixelsOf(kind, dist, step) {
  const deg = 2 * Math.atan(sizeOf(kind) / 2 / Math.max(1, dist)) * 180 / Math.PI;
  return +(deg * (OPTIC.h / fovOf(step))).toFixed(0);
}

/**
 * ★★ **흐림** (0~1). 배율이 높을수록, 많이 밀수록 흐리다.
 * @param push 조종 입력의 세기 (|pitch|+|yaw|+|roll|)
 */
export function blurOf(step, push) {
  const m = Math.max(1, step || 1);
  return Math.max(0, Math.min(1, (Math.abs(push || 0) * m) / OPTIC.shake));
}

/** 지금 읽히나 — 흐림이 한계 아래인가 */
export const readable = (step, push) => blurOf(step, push) < OPTIC.blind;

/**
 * ★★★ **판에 무엇을 적나** — 종류마다 다른 것을 묻는다.
 *
 *   사장님 「**우주쓰레기면 필요한 재료나 음식이 있는지, 행성이면 재료가
 *   있는지** 등」. 즉 이 창은 「무엇인가」가 아니라 **「나에게 무엇인가」**를
 *   말해야 한다. 적이면 전투력, 쓰레기면 든 것, 노획이면 얼마나 느나.
 *
 *   ★ 이름을 안 붙인 종류는 **아무 줄도 안 만든다.** 빈 줄을 채우려고
 *     「없음」을 적으면 판이 늘 꽉 차 보여서 진짜 내용이 안 읽힌다
 */
export function readOut(kind) {
  const k = KINDS[kind];
  if (!k) return null;
  const foe = !!(k.shoots || k.rams || k.closes !== undefined);
  const g = k.gives ?? {};
  const has = [];
  if (g.ore) has.push(`광석 ${g.ore}`);
  if (g.parts) has.push(`부품 ${g.parts}`);
  if (g.food) has.push(`식량 ${g.food}`);
  const loot = lootOf(kind);
  return {
    name: k.name,
    foe,
    might: foe ? mightOf(kind) : 0,
    /** 부수면 나오는 것 — 쓰레기의 「필요한 재료나 음식」이 이 줄이다 */
    has,
    /** 적이면 노획 — 뜯어서 내 전투력에 붙는 것 */
    loot: (loot.weapon || loot.armor) ? loot : null,
    what: k.what ?? '',
  };
}
