/**
 * ★★★ **이탈** — 터지기 전에 얼마나 벌려야 하나 (m).
 *
 *   ★ 손으로 고른 값이 아니다. 순항 26 u/s 로 22초면 572, 급가속(3.4배)이면
 *     1,944 다. 그 사이에 두면 **밟으면 되고 안 밟으면 안 된다** —
 *     그게 이 마지막 몇 초를 결심으로 만든다.
 *   ★★ 못 벌리면 **안 죽인다.** 이 배의 규약은 「벌은 죽음이 아니라 일이
 *     는다」이므로, 덜 벌린 만큼 **선체가 상하고 끝 화면에 한 줄이 남는다**.
 *     2시간을 쓰고 마지막 3초에 처음부터 다시가 되면 그건 벌이 아니라 낭비다.
 *
 * @property need  이만큼 벌리면 멀쩡하다
 * @property hurt  이보다 가까우면 상한다 (사이는 조금 상한다)
 * @property max   선체가 최대 몇 % 깎이나
 */
export const ESCAPE = { need: 1500, hurt: 400, max: 0.55 };

/** 지금 얼마나 상하나 — 0 이면 멀쩡 · 1 이면 최대 */
export function hurtAt(dist) {
  if (dist >= ESCAPE.need) return 0;
  if (dist <= ESCAPE.hurt) return 1;
  return +((ESCAPE.need - dist) / (ESCAPE.need - ESCAPE.hurt)).toFixed(3);
}

