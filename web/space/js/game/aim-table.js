//  ★★★ v157 — **물었으면 조준이 따라간다** (사장님 지시)
//
//  ★ 사장님 (2026-08-14) 「지금 **락온되면 마우스 위치가 타겟하고 크게
//    벌어지지 않는다면 자동으로 따라가도록** 해줘. **기준을 세우고**」
//
//  ══ 기준 넷 ═══════════════════════════════════════════════════════════
//
//   ① **물었을 때만** — 안 문 것까지 따라가면 겨누는 일이 통째로 없어진다
//   ② **가까울 때만** (`within`) — 사장님 말씀 그대로 「크게 벌어지지
//      않는다면」. 멀면 안 따라간다. 그래서 **표적을 바꾸는 것도 자유롭다** —
//      6도 밖으로 밀면 그 순간 손이 놓인다
//   ③ **속도에 상한** (`rate`) — 순간이동이 아니라 **끌린다.** 상한이
//      없으면 그건 따라가기가 아니라 **자동 조준**이고, 그러면 v114 조준
//      띠와 v119 락온이 둘 다 죽는다 (`space-skill [2]` 이 지키는 선)
//   ④ **다 안 붙인다** (`leave`) — 0 까지 당기면 정중앙에 붙박여 「내가
//      겨눈 것」이 아니게 된다. 이만큼은 사람이 마저 맞춘다
//
//  ★★ 왜 「조준」이 아니라 **배를 돌리나.** 이 배는 `aimAz = nose.az` 라
//    **조준이 곧 기수**다 (v85 에 둘을 갈랐다가 「상하 조정이 안 된다」가
//    났고, 그때 하나로 합쳤다). 조준만 몰래 옮기면 **창밖과 조준선이
//    갈라진다** — 이 저장소가 제일 자주 밟는 그 함정이다.
//    그래서 `fly3`(비행 자세)를 돌린다. **배가 정말 그쪽으로 튼다.**
// ══════════════════════════════════════════════════════════════════════════

export const STICKY = {
  /**
   * ★★★ **이 각(도) 안이면 따라간다.** 사장님 「크게 벌어지지 않는다면」.
   *   6 은 락온 원뿔(`RADAR.lockCone` 9도)보다 **좁다** — 문 것을 놓지
   *   않을 만큼만 돕고, 그 밖은 손대지 않는다
   */
  within: 6,
  /**
   * ★★★ **초당 이 각(도)까지만 끈다.** 이 상한이 이 기능의 안전장치다.
   *   없으면 순간이동이 되고, 그건 따라가기가 아니라 자동 조준이다.
   *   22 는 적이 흔드는 각속도(`ENGAGE` 최대 초당 5도)보다 넉넉히 크되,
   *   사람이 밀면 밀리는 값이다
   */
  rate: 22,
  /**
   * ★★ **여기까지만 당긴다** (도). 0 으로 두면 정중앙에 붙박여
   *   「내가 겨눈 것」이 아니게 된다 — 마지막 한 뼘은 사람이 맞춘다
   */
  leave: 0.6,
};

/**
 * ★★★ **이번 걸음에 배를 얼마나 틀까** (도).
 *
 *  ★ 게임도 검사도 이 함수 하나를 부른다. `main.js` 가 제 방식으로 다시
 *    재기 시작하면 그때부터 「검사는 초록인데 화면은 안 따라가는」 것이 난다
 *
 * @param offAz 표적이 조준에서 옆으로 벌어진 각 (도 · 오른쪽이 +)
 * @param offEl 위아래로 벌어진 각 (도 · 위가 +)
 * @param dt    한 걸음 (초)
 * @param locked 물었나 — 안 물었으면 **아무것도 안 한다**
 * @returns `{ az, el }` 이번 걸음에 더할 각 (도). 안 따라가면 둘 다 0
 */
export function stickyPull(offAz, offEl, dt, locked = false) {
  if (!locked) return { az: 0, el: 0 };
  const off = Math.hypot(offAz, offEl);
  //  ★ ② 멀면 손을 놓는다 — 여기가 「크게 벌어지지 않는다면」이다
  if (!(off > 0) || off > STICKY.within) return { az: 0, el: 0 };
  //  ★ ④ 마지막 한 뼘은 남긴다
  const want = Math.max(0, off - STICKY.leave);
  if (want <= 0) return { az: 0, el: 0 };
  //  ★ ③ 속도 상한 — 이번 걸음에 갈 수 있는 만큼만
  const step = Math.min(want, STICKY.rate * dt);
  const k = step / off;
  return { az: +(offAz * k).toFixed(5), el: +(offEl * k).toFixed(5) };
}
