/**
 * ★★★ **점 옆에 무엇을 적나** — 여기가 「오른쪽 왼쪽이 아니고」의 답이다.
 *
 *   실제 스코프가 표적 옆에 적는 것 그대로:
 *     · **상대 고도** — 위/아래 몇 도. PPI 에 담을 수 없는 축이라 숫자다
 *     · **접근율** — 초당 몇 m 로 가까워지나. 부호가 곧 추격 곡선이다
 *
 *   ★ 둘 다 **원뿔 안(추적)일 때만** 적는다. 원뿔 밖은 「저쪽에 뭔가
 *     있다」까지만 아는 것이 맞다 — 알면 안 되는 것을 적으면 그건
 *     레이더가 아니라 전지(全知)다.
 *
 * @property elMin  이보다 |고도| 가 작으면 안 적는다 (수평이면 군더더기다)
 * @property vcMin  이보다 |접근율| 이 작으면 안 적는다 (0 근처는 잡음이다)
 */
export const READ = {
  elMin: 4,
  vcMin: 2,
  /** 다가온다 · 멀어진다 — 부호를 **글자 하나**로 */
  closing: '▲',
  opening: '▼',
};

/**
 * ★★ **RWR — 저쪽이 나를 겨눈다** (실제 전투기의 레이더 경고 수신기).
 *
 *   적은 겨눔을 쌓고 나서 쏜다 (`target-table.js ENEMY_FIRE`). v74 까지
 *   그 시간이 **화면에 하나도 안 나왔고**, 그래서 피격은 늘 예고 없이 왔다.
 *   실제 조종사가 제일 먼저 보는 계기를 넣으면 그 구멍이 메워진다.
 *
 *   ★ 그런데 **경고가 곧 안전은 아니다.** 알려 주는 것은 **방위**뿐이고,
 *     피하는 것은 여전히 손이다. 「알고도 못 피한다」가 있어야 긴박하다.
 *
 * @property from  겨눔이 이 비율을 넘으면 화면에 뜬다 (0~1).
 *                 0 이면 늘 떠 있어 경고가 아니고, 1 이면 쏘는 순간이라 늦다
 * @property blink 뜬 뒤 초당 몇 번 깜빡이나 — 급한 것은 깜빡인다
 * @property hot   이 비율을 넘으면 **크게** 깜빡인다 (곧 쏜다)
 */
export const RWR = {
  from: 0.45,
  blink: 3.2,
  hot: 0.80,
};

/** 겨눔 비율(0~1)이 화면에 뜨나 · 급한가 */
export const rwrLevel = (k) => {
  if (!(k >= RWR.from)) return null;
  return k >= RWR.hot ? 'hot' : 'warn';
};

/**
 * ★ 상대 고도를 **읽는 글자**로. 「+12°」 처럼.
 *   `null` 이면 안 적는다 (거의 수평이다).
 */
export function elWord(relEl) {
  if (!Number.isFinite(relEl) || Math.abs(relEl) < READ.elMin) return null;
  return `${relEl > 0 ? '+' : '−'}${Math.round(Math.abs(relEl))}°`;
}

/**
 * ★ 접근율을 읽는 글자로. 「▲34」 는 초당 34m 로 **다가온다**.
 *   `null` 이면 안 적는다.
 */
export function vcWord(closing) {
  if (!Number.isFinite(closing) || Math.abs(closing) < READ.vcMin) return null;
  return `${closing > 0 ? READ.closing : READ.opening}${Math.round(Math.abs(closing))}`;
}

/**
 * ★★ 방위를 **숫자로** — 「왼쪽」이 아니라 「방위 214」.
 *
 *   ★ 실제 항공·항해가 쓰는 그대로 **0~359 도, 기수가 000**이다.
 *     상대 방위(−180~+180)를 그대로 쓰면 음수가 나오는데, 사람이
 *     「−146도」를 방향으로 옮기는 것은 한 박자 더 걸린다.
 */
export function bearing(relAz) {
  const a = Math.round(relAz) % 360;
  return String((a + 360) % 360).padStart(3, '0');
}

/**
 * ★★★ **말 한 줄** — 조준경 아래에 뜨는 것.
 *
 *   v74 까지 「요격기 — **왼쪽 옆**」이었다. 방위와 고도를 숫자로 주면
 *   **어디로 얼마나 돌릴지**가 그 자리에서 나온다.
 *
 *   ★ 「왼쪽/오른쪽」을 아주 버리지는 않는다 — 숫자만 있으면 어느 쪽으로
 *     도는 것이 가까운지 한 번 더 생각해야 한다. **도는 방향은 글자,
 *     얼마나는 숫자**로 나눈다: 「좌 146° · 아래 22°」
 */
export function callOut(name, relAz, relEl) {
  const d = ((relAz % 360) + 540) % 360 - 180;      // −180~+180
  const way = Math.abs(d) < 1 ? '정면' : (d > 0 ? '우' : '좌');
  const az = Math.round(Math.abs(d));
  const el = Math.round(relEl ?? 0);
  const up = Math.abs(el) < READ.elMin ? '수평' : (el > 0 ? `위 ${Math.abs(el)}°` : `아래 ${Math.abs(el)}°`);
  const turn = way === '정면' ? '정면' : `${way} ${az}°`;
  return `${name} — ${turn} · ${up}`;
}

