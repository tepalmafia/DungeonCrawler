// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **레이더 계기** — 실제 레이더를 고증해서 다시 (v75)
//
//  ★ 사장님 「레이더 시스템을 더 **정교하게 직관적으로** 만들어줘.
//            **오른쪽 왼쪽이 아니고.** 실제 레이더 시스템을 고증해서」
//
//  ══ 무엇이 문제였나 ═══════════════════════════════════════════════════
//
//  v74 까지 레이더가 말하는 것은 **방위 하나**뿐이었다:
//    · 계기(PPI)에 점이 찍히는데 **위아래(고도)가 없다**
//    · 조준경은 「요격기 — **왼쪽 옆**」처럼 **말로** 알려 준다
//
//  v73 에 세 축을 다 열어 놓고(360도) 계기는 **평면 하나**였던 셈이다.
//  적이 아래에 있으면 화면에도 「왼쪽」이라고만 뜬다 — 어디로 기수를
//  돌려야 하는지 **알 수가 없다.** 그게 「오른쪽 왼쪽이 아니고」다.
//
//  ══ ★★★ 고증 — 실제 레이더가 화면에 적는 것 ═══════════════════════════
//
//  ① **B-스코프 vs PPI.** 전투기 사격통제 레이더는 **B-스코프**(가로=방위,
//     세로=거리)를 쓴다. 앞쪽 원뿔을 크게 펴서 보기 위함이다. 함정·조기경보기는
//     **PPI**(위에서 내려다본 360도)를 쓴다.
//     ★ 우리 배는 **360도를 다 봐야 하므로 PPI 가 맞다.** 다만 PPI 는
//       세로축이 거리라 **고도를 담을 데가 없다** — 그래서 실제 레이더도
//       고도는 **점 옆에 숫자로 적는다** (전투기 스코프의 고도 표기가 그것).
//       그 한 가지가 「왼쪽/오른쪽」을 「방위 + 고도」로 바꾼다.
//
//  ② **접근율 (Vc · closure rate).** 실제 스코프가 표적 옆에 반드시 적는
//     숫자다. 「가까워지고 있나 멀어지고 있나」는 거리보다 중요하다 —
//     선도 추격이 되고 있는지가 이 부호 하나로 나온다 (`docs/space/BFM.md`).
//     ★ 우리는 v73 에 이미 재고 있었는데 **화면에 안 냈다.**
//
//  ③ **심볼 규약.** 실제 레이더는 상태마다 모양이 다르다:
//       수색 접촉 → **빈 표시**   (있는 줄만 안다)
//       추적      → **채운 표시** (거리·속도를 안다)
//       물린 것   → **마름모**    (무기가 따라간다)
//     색으로만 나누면 색약인 사람에게 아무것도 아니고, 흐린 화면에서도 죽는다.
//
//  ④ ★★ **RWR (레이더 경고 수신기).** 실제 전투기의 **별개 계기**다 —
//     「누가 나를 비추고 있나」를 방위로 알려 주고, 물리면(락온) 경고음과
//     함께 그쪽을 가리킨다. 조종사가 제일 먼저 보는 화면이 이것이다.
//     ★★★ 우리 게임에 **이게 없어서 맞기 전까지 아무 예고가 없었다.**
//       적은 이미 겨눔을 쌓고 나서 쏘는데(`target.js` 의 `t.aim`),
//       그 시간이 화면에 하나도 안 나왔다. 고증을 넣으면 그 구멍이 메워진다.
//
//  ⑤ **거리 고리에 숫자.** 실제 스코프는 고리마다 거리를 적는다.
//     안 적으면 「점이 가운데 가깝다」까지만 알고 **몇 미터인지 모른다**.
//
//  ⑥ **사각(blind zone).** 원뿔 밖은 정밀 추적이 안 된다 — 이미 있다.
//
//  ★ three.js 를 안 쓴다 — `tools/space-radar.js` 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

