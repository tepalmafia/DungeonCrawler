export const MARK = {
  /**
   * ★★★ **상자는 표적보다 이만큼 크다** (배수).
   *   ★ 1.0 이면 딱 붙어서 실루엣을 갉아먹고, 2.0 이면 옆 표적까지 삼킨다.
   *     1.45 면 **표적 둘레에 한 뼘**이 남는다
   */
  box: 1.45,
  /** 상자가 아무리 작아도 이만큼은 (도) — 먼 표적을 못 찾으면 안 된다 */
  minDeg: 1.6,
  /** ★★ 상자가 아무리 커도 이만큼 (도) — 붙었을 때 화면을 두르지 않게 */
  maxDeg: 22,

  /**
   * ★★★ **이보다 크면 상자를 지운다** (도).
   *   ★ 그 거리에서는 눈이 이미 배를 본다. 상자는 **찾는 도구**이지
   *     보는 도구가 아니다 — Ace Combat 이 쓰는 규약이다.
   *   ★★ 대신 **모서리 갈고리 넷**만 남긴다: 「지정돼 있다」는 알려 주되
   *     실루엣은 안 건드린다
   */
  dropAt: 6,
  /** 갈고리 길이 — 상자 한 변의 몇 할 */
  hook: 0.26,

  /**
   * ★★★ **글은 표적에서 떨어뜨린다** — 상자 반지름의 몇 배 밖에.
   *   ★ 표적 위에 글을 얹으면 **글도 안 읽히고 배도 안 보인다.**
   *     지금이 정확히 그 상태다
   */
  tagAway: 1.35,
  /** 글이 앉는 쪽 (화면 기준) — 오른쪽 아래. 조준선(가운데)과 안 겹친다 */
  tagAt: { x: 1, y: -1 },
  /** 떨어뜨린 글과 표적을 잇는 **가는 선** — 없으면 어느 표적의 글인지 모른다 */
  leader: true,

  /**
   * ★★ **진한 것은 하나만** (v130 「굵은 한 줄」과 같은 규약).
   *   지정한 표적만 이 밝기, 나머지는 아래 `dim`
   */
  hot: 1.0,
  dim: 0.28,
};

/** 길이 L(m) 짜리가 거리 d(m) 에서 몇 도로 보이나 — **자는 하나다** */
export const degAt = (L, d) =>
  2 * Math.atan(L / 2 / Math.max(1, d)) * 180 / Math.PI;

/**
 * ★★★ **이 표적에 무엇을 그리나.**
 *
 * @param lenM  표적의 길이 (m · `target-table.js lenOf`)
 * @param distM 거리 (m)
 * @param picked 지정한 표적인가
 * @returns { deg, boxDeg, box, hooks, tagDeg, alpha }
 *          `box` 가 거짓이면 **상자를 안 그린다** (갈고리만)
 */
export function markAt(lenM, distM, picked = false) {
  const deg = degAt(lenM, distM);
  const boxDeg = Math.min(MARK.maxDeg, Math.max(MARK.minDeg, deg * MARK.box));
  const box = deg < MARK.dropAt;
  return {
    deg: +deg.toFixed(2),
    boxDeg: +boxDeg.toFixed(2),
    /** 상자를 그리나 — 가까우면 안 그린다 */
    box,
    /** 갈고리는 **늘** 그린다 — 「지정돼 있다」를 알리는 최소한이다 */
    hooks: true,
    /** 글이 앉을 거리 (도) — 상자 반지름의 `tagAway` 배 */
    tagDeg: +(boxDeg / 2 * MARK.tagAway).toFixed(2),
    alpha: picked ? MARK.hot : MARK.dim,
  };
}

/** ★ 표시가 표적을 덮나 — 검사가 묻는다. **덮으면 안 된다** */
export const covers = (m) => m.box && m.boxDeg < m.deg;

/** 사람이 읽는 한 마디 */
export const markWord = (m) => (m.box
  ? `상자 ${m.boxDeg}° (표적 ${m.deg}°)`
  : `갈고리만 — 표적이 ${m.deg}° 라 눈에 이미 보인다`);
