//  문 — **배가 살아 있다고 느끼게 하는 것.** 그리고 갇히는 것.
//
//  ★ 지금까지 문은 **문이 아니었다**
//    `kit.js hatch()` 는 문틀만 만들었다 — 기둥·상인방·문턱·잠금 손잡이.
//    **문짝이 아예 없고** 구멍은 영구히 뚫려 있었다. 배 안이 조용했던 이유의
//    절반이 이것이다: 아무것도 움직이지 않았다.
//
//  ★ 갇힘은 **「벽」이 아니라 「시간 손해」다** — 이게 제일 중요한 규칙
//    이 배는 척추형이라 **우회로가 없다.** 기관실 문이 끼었는데 못 열면
//    열이 100인 채로 밸브에 못 가고 아무것도 못 한다 — v21 에서 게임을
//    못 하게 만들었던 바로 그 종류다.
//
//    그래서: **끼인 문은 언제나 손으로 열린다.** 비상 크랭크를 잡고
//    돌리면 열린다. 열이 오르는 중이면 그 시간이 아프고, 평온할 때는
//    그냥 귀찮다. 그게 이 게임이 벌을 주는 방식이다 (PLAN §4-4).
//
//  ★ three.js 를 안 쓴다 — tools/space-door.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const DOOR = {
  /**
   * 문 반폭(m). **ship.js 의 문구멍이 이 값을 쓴다** — 두 곳에 적으면
   * 「분명히 문이 있는데 못 지나간다」가 난다
   */
  half: 1.1,

  /** 이 안에 들어오면 열린다(m). 걸어가는 속도(2.9)로 한 걸음 전 */
  near: 2.4,
  /** 다 열리는 데(초) — 빠르다. 문 앞에서 기다리는 게임이 아니다 */
  openTime: 0.5,
  /** 닫히는 데(초). **여는 것보다 느리다** — 급히 닫히면 갇히는 기분이 든다 */
  closeTime: 0.9,
  /** 지나간 뒤 열어 두는 시간(초). 되돌아설 때 코앞에서 안 닫히게 */
  dwell: 1.4,
  /** 이만큼 열려야 지나갈 수 있다 (0~1) */
  passAt: 0.72,

  // ── 고장 ────────────────────────────────────────────────
  /**
   * ★ 문은 **쓴 만큼 낡는다.** 여닫을 때마다 조금씩. 그래서 많이 다니는
   *   문(조종석·기관실)이 먼저 끼고, 그게 맞다 — 왕복이 잦은 길이 먼저
   *   말썽을 부리는 것이 이 게임의 결이다.
   */
  wearPerCycle: 0.028,
  /** 이 값을 넘으면 끼일 수 있다 */
  jamAt: 1.0,
  /**
   * 켠 뒤 이만큼은 안 끼인다 — 시작하자마자 갇히면 억울하다.
   * ★ 150 이었다. 그런데 **처음 오는 사람은 배 안을 쉬지 않고 돌아다닌다** —
   *   그렇게 5분을 걸으면 문이 닳아서 껴 버렸다. 배우는 중에 갇히는 건
   *   튜토리얼이 아니라 검문이다. 첫 5분은 통째로 비운다 (여유 30초).
   *   (게임 쪽에는 빗장이 하나 더 있다 — main.js 가 **가르침을 다 뗄 때까지**
   *    안 끼게 한다. 고장·위험 지대와 같은 규약이다)
   */
  firstAfter: 330,
  /** 한 번 끼고 다음까지 최소 간격(초). 몰아치면 문 게임이 된다 */
  jamGap: 110,
  /** 동시에 이만큼만 낀다. 둘이 끼면 배가 셋으로 갈린다 */
  maxJammed: 1,

  /**
   * 비상 크랭크를 **잡고 돌리는 시간(초).**
   * ★ 밸브(4.2초)보다 길고 점검 패널(7초)과 비슷하다. 「짜증나기 직전」이
   *   맞는 자리다 — 짧으면 벌이 아니고, 길면 벌이 아니라 벽이다.
   */
  crank: 9,
  /** 놓으면 초당 이만큼 되돌아간다 — 밸브와 같은 규약 */
  slip: 0.5,
  /** 크랭크로 연 문은 이만큼 열린 채로 있는다(초). 다시 안 끼게 */
  afterCrank: 25,
};

/** 문이 지나갈 수 있나 */
export const canPass = (d) => d.k >= DOOR.passAt;

/** 사람이 이 문 가까이 있나 — 좌표는 배가 준다 */
export function nearDoor(doors, x, z) {
  let best = null, bd = DOOR.near;
  for (const d of doors) {
    const dist = Math.hypot(x - d.x, z - d.z);
    if (dist < bd) { bd = dist; best = d; }
  }
  return best;
}
