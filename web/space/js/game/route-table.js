//  ★★★ v161 까지 갈래는 **구간 번호를 안 봤다.** 1구간에서 낼 수 있는
//    것과 10구간에서 낼 수 있는 것이 똑같았고, 그래서 「깊이 들어간다」가
//    화면 어디에도 안 나왔다 — `depth` 를 표에 적어 놓고 **아무도 안 읽는**
//    상태였다.
//
//  ★★ 이제 구간 번호가 **깊이 창**을 정하고, 그 창 안에서 둘을 낸다.
//    앞 구간에서는 빈 공간·잔해밭·채굴 지대가 나오고, 뒤로 갈수록
//    전초선·외계 생명권·호송 항로가 나온다.
//
//  ★ **창을 넓히는 규칙이 있다.** 깊이 5~7 이 셋 다 「숨는 쪽」이라
//    창 안에 빠른 쪽이 하나도 없는 구간이 생긴다. 그때는 **한쪽이 찰
//    때까지 창을 넓힌다** — 「양쪽에서 하나씩」이 이 표의 축이므로
//    그것을 깨느니 창을 늘린다.
// ══════════════════════════════════════════════════════════════════════════

/** 고를 수 있는 구역만 — 성간 공백·적 행성 상공은 **닿는 곳**이라 뺀다 */
const PICKABLE = () => REGIONS.filter((r) => r.depth < VOID_DEPTH);
/** 갈래로 안 나오는 깊이의 문턱 (성간 공백 11 · 적 행성 상공 12) */
const VOID_DEPTH = 11;

/** 이 구간이 서 있는 깊이 (1~10) */
export function depthAt(leg) {
  const last = Math.max(1, LEG.count - 2);
  const d = 1 + Math.round((Math.max(0, leg) * (VOID_DEPTH - 2)) / last);
  return Math.min(VOID_DEPTH - 1, Math.max(1, d));
}

/**
 * 이번 구간에 낼 두 갈래. 한쪽은 숨는 쪽, 한쪽은 빠른 쪽.
 * @param leg 몇 번째 구간인가 (0부터). 안 주면 첫 구간으로 본다
 */
export function offerFor(rnd, leg = 0) {
  const d = depthAt(leg);
  const pool = PICKABLE();
  const pickSide = (side) => {
    // 창을 1 부터 넓혀 가며 그 편이 나올 때까지 — 못 찾으면 전부에서
    for (let w = 1; w <= VOID_DEPTH; w++) {
      const near = pool.filter((r) => sideOf(r) === side && Math.abs(r.depth - d) <= w);
      if (near.length) return rnd.pick(near.map((r) => r.key));
    }
    return rnd.pick(pool.filter((r) => sideOf(r) === side).map((r) => r.key));
  };
  return [forkOf(pickSide('hide')), forkOf(pickSide('fast'))];
}

