// ══════════════════════════════════════════════════════════════════════════
//  항로 — 목적 한 줄의 **첫 문장**이다.
//
//    「**따라오지 못하는 곳까지 간다.** 가는 동안 먹고, 고치고, 뿌리친다」
//
//  ★ 왜 이게 없으면 안 되나 (2026-08-03 점검 · docs/space/GAP.md §1-1)
//    전에는 구역이 95초마다 **돌았다.** 성운 → 잔해밭 → 행성 곁 → 빈 공간 →
//    성운. 창밖이 바뀌니 움직이는 것처럼 보였지만 **20분을 돌아도 같은
//    자리**였다. 그래서 뿌리쳐도 아무것도 안 쌓이고, 공들여 만든 「뿌리친
//    직후 3초」가 **무엇을 향한 3초인지가 비어 있었다.**
//
//  ★ 벤치마크 — FTL 의 쫓아오는 함대를 각색했다 (GAP.md §2-①)
//    그쪽은 압박을 **실시간 거리가 아니라 지도 위의 전진**으로 표현하고,
//    성운에 들르면 그 턴의 전진이 절반이 된다. 즉 **유저가 압박과 거래한다.**
//    우리 추격은 초 단위 거리 하나뿐이라 끝나면 사라진다. 그 위에 한 겹 —
//    **뿌리쳐도 안 사라지고 쌓이는 것**이 필요했다. 그게 압박이다.
//
//  ★ 갈래가 진짜로 달라야 한다 — 여기가 제일 위험한 자리다
//    바 하나가 오르기만 하면 그건 선택이 아니라 **시계**다 (GAP.md §5).
//    그래서 매 구간 **「숨는 쪽」 하나와 「빠른 쪽」 하나**를 짝지어 낸다.
//    둘 중 아무거나 골라도 되는 상황이 나오지 않게 하는 것이 이 규칙의 전부다.
//
//  ★ 숫자를 여기 새로 만들지 않는다
//    구간 길이는 `regions-table.js` 의 `speed` 에서, 압박 속도는 `signMult`
//    에서 나온다. 한 숫자가 여러 일을 하게 두는 편이 **두 곳에 적어서
//    갈라지는 것**보다 낫다 (CLAUDE.md 「숫자는 한 곳에만」).
//
//  ★ three.js 를 안 쓴다 — tools/space-route.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════
import { REGIONS, REGION_BY_KEY } from './regions-table.js';

/** 구간과 회차 */
export const LEG = {
  /** 기준 길이(초). 실제 길이는 이것을 구역의 speed 로 나눈다 */
  seconds: 490,
  /**
   * 한 회차의 구간 수 = 거점 수.
   *
   * ★ **8 → 12 로 올렸다** (2026-08-05 · PLAN2H §5).
   *   옛 전제는 「20분 회차를 반복한다」였고 거점 6~8개면 맞았다.
   *   전제가 **「2시간 한 번의 여정」**으로 바뀌면서 12구간이 됐다 —
   *   구간 하나가 8~12분이므로 12구간이 104~132분이다.
   *
   *   **올리기 전에 쟀다.** 8 로 두면 69~88분이라 2시간의 절반이었고,
   *   12 로 두니 104~132분으로 배치표(0~132분)와 맞았다. `space-route.js`
   *   의 회차 목표도 60~90 에서 100~140 으로 같이 옮겼다 — 안 옮기면
   *   **도구가 옛 기획서를 지켜서** 맞게 고친 쪽이 빨개진다.
   */
  count: 12,
  /**
   * ★ **추진을 끄면 구간이 이 속도로만 나아간다.** 켜면 1.0 이다.
   *
   *   이게 없으면 「셋 중 둘」(추진·냉각·센서)이 추격 중에만 뜻이 있고
   *   평온할 때는 아무 뜻이 없다. 추진이 항로를 미는 순간 **평온할 때도
   *   같은 저울이 돈다** — 밟으면 빨리 가고 압박도 덜 쌓이지만, 자국이
   *   커지고 열이 오른다. 그래서 기관실에 다녀와야 한다.
   *
   *   ★ 처음엔 반대로 뒀다 — 「기본 1.0 에 밟으면 +0.18」. 그랬더니
   *     **발만 떼면 영영 안 붙는 게임**이 됐다. 자국이 안 나니 추격이 0회고,
   *     발을 떼도 구간은 85% 속도로 계속 가니 잃는 게 없었다.
   *     시뮬이 「추격 0회」로 잡아 줬다 — 안 쟀으면 못 봤다.
   *
   *     지금은 **엔진이 있어야 간다.** 발을 떼면 구간이 두 배로 늘어지고,
   *     늘어진 만큼 압박이 진짜 시간으로 쌓여 결국 그물이 닫힌다.
   *     숨는 것에 값이 붙는다.
   */
  coast: 0.45,
};

/**
 * 압박 — **뿌리쳐도 안 사라지는 것.**
 *
 * 0 이면 아무도 내 자리를 모르고, 100 이면 그물이 닫힌 것이다.
 */
export const PRESS = {
  max: 100,
  /**
   * ★ **구간 하나를 지나면 이만큼 오른다** (초당이 아니라 구간당이다).
   *   구역의 signMult 를 곱한다 — 성운은 적게, 행성 곁은 많이.
   *
   *   처음엔 초당으로 뒀다. 그러면 **느린 길은 오래 걸려서 결국 같은 만큼
   *   쌓인다** — 지형을 골라도 끝 압박이 거의 같았다 (쓸어보니 차이가 5~11).
   *   FTL 도 함대는 **점프마다** 전진하지 초마다 전진하지 않는다.
   *   구간당으로 바꾸니 「숨는 길은 정말로 덜 쌓인다」가 성립한다.
   *
   *   화면에서는 구간 길이에 나눠 **부드럽게** 올린다 — 거점에서 툭 뛰면
   *   계기가 아니라 알림이 된다.
   */
  perLeg: 32,
  /**
   * ★ **갈래가 못 깎는 부분.** 시간 자체의 값이다.
   *
   *   이게 없으면 성운만 골라 다니는 것이 무조건 정답이 된다 — 압박이
   *   절반이고 잃는 게 없으니까. 시간에 값을 붙여야 「느리지만 안전한
   *   길」과 「빠르지만 위험한 길」이 **비긴다.**
   *   (FTL 이 연료로 하는 일을 우리는 아직 식량이 없어서 이걸로 한다.
   *    식량이 생기면 여기를 다시 본다)
   */
  drift: 0.012,
  /**
   * ★ 거점에서 **이만큼만 남는다** (뺄셈이 아니라 곱셈이다).
   *
   *   처음엔 「-55 씩 뺀다」로 뒀다. 그러면 어떤 길로 가든 몇 구간 만에
   *   100 에 붙어 버리고, **정책이 달라도 끝 압박이 똑같아진다** —
   *   고르는 것이 결과를 안 가른다. 시뮬이 「압박 차 8」로 잡아 줬다.
   *
   *   곱셈이면 길마다 **자기 평형점**이 생긴다. 구간 상승분 g 에 대해
   *   평형은 g × keep/(1-keep) 이다 — 성운은 낮은 데서, 행성 곁은 높은 데서
   *   멎는다. 그리고 **어디서도 100 에 안 눌어붙는다.**
   */
  portKeep: 0.65,
  /**
   * 압박이 접촉 기준을 끌어내린다 — **깊이 갈수록 잘 붙는다.**
   * 자국이 같아도 뒤쪽 구간에서는 붙는다. 그게 「좁혀 온다」의 실체다.
   */
  contactFrom: 52,   // 압박 0 일 때 (= chase-table SIGN.contactAt)
  contactTo: 32,     // 압박 100 일 때
  /**
   * ★ **압박이 넘치면 무조건 붙는다.** 자국이 얼마든 상관없다.
   *
   *   처음엔 넘쳐도 「붙는 속도가 1.25배」로만 뒀다. 시뮬을 돌려 보니
   *   **추격이 한 번도 안 났다** — 위험 계기를 보고 발만 떼면 영영 안 붙는다.
   *   그러면 이 게임은 「가만히 있으면 이기는」 게임이 된다.
   *
   *   발을 떼면 구간이 안 줄고, 구간이 안 줄면 **압박은 진짜 시간으로
   *   쌓인다.** 그래서 넘친다. 그게 조인다는 것의 실체다 —
   *   숨어도 시간이 쫓아온다.
   */
  overrunTrack: 1.25,
  /** 뿌리치면 압박도 조금 준다. **추격을 이긴 것이 항로에도 남아야 한다** */
  escapeRelief: 18,
};

/** 갈래의 이름 — 구역 하나에 한 줄. 표에 있는 것을 문장으로만 바꾼다 */
const CALL = {
  empty: '빈 공간을 가로지른다',
  nebula: '성운을 지난다',
  debris: '잔해밭을 가른다',
  planet: '행성 곁을 돈다',
  // ★ 이것만 「~한다」가 아니다. 고르는 것이 아니라 **닿는 곳**이라
  //   부르는 말이 아니라 자리 이름이다 (PLAN2H §9 · void-table.js)
  void: '성간 공백',
  // ★★★ v93 — **적 행성 상공** (마지막 구간). 같은 이유로 자리 이름이다 —
  //   고르는 곳이 아니라 **닿아야 하는 곳**이고, 거기서 떨군다 (`WAR.md §6`)
  siege: '적 행성 상공',
};

/**
 * ★ 「숨는 쪽」과 「빠른 쪽」. 매 구간 **양쪽에서 하나씩** 낸다.
 *   같은 쪽 둘을 내면 고를 이유가 없어지고, 그 순간 항로는 시계가 된다.
 */
const HIDE = ['nebula', 'debris'];
const FAST = ['empty', 'planet'];

/**
 * 갈래 하나 — 구역에서 뽑아낸다. 새 숫자를 안 만든다.
 *
 * ★ **부를 때마다 계산한다.** 처음엔 한 번 만들어 `FORKS` 에 굳혔는데,
 *   그러면 표(LEG·PRESS·REGIONS)를 고쳐도 갈래는 옛날 값을 들고 있다.
 *   `tools/space-tune.js` 가 숫자를 바꿔 가며 쓸어 보려면 반드시 그때그때
 *   다시 나와야 한다 — 굳은 값을 재면 **바꾸지도 않은 것을 재게 된다.**
 */
export function forkOf(key) {
  const r = REGION_BY_KEY[key];
  return {
    key, region: key, name: CALL[key], what: r.what,
    seconds: LEG.seconds / r.speed,
    /** 초당 오르는 몫 = 구간당 몫을 길이로 나눈 것 + 시간 자체의 몫 */
    pressRate: (PRESS.perLeg * r.signMult) / (LEG.seconds / r.speed) + PRESS.drift,
    trackMult: r.trackMult,
    signMult: r.signMult,
    /** 성운에서는 센서를 켜도 거리가 안 읽힌다 — 「나도 못 본다」의 실체 */
    blind: key === 'nebula',
  };
}

/** 갈래 넷 — 지금 표 기준 */
export function allForks() { return REGIONS.map((r) => forkOf(r.key)); }

/** 이번 구간에 낼 두 갈래. 한쪽은 숨는 쪽, 한쪽은 빠른 쪽 */
export function offerFor(rnd) {
  return [forkOf(rnd.pick(HIDE)), forkOf(rnd.pick(FAST))];
}

/** 압박이 이만큼이면 접촉 기준이 얼마인가 */
export function contactAtFor(press) {
  const t = Math.max(0, Math.min(1, press / PRESS.max));
  return PRESS.contactFrom + (PRESS.contactTo - PRESS.contactFrom) * t;
}
