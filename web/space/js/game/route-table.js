/**
 * 이 거점이 조용한가.
 *
 * ★★★ **항로의 난수를 안 쓴다** — 처음에 `rt.rnd` 를 썼다가
 *   `space-route.js` 가 「구간 하나가 12.1분」으로 빨개졌다. 거점마다
 *   한두 번씩 뽑아 쓰니 **그 뒤의 갈래 길이가 통째로 밀렸기** 때문이다.
 *   새 계통을 얹으면서 **남의 흐름을 건드리는 것**은 이 저장소가 자주
 *   밟는 함정이고, 이번엔 검사가 바로 잡아 줬다.
 * ★ 그래서 **구간 번호에서 바로 뽑는다** — 흐름을 안 쓰고, 같은 회차면
 *   같은 답이 나온다 (저장을 이어해도 안 바뀐다)
 */
export function quietAt(leg, seed = 0) {
  if (leg < QUIET.notBefore) return null;
  // 작은 해시 — 구간과 시드로 0~1 을 만든다
  let h = (Math.floor(leg) * 2654435761 + Math.floor(seed) * 40503) >>> 0;
  h ^= h >>> 15; h = (h * 2246822507) >>> 0; h ^= h >>> 13;
  const u = (h >>> 8) / 16777216;
  if (u > QUIET.chance) return null;
  const total = QUIET.kinds.reduce((a, k) => a + k.weight, 0);
  let r = ((h >>> 3) % 1000) / 1000 * total;
  for (const k of QUIET.kinds) { r -= k.weight; if (r <= 0) return k; }
  return QUIET.kinds[0];
}

