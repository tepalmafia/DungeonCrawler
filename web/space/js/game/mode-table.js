// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **마우스를 쓰는 모드** — 뼈대 (v129). three 도 DOM 도 안 쓴다.
//
//  ★ 사장님 (2026-08-12) 「**u로 ui 이동 시키면 방향 전환이 안 돼.**」
//    (2026-08-13) 「**블록아웃으로 테스트하고 구현하고 있지?**」
//
//  ══ 왜 이 표가 없어서 태웠나 ═══════════════════════════════════════════
//
//  이 배에는 **마우스를 쓰려고 포인터 잠금을 푸는 모드가 다섯**이다
//  (점검 · 배치 · 베이 · 도움말 · 멈춤). 그런데 그 다섯이 저마다
//  `main.js` 안에서 **손으로 쓴 조건**을 들고 있었다:
//
//      · 점검  — 자동 멈춤의 예외에 **적혀 있다**
//      · 배치  — 안 적혀 있었다 → v128 에 사장님이 겪으셨다
//      · 베이  — 안 적혀 있다  → **I 로도 Esc 로도 안 닫힌다** (재서 확인)
//      · 도움말— `paused` 를 **먼저** 켜서 우연히 피한다 (순서에 기댄다)
//      · 멈춤  — 제가 멈춤이다
//
//  ★★★ **재는 곳이 다섯이면 다섯 번 갈라진다.** 이 저장소가 v91~v98 에
//    자리를 아는 곳을 넷으로 두고 네 판을 태운 것과 **같은 모양**이다.
//    그때 배운 답도 같다 — **뼈대를 하나 세우고 계통이 묻기만 하게 한다.**
//
//  ══ 세 줄이 전부다 ════════════════════════════════════════════════════
//
//      ① 마우스를 쓰는 모드가 하나라도 열려 있으면 **잠그지 않는다**
//      ② 그동안 **자동 멈춤이 걸리면 안 된다** — 걸리면 닫는 키가 막힌다
//      ③ 마지막 하나가 닫히면 **잠금을 돌려준다** (여는 것과 닫는 것은 대칭)
//
//  ★ ②가 이번 병의 알맹이다. 잠금이 풀린 것을 「사람이 창 밖으로 나갔다」로
//    읽어 멈추면, 닫는 키가 `!paused` 에 막혀 **못 나온다.** 그러면 잠금도
//    안 돌아오고, 잠금이 없으면 이 배는 조종간이 안 움직인다
// ══════════════════════════════════════════════════════════════════════════

/**
 * ★★★ **마우스를 쓰는 모드 다섯.**
 *
 *  @property key    여닫는 키 (사람에게 보여 주는 이름)
 *  @property stops  ★ 이 모드가 **시계를 멈추나** — 멈추는 것과 마우스를
 *                   쓰는 것은 **다른 일**이다. 여태 둘을 섞어 두어서
 *                   「마우스 쓰려고 풀었는데 멈춰 버리는」 일이 났다
 *  @property why    왜 마우스가 필요한가 — 까닭 없이 푸는 모드가 없어야 한다
 */
export const MODES = {
  점검: { key: 'F2 · `', stops: false, why: '단추를 눌러 아무 상황이나 만든다' },
  배치: { key: 'U', stops: false, why: '창을 끌어 옮긴다' },
  베이: { key: 'I · Esc', stops: false, why: '탭과 단추를 누른다 (기체 · 성장 · 화물 · 탄두)' },
  도움말: { key: 'F1', stops: true, why: '읽는다 — 읽는 동안 얻어맞으면 그건 도움말이 아니라 함정이다' },
  멈춤: { key: 'Esc', stops: true, why: '멈추는 것이 곧 그 뜻이다' },
};

/** 이름 목록 — 검사와 게임이 같은 것을 센다 */
export const MODE_NAMES = Object.keys(MODES);

/**
 * ★★★ **지금 마우스를 쓰는 모드가 열려 있나.**
 * @param open `{ 배치: true, … }` — 게임이 제 상태를 그대로 넘긴다
 */
export const takesMouse = (open = {}) => MODE_NAMES.some((n) => !!open[n]);

/** 열려 있는 것들 (이름) */
export const openList = (open = {}) => MODE_NAMES.filter((n) => !!open[n]);

/**
 * ★★★ **포인터를 잠가야 하나** — 하나라도 열려 있으면 **아니다.**
 *
 *   ★ 「마지막 하나가 닫힐 때」가 저절로 나온다. 모드마다 제 조건을 들면
 *     둘을 겹쳐 열었다가 하나만 닫았을 때 **잠금이 되살아난다**
 */
export const wantLock = (open = {}) => !takesMouse(open);

/**
 * ★★★ **잠금이 풀린 것을 「창 밖으로 나갔다」로 읽어도 되나.**
 *
 *   ★ 마우스를 쓰는 모드가 열려 있으면 **안 된다** — 그 풀림은 게임이
 *     스스로 푼 것이지 사람이 나간 것이 아니다. 이 한 줄이 v128 의 병이다
 */
export const autoPauseOK = (open = {}) => !takesMouse(open);

/**
 * ★★★ **시계를 멈춰야 하나** — 열린 것 중 하나라도 멈추는 것이면 멈춘다.
 *   ★ 마우스를 쓰는 것과 멈추는 것은 **다른 일**이다 (`stops`)
 */
export const wantStop = (open = {}) => openList(open).some((n) => MODES[n].stops);

/**
 * ★★★ **멈춰 있어도 닫을 수 있어야 한다** — 예외 없이 전부.
 *
 *   ★ 「들어가는 길만 있고 나오는 길이 없으면 갇힌다」. 왜 멈췄는지와
 *     상관없이 닫는 키는 살아 있어야 한다 — 원인을 없애는 것과 나오는
 *     길을 두는 것은 **따로 해야 한다.** 원인은 또 생기기 때문이다
 */
export const closableWhileStopped = () => true;

/** 사람이 읽는 한 줄 */
export const modeWord = (open = {}) => {
  const on = openList(open);
  return on.length ? `${on.join(' · ')} — ${on.map((n) => MODES[n].key).join(' · ')} 로 닫습니다` : '';
};
