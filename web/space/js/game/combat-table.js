/**
 * 이 무기를 지금 쏠 수 있나.
 * @param s.weapon 무기 · s.target 겨눈 것(없으면 null) · s.locked 묶여 있나
 * @param s.supply 보급 · s.cool 남은 재는 시간 · s.radar 레이더가 켜졌나
 */
export function whyNotFire(s = {}) {
  const w = s.weapon;
  if (!w) return 'none';
  const sup = s.supply ?? {};
  // ★★ v69 — 미사일이 **제 주머니**를 쓴다 (사장님 「미사일 저장고도
  //   따로 만들어서 재고를 관리할 수 있도록」). v68 까지 부품을 썼는데,
  //   그러면 「고치는 것」과 「쏘는 것」이 한 주머니라 벌이 하나뿐이었다 —
  //   미사일을 아끼는 이유와 수리를 아끼는 이유가 같은 것이 되어 버린다
  // ★ v84 — 시험 동안은 **재고로 안 막는다** (`MISSILES.infinite`)
  if (!MISSILES.infinite
    && ((w.cost.ore ?? 0) > (sup.ore ?? 0)
      || (w.cost.parts ?? 0) > (sup.parts ?? 0)
      || (w.cost.missiles ?? 0) > (sup.missiles ?? 0))) return 'ammo';
  if ((s.cool ?? 0) > 0) return 'reload';
  if (!s.target) return 'none';
  if (w.needLock && !s.radar) return 'radar';
  if (w.needLock && !s.locked) return 'lock';
  if (s.target.dist > w.rMax) return 'far';
  if (s.target.dist < w.rMin) return 'near';
  return null;
}

/** 발사 봉투 안인가 — 조준경이 「사거리」를 이걸로 띄운다 */
export const inEnvelope = (w, dist) => dist >= w.rMin && dist <= w.rMax;

/**
 * 맞을 확률 — **봉투의 끝으로 갈수록 떨어진다.**
 * 실제로도 R_max 근처에서 미사일은 에너지가 없어 잘 못 맞힌다.
 */
export function hitChance(w, dist) {
  if (!inEnvelope(w, dist)) return 0;
  const mid = (w.rMin + w.rMax) / 2;
  const half = (w.rMax - w.rMin) / 2;
  const off = Math.abs(dist - mid) / half;          // 0 가운데 · 1 끝
  return (w.pk ?? 1) * (1 - 0.45 * off * off);
}

/** 사람에게 — **숫자로 안 띄운다** */
export function lockWord(l) {
  if (!l.on) return '레이더 꺼짐';
  if (l.locked) return '묶었습니다';
  if (l.t > 0) return '묶는 중';
  return '탐색 중';
}

/** 겨눈 것이 원뿔 안인가 */
export const inCone = (az, el) =>
  Math.abs(az) <= RADAR.az && Math.abs(el) <= RADAR.el;

/**
 * ★★★ **v69 — 이 검사가 「아니오」로 뒤집혔다.**
 *
 *   v68 까지 「표적이 뜨는 범위가 원뿔 안에 다 들어오나」를 물었고,
 *   답이 「예」여야 했다 — 안 그러면 **보이는데 레이더에 없는** 것이
 *   생기고 그건 계기가 거짓말하는 것이었다. 맞는 말이었다,
 *   **표적이 앞쪽 ±62도에만 뜰 때는.**
 *
 *   v69 에 표적이 **사방(±180)** 에 뜬다 (`WAR.md` — 적진을 뚫는다).
 *   그러면 원뿔(±66)이 하늘을 덮을 수가 없고, **덮으면 안 된다**:
 *   덮는 순간 레이더가 전지가 되어 **기수를 돌릴 이유가 사라진다.**
 *
 *   ★ 그래서 규칙을 바꾼다 — **못 보는 데가 있는 것이 설계다.**
 *     · 고도는 여전히 덮는다 (위아래는 기수로 못 쫓아가므로)
 *     · 방위는 안 덮는다. 대신 **원뿔 밖은 수동으로 안다** (아래)
 */
export const coneCoversEl = () => RADAR.el >= TARGET.elLimit;

/** 방위 중 원뿔이 못 보는 몫 (0~1) — 「뒤가 있다」를 검사가 센다 */
export const blindShare = () => Math.max(0, 1 - RADAR.az / 180);

/**
 * ★★★ **원뿔 밖 — 수동 접촉** (v69).
 *
 *   레이더는 앞만 훑지만, **엔진을 켠 것은 뒤에서도 뜨겁다.** 실제로도
 *   전투기의 적외선 탐색·추적(IRST)이 그렇게 쓰인다.
 *
 *   ★ 그래서 원뿔 밖에서 보이는 것은 **엔진이 있는 것뿐**이다 —
 *     파편도 죽은 위성도 안 보인다. 그러면 등 뒤의 점 하나가 곧
 *     **「적이다」**가 되어, 글로 안 알려주고도 뜻이 선다.
 *
 * @property range 이 안이면 수동으로 잡힌다 (m). 원뿔보다 **넓다** —
 *                 열은 멀리 간다. 대신 **거리를 모른다**
 */
export const PASSIVE = { range: 340 };

/**
 * 한 표적을 레이더가 얼마나 아나.
 *
 * @returns 'full'  원뿔 안 + 사거리 안 — 자리와 거리를 다 안다
 *          'blip'  원뿔 밖인데 엔진이 있다 — **방위만** 안다
 *          null    모른다
 */
export function contactLevel(t, hot) {
  if (inCone(t.relAz, t.relEl) && t.dist <= RADAR.range) return 'full';
  if (hot && t.dist <= PASSIVE.range) return 'blip';
  return null;
}
