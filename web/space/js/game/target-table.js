/**
 * 무게를 보고 하나 고른다.
 * ★ `weight: 0` 인 것은 **떠도는 것에 안 섞인다** — 적 우주선이 그렇다.
 *   섞으면 「하늘에 셋」 안에 적이 들어가 버려서, 적이 뜨면 주울 것이
 *   줄어든다. 적은 **제 시계**(`raiderEvery`)로 따로 온다
 */
export function pickKind(rnd) {
  const all = Object.values(KINDS).filter((k) => k.weight > 0);
  const total = all.reduce((s, k) => s + k.weight, 0);
  let r = rnd() * total;
  for (const k of all) { r -= k.weight; if (r <= 0) return k; }
  return all[0];
}

/** 사람에게 보이는 한 줄 — **숫자로 안 띄운다** */
export function rangeWord(dist) {
  if (dist > TARGET.range) return '사거리 밖';
  if (dist > TARGET.range * 0.6) return '멀다';
  if (dist > TARGET.gone * 2.2) return '사거리 안';
  return '지나갑니다';
}

