/** 이 거리에서 적탄이 맞을 확률 */
export function enemyHitChance(dist) {
  const [near, far] = ENEMY_FIRE.hit;
  const t = Math.max(0, Math.min(1, dist / ENEMY_FIRE.range));
  return near + (far - near) * t;
}
