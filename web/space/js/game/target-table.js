/**
 * ★★ **겨눔이 부위를 정한다.**
 *
 * @param off   조준 오차 (도) — 작을수록 한가운데
 * @param tol   그 무기의 허용 각 (도)
 * @param behind 내가 저쪽 **뒤**에 있나 (0~1 · 1 이면 정후면)
 */
export const CORE_AT = 0.34;
export function partOf(off, tol, behind = 0, rnd = Math.random) {
  const k = Math.max(0, Math.min(1, (off ?? 0) / Math.max(1e-6, tol)));
  // ★ 한가운데에 얼마나 붙었나 — `CORE_AT` 안쪽이라야 핵심이 나온다
  if (k <= CORE_AT && rnd() < 0.55 - k) return PARTS.core;
  // ★ 뒤를 잡았으면 엔진, 정면이면 무기 — 실제로 그 자리가 보인다
  if (behind > 0.55 && rnd() < 0.55) return PARTS.engine;
  if (behind < 0.25 && rnd() < 0.40) return PARTS.gun;
  return PARTS.hull;
}

