/** 닳아서 생기는 것만 — 장면이 주는 것(drift)은 뺀다 */
export const EARNED = Object.values(SCARS).filter((s) => !s.fromScene);

/** 사람에게 보이는 한 줄 — 정비실 진단대가 쓴다 */
export function scarWord(keys = []) {
  if (!keys.length) return '영구 손상 없음';
  return keys.map((k) => SCARS[k]?.name ?? k).join(' · ');
}

/** 이 계통이 지금 흉터를 받을 만큼 닳았나 */
export const worn = (wear, sys) => (wear?.[sys] ?? 0) >= SCAR.scarAt;
