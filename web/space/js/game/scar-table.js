//    그래서 「세 번」은 살리되 **무엇을 세는지**를 바꿨다:
//
//      **그 계통이 닳아 있는 채로(`scarAt` 위) 고친 것이 세 번**
//
//    닳기 전에 고치면 안 센다. 즉 **혹사한 것만 흉터가 된다** —
//    쟀더니 혹사 2개 · 보통 1개 · 조심 0개로 갈렸다.
//
//  ★★ 그리고 **전력 흉터는 안 만든다** — 재 보니 성립하지 않는다
//    §8 은 「전력 손상 → 차단기가 셋 중 하나만」도 적어 뒀는데, 전력 마모는
//    `WEAR.rate` 가 `base` 뿐이라 **아무리 혹사해도 안 찬다.** 어느
//    프로필로 2시간을 돌려도 「닳은 채로 고침」이 0~1회였다.
//    없는 조건에 걸어 두면 **표에는 있는데 게임에서 한 번도 안 뜨는** 것이
//    되고, 그게 v46 까지의 장면 B 였다. 걸 자리가 생기면 그때 만든다.
//
//  ★ three.js 를 안 쓴다 — tools/space-scar.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

