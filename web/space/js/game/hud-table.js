/** 조준경 캔버스 크기 — **여기가 한 곳이다** (`world/gunsight.js` 가 읽는다) */
export const PLATE = { w: 1024, h: 768 };

/**
 * ★★★ **각(도) → 판 위 반지름** (판 높이 대비).
 *
 *   ★ 조준경과 `tools/space-hud.js` 가 **같은 자를 쓴다.** 도구가 제
 *     방식으로 다시 재면 「도구는 초록인데 화면은 겹치는」 상태가 되고,
 *     그게 v91~v98 에 네 판을 태운 병이다.
 *   ★ 판은 눈앞의 **평면**이라 각 θ 는 `tan θ` 자리에 찍힌다 (비례가 아니다)
 */
export const radiusOf = (deg, fovH) =>
  (PLATE.w / PLATE.h) * 0.5 * Math.tan((deg * Math.PI) / 180)
  / Math.tan((fovH / 2) * (Math.PI / 180));

