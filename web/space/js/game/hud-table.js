/** 줄이 차지하는 칸 (y0 ~ y1) */
export const spanOf = (r) => ({ y0: r.y - r.size, y1: r.y + r.size * 0.25 });

/** 두 줄이 겹치나 */
export function rowsOverlap(a, b) {
  const p = spanOf(a), q = spanOf(b);
  return p.y0 < q.y1 && q.y0 < p.y1;
}
