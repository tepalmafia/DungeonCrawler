export const READ = {
  /** 화면에서 이만큼은 돼야 읽힌다 (화소) */
  minPx: 15,
  /** 기준 화면 세로 (화소) — 이보다 큰 화면에서는 더 커진다 */
  screenH: 760,
  /** 주 카메라 화각 (도) — `main.js` 의 `FOV_WIDE` 와 같은 값 */
  camFov: 72,
};

/** 조준경이 화면 세로의 몇 할을 덮나 (0~1) */
export function plateShare(hudFovV) {
  const R = Math.PI / 180;
  return Math.tan((hudFovV / 2) * R) / Math.tan((READ.camFov / 2) * R);
}
/** 판 높이 대비 **최소 글자 크기** — 이보다 작으면 화면에서 못 읽는다 */
export function minSize(hudFovV) {
  return READ.minPx / (plateShare(hudFovV) * READ.screenH);
}
/** 판 대비 크기를 화면 화소로 — 도구가 이 값을 읽는다 */
export const toPx = (size, hudFovV) => size * plateShare(hudFovV) * READ.screenH;

