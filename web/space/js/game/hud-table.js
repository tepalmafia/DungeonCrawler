export const WOBMAX = 0.30;

// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **자세계** — 「비행기 현재 회전 상태」 (v103 · 두 번째 판)
//
//  ★ 사장님 「**비행기 현재 회전 상때도 도입했어?**」
//
//  ══ ★★ 첫 판은 **절반이었다** ═════════════════════════════════════════
//
//  수평의를 넣으면서 선을 **늘 화면 복판**에 그렸다. 그러면 「얼마나
//  기울었나」(롤)만 보이고 **「기수가 얼마나 들렸나」(피치)는 안 보인다.**
//  실기의 자세계(ADI)는 그 둘이 **한 벌**이다:
//
//      고정된 기수 표시(waterline)  —  이 배의 십자선. 늘 복판
//      움직이는 수평선              —  세상의 수평. **기울고 · 오르내린다**
//      그 사이의 벌어짐             =  **지금 기수 각**
//
//  ★★★ 즉 피치는 **새 표식이 아니라 수평선을 옮기는 것**이다. 선을
//    복판에 못박아 두면 그 정보가 통째로 사라진다 — 첫 판이 그랬다.
//
//  ★ 눈금(사다리)이 있어야 「얼마나」가 숫자로 읽힌다. 실기와 같은
//    10도 간격을 쓴다
// ══════════════════════════════════════════════════════════════════════════
export const ADI = {
  /** 사다리 눈금 간격 (도) — 실기와 같다 */
  step: 10,
  /**
   * 위아래로 이만큼까지 그린다 (도).
   * ★★ v105 — 40 → 20. 여덟 칸을 늘 그렸더니 **판이 빗금으로 덮였다**
   *   (사장님 「조잡하잔아」). 눈금은 「얼마나」를 말하는 것이지 배경이 아니다
   */
  span: 20,
  /**
   * ★★ 수평선이 판 밖으로 나가도 **가장자리에 붙어 남는다**.
   *   기수를 90도 들면 수평선은 저 아래라 화면에서 사라지는데, 그러면
   *   「지금 얼마나 들렸나」를 볼 방법이 없어진다 — 실기도 이럴 때
   *   **화살표로 어느 쪽인지** 알려 준다 (0~1 · 판 높이 대비)
   */
  pin: 0.42,
  /** 이 각을 넘으면 「많이 들렸다」로 보고 색이 바뀐다 (도) */
  steep: 45,
  /**
   * ★★★ **사다리를 접는다** (참 크기의 몇 배로 그리나).
   *
   *   ★ 재고 알았다: 조준경은 세로로 **20.1도**만 덮는다 (`hudFov`).
   *     참 크기로 그리면 **기수를 10도만 들어도 수평선이 판 끝**이고
   *     (0.99), 20도면 아예 밖이다 (2.05). 즉 참 크기 사다리는
   *     **±10도짜리 계기**가 된다 — 우주선은 360도를 도는데.
   *
   *   ★★ **실기 HUD 도 사다리를 압축한다.** 참 크기로 그리면 급기동
   *     중에 사다리가 화면을 쓸고 지나가 아무것도 못 읽기 때문이다.
   *     여기서 접는 것은 흉내가 아니라 **같은 이유의 같은 해법**이다.
   *
   *   ★ 대신 잃는 것을 적어 둔다: 수평선이 **창밖의 진짜 지평선과
   *     안 겹친다** (행성 가까이에서만 보이는 그것). 이 게임은 우주가
   *     대부분이라 그 손해가 작고, 얻는 것(±40도가 다 읽힌다)이 크다.
   *     0.20 은 ±40도가 판의 ±0.95 에 들어오게 맞춘 값이다
   */
  squeeze: 0.20,
  /**
   * ★★★ v105 — **이만큼 기울거나 들렸을 때만 사다리를 그린다** (도).
   *
   *   ★ 수평일 때 사다리는 **아무것도 안 말한다** — 십자선이 이미 복판에
   *     있으므로. 그런데 늘 그리고 있었고, 그것이 화면을 덮은 주범이다.
   *   ★★ 계기는 **할 말이 있을 때만** 말한다 (이 저장소의 오랜 규약 —
   *     늘 떠 있는 경고는 경고가 아니다)
   */
  showFrom: 8,
};

/** 사다리에 그릴 눈금들 (0 은 수평선 자신이라 뺀다) */
export const rungs = () => {
  const out = [];
  for (let d = ADI.step; d <= ADI.span; d += ADI.step) { out.push(d, -d); }
  return out;
};

/** 사람이 읽는 한 마디 — 기수가 얼마나 들렸나 */
export function pitchWord(el) {
  const d = Math.round(el);
  if (Math.abs(d) < 3) return '수평';
  return `${d > 0 ? '기수 올림' : '기수 내림'} ${Math.abs(d)}°`;
}

