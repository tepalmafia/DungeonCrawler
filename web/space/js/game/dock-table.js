// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **도킹 회수** — 붙어서 가져온다 (v101). 숫자만. 규칙은 `dock.js`.
//
//  ★ 사장님 「격추후에 상대 행성이나 물체에 **도킹해서 회수**할 수 있도록
//    **락온하고 다가가서 도킹** 해서 아이템을 회수할 수 있도록 해야지.
//    **아이템을 먹을 방법이 없거나 어렵잔아.** 블록아웃으로 먼저 설계하고」
//
//  ══ 왜 지금이 어려운가 — 재 보고 적는다 ═══════════════════════════════
//
//  회수 방법이 셋 있다 (`cargo-table.js WAYS`):
//
//    도킹 팔  25m 까지 · 1.2초   ← **25m 는 선체 반지름(21m) 바로 밖이다**
//    그물     80m 까지 · 감는 동안 못 나아간다
//    로봇     160m 까지 · 12초
//
//  그런데 꾸러미는 **55초만 떠 있고**(`PACK.live`) 부순 자리에서
//  **밀려난다**(`drift`). 그 사이에 다음 물결이 온다 (`wave.gap` 7~13초).
//  즉 「부수고 → 겨누고 → 쏘고 → 감고」를 다음 적이 오기 전에 끝내야 하고,
//  그물은 감는 동안 **추진이 묶인다.** 그래서 사장님 말씀대로 **어렵다.**
//
//  ══ ★★★ 도킹이 그것을 어떻게 푸나 ════════════════════════════════════
//
//    · **조준이 아니라 조종이다.** 겨눠서 쏘는 것이 아니라 **가서 붙는다** —
//      v101 의 스로틀(전진·역추진)이 그대로 조작이 된다
//    · **묶은 것에 붙는다.** 락온을 이미 하고 있으므로 새 동작이 아니다
//    · **한 번에 여럿을 담는다.** 그물은 하나씩인데, 도킹은 **붙어 있는
//      동안 계속** 들어온다 — 「먹을 방법이 어렵다」의 답이 여기다
//    · 대신 **붙어 있는 동안 못 움직이고**, 적이 오면 그대로 맞는다
//
//  ★ three.js 를 안 쓴다 — `tools/space-dock.js` 가 읽는다.
// ══════════════════════════════════════════════════════════════════════════

/** 마디 — 안 함 → 다가감 → 붙음 → 빨아들임 */
export const DSTEP = {
  NONE: 'none',
  /** 락온한 것으로 다가가는 중. 계기가 거리와 접근율을 적는다 */
  CLOSE: 'close',
  /** 붙었다 — 걸쇠가 물렸다 */
  LATCH: 'latch',
  /** 들어오는 중 — **붙어 있는 동안 계속** */
  PULL: 'pull',
};

export const DOCK = {
  /**
   * ★★★ **이만큼 붙어야 걸린다** (m).
   *   32 — 선체 반지름(`HULL.radius` 21)보다 **밖**이다. 안으로 잡으면
   *   들이받는 것과 도킹이 같은 자리가 되어 「부딪혔는데 도킹됐다」가 난다
   */
  reach: 32,
  /**
   * ★★ **이보다 빠르면 못 문다** (m/초) — 걸쇠가 튕긴다.
   *   그래서 **역추진으로 속도를 죽여야** 하고, v101 의 스로틀이
   *   여기서 값을 한다. 그냥 들이받으면 도킹이 아니라 충돌이다
   */
  softAt: 12,
  /** 너무 빨리 닿으면 선체가 이만큼 깎인다 (0~1) */
  hardWear: 0.035,
  /** 걸쇠가 물리는 데 걸리는 초 */
  latch: 1.4,
  /** 붙어 있는 동안 **초당 몇 개**가 들어오나 */
  rate: 1.6,
  /**
   * ★ 붙어 있는 동안 **못 움직인다.** 그물과 같은 값이다 —
   *   「주우려면 도망칠 수 없다」가 이 배의 오랜 규약이다
   */
  holdsThrust: true,
  /** 붙어 있는 동안 자국이 이만큼 오른다 (초당) — 가만히 붙어 있으면 훤하다 */
  sign: 3.5,
  /** 이 각 안에 있어야 붙는다 (도) — 뒤로는 못 문다 */
  cone: 42,
};

/** 왜 못 붙나 — **조용히 안 되면 「고장」으로 읽힌다** (이 배의 규약) */
export const WHY = {
  none: '묶은 것이 없습니다',
  far: '너무 멉니다 — 더 다가가야 합니다',
  fast: '너무 빠릅니다 — 역추진으로 줄이십시오',
  side: '정면으로 붙어야 합니다',
  full: '화물칸이 꽉 찼습니다',
  busy: '이미 물려 있습니다',
};

/**
 * 왜 못 붙나 — 되면 `null`.
 * @param dist  묶은 것까지 거리 (m)
 * @param close 다가가는 속도 (m/초 · 양수가 다가가는 것)
 * @param off   기수에서 벗어난 각 (도)
 */
export function whyNotDock({ has = false, dist = 999, close = 0, off = 0, full = false, step = DSTEP.NONE } = {}) {
  if (step !== DSTEP.NONE && step !== DSTEP.CLOSE) return 'busy';
  if (!has) return 'none';
  if (full) return 'full';
  if (dist > DOCK.reach) return 'far';
  if (off > DOCK.cone) return 'side';
  if (close > DOCK.softAt) return 'fast';
  return null;
}

/** 계기가 적는 한 마디 */
export function dockWord(d) {
  if (!d || d.step === DSTEP.NONE) return '해제';
  if (d.step === DSTEP.CLOSE) return '접근';
  if (d.step === DSTEP.LATCH) return '결합 중';
  return '회수 중';
}

