// ══════════════════════════════════════════════════════════════════════════
//  ★★★ v114 — **화면이 넓어지면 계기가 하늘로 걸어 들어온다** (UHD 정렬)
//
//  ★ 사장님 (2026-08-11) 「**화면 uhd 정렬좀해 시야를 안가리게**」
//
//  ══ 왜 그런가 — 짐작이 아니라 셈이다 ═══════════════════════════════
//
//  계기 셋은 **배에 박힌 3D 판**이고, 자리를 `HUDV.w * 1.42` 처럼
//  **미터**로 적어 두었다. 그런데 화면 좌표는 이렇게 나온다:
//
//        nx = x / (dist · tan(fov/2) · **aspect**)
//        ny = y / (dist · tan(fov/2))
//
//  ★★★ **가로에만 `aspect` 가 있다.** 즉 화면이 넓어질수록(21:9 · UHD
//    가로배치) 같은 미터가 **더 작은 nx** 가 되어, 판이 **화면 복판으로
//    걸어 들어온다.** 세로는 안 변하니 「아래는 그대론데 옆에서 조여드는」
//    모양이 되고, 그게 사장님이 보신 화면이다. 반대로 세로로 긴 창에서는
//    판이 **화면 밖으로 걸어 나간다** — 레이더 아랫줄이 잘리던 그 병이다.
//
//  ★ v103 은 이것을 **한 해상도(1280×760)에서** 재고 고쳤다. 그래서
//    그 해상도에서만 맞았다. **한 화면만 재는 검사는 절반**이다 —
//    v98 의 「정면만 보면 안 잡힌다」와 같은 종류의 실수다.
//
//  ══ 그래서 고치는 방법 ═════════════════════════════════════════════
//
//  자리를 **미터로 적지 않고 화면 좌표(`ANCHOR`)로 적는다.** 창 크기가
//  바뀔 때마다 `worldAt()` 이 그때의 aspect 로 미터를 **다시 낸다.**
//  그러면 판은 4:3 이든 32:9 든 **늘 같은 구석**에 있다.
