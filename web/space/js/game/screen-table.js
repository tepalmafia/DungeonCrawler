/**
 * ★★★ **화소 수가 아니라 aspect 가 자리를 바꾼다** — 재서 확인한 것이다.
 *
 *   처음에 3840×2160 과 3440×1440 을 그대로 띄워 재려다 **소프트웨어
 *   렌더러에서 5분을 넘겨** 검사가 끝나지 않았다. 그런데 위 식을 보면
 *   `nx` 에 들어가는 것은 **`aspect` 뿐**이고 화소 수는 어디에도 없다 —
 *   즉 1600×900 과 3840×2160 은 **정확히 같은 자리**에 그린다.
 *   그래서 **같은 비율의 작은 창**으로 잰다. 값이 같다는 것을 아는 채로
 *   싼 쪽을 고르는 것과, 몰라서 안 재는 것은 다르다.
 */
export const ASPECT_ONLY = true;

/**
 * ★★★ **화면 좌표 → 배 안의 미터.**
 *
 *   ★ 게임도 도구도 **이 함수 하나**를 부른다. `main.js` 가 제 방식으로
 *     `HUDV.w * 1.42` 를 다시 적기 시작하면 그때부터 갈라진다 —
 *     이 저장소가 자리를 아는 곳을 넷으로 두고 네 판을 태운 적이 있다
 *
 * @param nx,ny  놓고 싶은 화면 좌표 (−1~1)
 * @param dist   눈에서 판까지 (m)
 * @param fovDeg 카메라 **세로** 화각 (도)
 * @param aspect 가로/세로
 */
export function worldAt({ nx, ny, dist, fovDeg, aspect }) {
  const t = Math.tan((fovDeg * Math.PI) / 360) * dist;
  return { x: nx * t * aspect, y: ny * t };
}

/**
 * ★★ **바깥 모서리를 구석에 대고 놓았을 때의 복판** (화면 좌표).
 *
 * @param name 판 이름 · @param halfW,halfH 판의 반쪽 크기 (화면 좌표)
 */
export function centerFor(name, halfW, halfH) {
  const a = ANCHOR[name];
  if (!a) return { nx: 0, ny: 0 };
  return { nx: a.x - Math.sign(a.x) * halfW, ny: a.y - Math.sign(a.y) * halfH };
}

/** 상자가 원뿔을 건드리나 — 상자에서 복판까지 **제일 가까운 점**으로 잰다 */
export function hitsCone(b) {
  const dx = Math.max(b.x0, Math.min(0, b.x1));
  const dy = Math.max(b.y0, Math.min(0, b.y1));
  return Math.hypot(dx, dy) < CONE;
}

/** 화면 밖으로 잘렸나 */
export const isCut = (b) =>
  b.x0 < -EDGE || b.x1 > EDGE || b.y0 < -EDGE || b.y1 > EDGE;

/** 두 상자가 겹치나 — 겹치면 둘 다 못 읽는다 */
export const overlaps = (a, b) =>
  a.x0 < b.x1 && b.x0 < a.x1 && a.y0 < b.y1 && b.y0 < a.y1;

/** 이 판이 제 구석에 있나 */
export function inCorner(name, b) {
  const [sx, sy] = PANELS[name]?.corner ?? [0, 0];
  if (sx && Math.sign(b.cx) !== sx) return false;
  if (sy && Math.sign(b.cy) !== sy) return false;
  return true;
}
