/**
 * ★★★ **전투 원뿔** — 화면 복판 이 반지름 안은 **조준경만** 쓴다.
 *
 *   정규화 화면 좌표(−1~1)의 반지름이다. 0.45 는 재서 골랐다:
 *   조준경이 가로 0.13 · 세로 0.17 을 쓰고, 표적 지시선(TLL)이
 *   `min(w,h)*0.44` 까지 뻗는다 (`world/gunsight.js`). 그 둘을 다 담고
 *   조금 여유를 둔 값이 0.45 다. 여기에 판이 들어오면 **조준하는 눈이
 *   판에 걸린다** — 사장님이 「전투화면이 더 광활하게」라고 하신 자리다
 */
export const CONE = 0.45;

/** 화면 밖으로 이만큼까지는 봐준다 — 이 밖은 **잘려서 못 읽는다** */
export const EDGE = 0.99;

/**
 * ★★ 계기 셋(조준경 뺀)이 합쳐서 화면의 몇 할까지 쓰나.
 *   지금이 17.9% 다. **14%** 로 조인다 — 셋을 다 지울 수는 없고
 *   (레이더 없이 못 싸운다) 셋 다 조금씩 줄이면 눈에 띄게 넓어진다
 */
export const BUDGET = 0.14;

/**
 * 판마다 **어느 구석인가** · **얼마나 커도 되나**.
 *
 * @property corner  x · y 의 부호. `0` 이면 아무 쪽이나 (조준경)
 * @property area    화면 넓이의 몇 할까지 (0~1)
 * @property inCone  전투 원뿔 안에 들어와도 되나 — **조준경만 참**
 */
export const PANELS = {
  조준경: { corner: [0, 0], area: 0.035, inCone: true, what: 'HUD — 겨누는 곳' },
  /**
   * ★★ **왼쪽 위.** v95 에 사장님이 「적을 확대해서 보는 화면이 아래로
   *   바뀌었는데 **화면이 안보이잔아 원래 자리로 복구해**」 하셨으므로
   *   하늘에 둔다. 다만 **구석으로 더 민다** — 지금은 복판에서 0.27 이다
   */
  광학창: { corner: [-1, 1], area: 0.045, inCone: false, what: '당겨 본다' },
  상태창: { corner: [-1, -1], area: 0.045, inCone: false, what: '배가 어떤가' },
  레이더: { corner: [1, -1], area: 0.05, inCone: false, what: '어디에 무엇이' },
};

/** 상자가 원뿔을 건드리나 — 상자에서 복판까지 **제일 가까운 점**으로 잰다 */
export function hitsCone(b) {
  const dx = Math.max(b.x0, Math.min(0, b.x1));
  const dy = Math.max(b.y0, Math.min(0, b.y1));
  return Math.hypot(dx, dy) < CONE;
}

/** 화면 밖으로 잘렸나 */
export const isCut = (b) =>
  b.x0 < -EDGE || b.x1 > EDGE || b.y0 < -EDGE || b.y1 > EDGE;

/** 두 상자가 겹치나 — 겹치면 둘 다 못 읽는다 */
export const overlaps = (a, b) =>
  a.x0 < b.x1 && b.x0 < a.x1 && a.y0 < b.y1 && b.y0 < a.y1;

/** 이 판이 제 구석에 있나 */
export function inCorner(name, b) {
  const [sx, sy] = PANELS[name]?.corner ?? [0, 0];
  if (sx && Math.sign(b.cx) !== sx) return false;
  if (sy && Math.sign(b.cy) !== sy) return false;
  return true;
}
