//    ★ 대신 **껐다 켜는 키 하나**(F)는 둔다 — 360도를 원하는 사람이 있다.
//
//  ★★★ 그러면 **수평의는 왜 만드나.** 보조를 껐을 때 읽으라고. 그리고
//    보조가 켜져 있어도 **되돌아가는 중**에는 잠깐 기울어 있으므로,
//    「지금 배가 스스로 바로 서는 중」이 눈에 보여야 한다. 계기는 남고,
//    다만 **주인공이 아니라 확인용**이 된다
