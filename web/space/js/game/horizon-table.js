// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **수평의** — 지금 똑바로인가 (v103). 숫자만.
//
//  ★ 사장님 「처음에는 정상적으로 움직이는데 **비행기를 q e로 뒤집으면
//    반대가 되는 것 같은데??** 그렇다면 **내가 지금 똑바로 유지하고
//    있는지를 표시해줘야 하나?**」
//
//  ══ ★★ 이건 버그가 아니라 물리다 — 그리고 사장님 물음이 답이다 ═══════
//
//  180도 뒤집힌 채로 조종간을 「위」로 밀면 기수는 **세상 기준 아래**로
//  간다. 실제 비행기가 다 그렇다 — 조종은 **동체 기준**이고 눈은
//  **세상 기준**으로 보기 때문이다. 부호를 뒤집어 고칠 것이 아니다
//  (뒤집으면 똑바로일 때가 반대가 된다).
//
//  ★★★ 실기가 이것을 푼 방법이 **수평의**다: 「지금 어느 쪽이 위인가」를
//    늘 보여 준다. 그러면 반대로 가는 것이 **놀랄 일이 아니라 읽을 수
//    있는 일**이 된다. 조종사는 뒤집힌 줄 알고 반대로 민다.
//
//  ★ 그래서 만드는 것은 「반대를 없애는 것」이 아니라 **「뒤집힌 줄 알게
//    하는 것」**이다 — 사장님이 물음 끝에 스스로 답하신 그대로다.
//
//  ★ three.js 를 안 쓴다 — `tools/space-horizon.js` 가 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const HORIZON = {
  /** 이 각을 넘으면 **뒤집힌 것**으로 본다 (도) */
  overAt: 90,
  /** 이 안이면 「똑바로」라고 한다 (도) — 딱 0 을 맞출 수는 없다 */
  levelAt: 8,
  /** 이 각을 넘으면 계기가 **경고 색**으로 바뀐다 (도) */
  warnAt: 45,
  /** 수평의 눈금 (도) — 이 간격으로 눈금을 긋는다 */
  tick: 30,
};

/** −180~180 으로 감는다 */
export const wrapDeg = (d) => ((d + 180) % 360 + 360) % 360 - 180;

/** 지금 뒤집혔나 */
export const isOver = (rollDeg) => Math.abs(wrapDeg(rollDeg)) > HORIZON.overAt;
/** 똑바른가 */
export const isLevel = (rollDeg) => Math.abs(wrapDeg(rollDeg)) <= HORIZON.levelAt;

/**
 * ★★ 사람이 읽는 한 마디 — **계기가 이 한 줄만 쓴다.**
 *   숫자만 주면 「−137도」로는 아무것도 못 정한다. 뒤집혔다는 말이 먼저다
 */
export function rollWord(rollDeg) {
  const r = wrapDeg(rollDeg);
  if (isLevel(r)) return '수평';
  if (isOver(r)) return '★ 뒤집힘 — 조종이 반대입니다';
  return `${r > 0 ? '우' : '좌'} ${Math.abs(r).toFixed(0)}° 기움`;
}

/**
 * ★★★ **조종간을 위로 밀면 세상에서 어느 쪽으로 가나** (+1 위 · −1 아래).
 *   뒤집히면 −1 이다. 이 값이 곧 사장님이 겪으신 「반대」이고,
 *   계기는 이것을 **미리** 말해 줘야 한다
 */
export const pitchWay = (rollDeg) => (isOver(rollDeg) ? -1 : 1);

// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **비행 보조** — 계기만으로는 안 된다 (v103 · 두 번째 물음)
//
//  ★ 사장님 「**물리방향으로 움직이니 게임이 너무 어렵게 느껴지는데?**」
//    「화면에 현재 배의 모습을 나타내는 hud를 만들어야하나?
//     아니면 **수평 유지 단축키**를 만들어야하나?」
//
//  ══ ★★ 재 보니 **둘 다 아니었다** ══════════════════════════════════════
//
//  ★ 뒤집힘을 만드는 축은 **롤 하나뿐**이다. 피치·요는 아무리 돌려도
//    조종이 안 뒤집힌다 (동체 기준이라 늘 같은 쪽으로 간다). Q/E 만이
//    「위가 아래가 되는」 일을 한다 — 사장님이 「**q e 로 뒤집으면**」이라고
//    정확히 짚으셨다.
//
//  ★★★ 그리고 **롤은 겨냥에 안 쓰인다.** 이 저장소가 이미 적어 둔 값이
//    그렇게 말한다: `OFF_WEIGHT.roll = 0.35` — 「롤은 궤도를 안 바꾼다.
//    다만 라디에이터와 안테나가 엉뚱한 데를 본다」. 즉 **롤을 저절로
//    되돌려도 잃는 것이 없다.** 피치·요를 되돌리면 겨냥을 뺏는 것이라
//    절대 안 되지만, 롤은 아니다.
//
//  ★ 그래서 만드는 것은 **자동 수평(비행 보조)** 이고 **기본은 켜짐**이다.
//    손을 Q/E 에서 떼면 배가 스스로 수평으로 돌아온다 → 뒤집힌 채로
//    **머무를 수가 없어** 「반대」가 아예 안 생긴다.
//
//  ★★ **단축키는 안 만든다.** 보조가 켜져 있으면 누를 일이 없고, 껐다면
//    그건 「내가 잡겠다」고 고른 것이다. 키를 하나 더 만드는 것은
//    **문제를 손에 떠넘기는 것**이지 푸는 것이 아니다.
//    ★ 대신 **껐다 켜는 키 하나**(F)는 둔다 — 360도를 원하는 사람이 있다.
//
//  ★★★ 그러면 **수평의는 왜 만드나.** 보조를 껐을 때 읽으라고. 그리고
//    보조가 켜져 있어도 **되돌아가는 중**에는 잠깐 기울어 있으므로,
//    「지금 배가 스스로 바로 서는 중」이 눈에 보여야 한다. 계기는 남고,
//    다만 **주인공이 아니라 확인용**이 된다
// ══════════════════════════════════════════════════════════════════════════

export const ASSIST = {
  /** ★★★ **기본 켜짐.** 어렵다는 말을 들었으면 기본값을 바꾸는 것이 답이다 */
  on: true,
  /**
   * ★★ 손을 떼면 초당 몇 라디안으로 수평으로 돌아오나.
   *
   *   ★ **새 숫자가 아니다** — `AXES.roll.back`(0.85) 과 같은 값이다.
   *     자동 항법이 이미 쓰는 값이고, 여기서 다른 값을 쓰면 같은 동작이
   *     두 속도를 갖는다 (이 저장소가 제일 자주 밟는 함정이다).
   *   ★★ 손으로 감는 것(`AXES.roll.rate` 1.25)보다 **느리다.** 그래서
   *     급하면 손이 빠르고, 안 급하면 놓고 다른 일을 한다 —
   *     「늘 이게 답」이 안 된다
   */
  rate: 0.85,
  /**
   * ══ ★★★ v111 — **많이 기울수록 빨리 편다** ═══════════════════════════
   *
   *  ★ 사장님 「**뒤집혀서 방향이 반대가 되는데 자동으로 돌아오게 해야지**」
   *    그리고 이어서 「아니야 처음에는 수평을 잡았다. **회전을 계속
   *    하다보니 안되네**」 — 이 둘째 문장이 원인을 정확히 짚으셨다.
   *
   *  ★★ **재 보니 보조가 손보다 느렸다.** 손으로 감는 것이 1.25 rad/s
   *    (`AXES.roll.rate`)인데 보조는 0.85 였다. 잠깐 굴리고 마는 동안에는
   *    문제가 안 나지만, **싸우면서 계속 굴리면** 보조가 영영 못 따라잡는다 —
   *    Q 를 놓는 짧은 틈마다 0.85 로 조금 감다가 다시 1.25 로 감기니까.
   *    그래서 「처음에는 잡았는데 계속 하다 보니 안 되는」 것이 된다.
   *
   *  ★★★ 그런데 `rate` 를 통째로 올리면 **잔 기울기까지 홱 펴져서**
   *    옆으로 눕혀 겨누는 것이 안 된다. 그래서 **기운 만큼 비례해서**
   *    빨라지게 한다: 잔 기울기는 그대로 느긋하고, 뒤집힌 것은 빨리 선다.
   *
   *      5°   0.86 rad/s  (거의 그대로 — 옆으로 눕혀 겨눌 수 있다)
   *      90°  1.70 rad/s
   *      180° 2.55 rad/s  → **1.2초면 바로 선다**
   *
   *  ★ 180도에서 손보다 **두 배 빠르다.** 「자동으로 돌아오게」가 성립하려면
   *    제일 나쁜 자리에서 손보다 빨라야 한다 — 안 그러면 못 이긴다
   */
  steep: 2.0,
  /**
   * ★ 이 안에 들면 딱 0 으로 물린다 (라디안). 안 물리면 0.3도쯤에서
   *   영영 떨고, 계기가 「우 0° 기움」이라고 적는다
   */
  snap: 0.02,
};

/**
 * ★★ 지금 이만큼 기울었을 때 **초당 몇 라디안**으로 펴나 (v111).
 *   `t` 는 −π~π 로 감긴 기울기
 */
export const rateAt = (t) =>
  ASSIST.rate * (1 + ASSIST.steep * Math.min(1, Math.abs(t) / Math.PI));

/**
 * ★★★ **한 프레임에 롤이 얼마나 되돌아오나** (라디안 · 부호 포함).
 *
 *   @param roll   지금 롤 (라디안 · 몇 바퀴든)
 *   @param dt     초
 *   @param hand   지금 손이 Q/E 를 잡고 있나 — **잡고 있으면 안 건드린다**
 *   @param on     보조가 켜져 있나
 *   @returns 더할 값 (0 이면 아무 일 없음)
 *
 *   ★ **제일 가까운 한 바퀴로 간다.** 720도를 되감으면 그건 조종이
 *     아니라 기다림이다 (`flight.js` 의 자동 항법과 같은 규약)
 */
export function levelStep(roll, dt, { hand = false, on = ASSIST.on } = {}) {
  if (!on || hand) return 0;
  const TWO = Math.PI * 2;
  let t = roll % TWO;
  if (t > Math.PI) t -= TWO;
  if (t < -Math.PI) t += TWO;
  if (Math.abs(t) < 1e-6) return 0;
  // ★ 다 왔으면 **딱 0 으로 물린다.** 안 물리면 0.3도쯤에서 영영 떨고,
  //   계기가 「우 0° 기움」이라고 적는다 (경고가 안 꺼진다)
  if (Math.abs(t) <= ASSIST.snap) return -t;
  // ★★★ v111 — 고정 속도가 아니라 **기운 만큼**이다 (위 `steep`)
  const step = Math.min(Math.abs(t), rateAt(t) * dt);
  return -step * Math.sign(t);
}

/** 보조가 켜졌나를 사람 말로 — 계기가 이 한 줄만 쓴다 */
export const assistWord = (on) => (on ? '보조 켜짐 — 저절로 수평' : '★ 보조 꺼짐 — 360°');
