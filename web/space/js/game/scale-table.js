/**
 * ★★★ **속도와 거리에 다 같이 곱하는 값.**
 *
 *  ★ 3.3 은 「지금 급가속(42 m/s)이 새 순항 언저리」가 되는 자리다 —
 *    사장님 「제로백 2초대」의 감각이 거기서 난다
 */
export const SCALE = 3.3;

/** 속도·거리 하나를 축척에 맞춘다 */
export const S = (v) => +(v * SCALE).toFixed(2);

/** 범위 `[a, b]` 를 통째로 */
export const SR = ([a, b]) => [S(a), S(b)];
