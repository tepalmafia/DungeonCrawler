/**
 * ★★★ **창밖이 초당 몇 유닛 흐르나** — **여기가 유일한 답이다.**
 *
 *   ★ 게임도 도구도 이 함수를 부른다. `main.js` 가 제 방식으로 다시
 *     곱하기 시작하면 그때부터 「화면은 빠른데 항로는 안 가는」 것이 난다
 *
 * @param leg   항로 배수 (`throttle.js legOf` 가 준 값 · 0~1)
 * @param back  역추진인가
 * @param boost 급가속 배수 (1 이면 안 씀)
 * @param tow   ★ 끌려가는 속도 (m/s) — 포획으로 **붙으러 갈 때**
 */
export function mpsAt({ leg = 0, back = false, boost = 1, tow = 0, port = false } = {}) {
  // ★ 거점에서는 **천장만** 씌운다 — 못 움직이게 하는 것이 아니다
  const lg = port ? Math.min(leg, SPEED.portCap) : leg;
  const k = back ? SPEED.back : (SPEED.idle + (SPEED.full - SPEED.idle) * Math.max(0, Math.min(1, lg)));
  // ★★ **붙으러 가는 것도 가는 것이다** (사장님 「f로 붙으면 실제로 붙어야지」).
  //   포획이 거리를 줄이는 동안 창밖이 그대로면 **꾸러미가 날아오는** 것으로
  //   보인다. 실제로는 배가 가는 것이므로 그 속도를 여기에 얹는다
  return CRUISE.speed * k * boost + tow;
}

// ══════════════════════════════════════════════════════════════════════════
//  ★★★ v152 — **창밖과 세상이 같은 값을 읽는다** (사장님이 잡으신 것)
//
//  ★ 사장님 (2026-08-14) 「**비행기가 목적지까지 날아는 가는거야? 앞으로
//    이동 중인데 적은 그대로 뒤에 있는데? 추력을 써도 그렇고**」
//
//  ══ 재 보니 **속도를 아는 곳이 둘**이었다 ══════════════════════════════
//
//    창밖 (별 · 먼지 · 속도계)   `mpsAt()` — **스로틀을 읽는다**
//    세상 (표적이 다가오는 것)   `TARGET.closing` **고정 5.5 m/s**
//
//  ★★★ 스로틀은 다가오는 속도에 **한 글자도 안 들어갔다.** 켜지느냐
//    마느냐(`power.thrust`)만 봤으므로 값이 **0 아니면 5.5** 둘뿐이었고,
//    그래서 이런 화면이 났다:
//
//      추력 끔 · 스로틀 최대  → 별은 흐르는데 **아무것도 안 온다**  ← 이것
//      추력 켬 · 스로틀 0    → 별은 안 흐르는데 **다가온다**       (반대로)
//      스로틀 0.38 → 1.0     → 다가오는 속도가 **똑같다**
//
//  ★★ 이 저장소는 이 병을 **이미 두 번 적어 뒀다.** `boost-table.js
//    RUSH.close` 주석이 「v73 이 급가속을 만들면서 넣은 것은 화면뿐이었다 …
//    **가속이 안 느껴지는** 게 아니라 **가속이 없었다**」라고 적고 있고,
//    `main.js` 의 추진제 고갈 자리가 「**「켜 놨는데 안 간다」는 계기가
//    거짓말하는 것이고, 이 배에서 제일 하면 안 되는 일**」이라고 적고 있다.
//    **같은 병을 두 번 고치고도 뿌리를 안 뽑았다** — 뿌리는 「재는 곳이
//    둘」이라는 것 하나다.
//
//  ★★★ 그래서 숫자를 고치지 않고 **자리를 없앴다.** 다가오는 속도는
//    이제 제 값을 안 갖고 **창밖 속도를 나눠서** 쓴다. 갈라질 수가 없다.
// ══════════════════════════════════════════════════════════════════════════

/**
 * ★★★ **순항일 때의 창밖 속도** — 다가오는 속도의 기준점(1배).
 *
 *   ★ `DRIVE.base` 를 여기서 베껴 적지 않고 **불러 온다.** 베끼면 v133 이
 *     「전진이 기본」의 값을 고쳤을 때 이쪽만 옛 값으로 남는다
 */
export const cruiseMps = () => mpsAt({ leg: DRIVE.base });

/**
 * ★★★ **창밖이 이만큼 흐르면 세상은 몇 배로 다가오나.**
 *
 *   순항이 **1배**다 — 그래야 `TARGET.closing`(5.5 m/s)이 뜻하던 것이
 *   그대로 남고, 이 판이 밸런스를 안 건드린다.
 *
 *   ★ 급가속 배수는 **넘겨받은 `mps` 안에 이미 들어 있다** (`mpsAt` 의
 *     `boost`). 여기서 또 곱하면 두 번 세는 것이고, 그게 「재는 곳이 둘」의
 *     새 판이다 — `RUSH.close` 가 이 값으로 대체되는 까닭이다
 *
 *   ★★ 0 으로는 안 떨어진다. 스로틀을 다 내려도 `SPEED.idle`(0.10) 만큼은
 *     흐르고, 우주에서 관성은 진짜로 있다 (v57 고증). **별이 조금 흐르면
 *     세상도 조금 다가와야** 「둘이 같다」가 된다
 *
 * @param mps 지금 창밖이 흐르는 속도 (`mpsAt` 가 낸 값)
 */
export const closeK = (mps) => +(Math.max(0, mps) / cruiseMps()).toFixed(4);

/** 이 속도에서 별줄이 얼마나 긴가 — 새 눈금 */
export function streakAt(mps) {
  if (!(mps > SPEED.streakMin)) return 0;
  const k = (mps - SPEED.streakMin) / (SPEED.streakFast - SPEED.streakMin);
  return +(30 * Math.min(1, Math.max(0, k)) ** SPEED.streakBend).toFixed(2);
}

/**
 * ★★★ **가속도가 얼마나 느껴지나** 0~1.
 *
 *   ★ `d` 는 **이번 걸음의 속도 변화**(mps/초)다. 양수만 센다 —
 *     느려지는 것은 다른 느낌이고, 그건 역추진이 이미 말한다
 */
export const accOf = (d) => Math.max(0, Math.min(1, d / SPEED.accFull));

/**
 * ★★ **가속 신호가 삭는다** — 등속이 되면 사라진다.
 * @param k 지금 값 · @param want 이번 걸음의 목표
 */
export function fadeAcc(k, want, dt) {
  if (want > k) return want;                       // 오를 때는 바로
  return Math.max(want, k - dt / SPEED.accFade);   // 내릴 때만 천천히
}

/** 가속이 화면에 얼마나 나오나 — 화각·좌석·먼지 */
export const feelOf = (k) => ({
  fov: SPEED.fovOpen * k,
  seat: SPEED.seatPush * k,
  dust: 1 + (SPEED.dustGain - 1) * k,
});

/** 사람이 읽는 한 마디 — 계기가 쓴다 */
export function speedWord(mps) {
  if (mps < 5) return '정지';
  if (mps < 18) return '순항';
  if (mps < CRUISE.speed * BOOST.mult * 0.6) return '전속';
  return '★ 급가속';
}
