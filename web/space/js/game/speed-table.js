// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **속도감** — 빨라지는 것이 느껴지나 (v114). 숫자만.
//
//  ★ 사장님 (2026-08-11) 「**가속도가 안 느껴지고**, f로 붙으면 실제로
//    붙어야지. **멀리서 그냥 가져오는게 아니고**」
//
//  ══ 재 보니 넷이 틀려 있었다 ═══════════════════════════════════════════
//
//    ① 창밖이 **멈춰도 흐른다** — 스로틀 0 에서 11.7 mps
//    ② 전속이 26 mps 라 **겨우 2.2배** (별줄로는 1.7배)
//    ③ `STREAK.fast` 가 **663** 인데 실제 최대가 88 이다 —
//       별줄 곡선의 **13%** 자리에서만 논다. 눈금이 통째로 안 맞았다
//    ④ **역추진이면 0** — 뒤로 가는데 별이 안 흐른다
//
//  ★★★ 그리고 제일 큰 것: **가속도를 아무도 안 그리고 있었다.**
//    사장님이 말씀하신 것은 「빠르다」가 아니라 **「빨라진다」**이고,
//    그건 속도가 아니라 **속도의 변화**다. 화면에 그 항이 없었다.
//
//  ══ 그래서 둘로 나눈다 ═════════════════════════════════════════════════
//
//      **속도**   별이 얼마나 길게 늘어지나 · 먼지가 얼마나 쏟아지나
//      **가속도** 화각이 열리나 · 좌석이 미나 · 먼지가 **더** 쏟아지나
//
//  ★ 가속도 쪽은 **잠깐만** 산다. 등속이 되면 사라져야 한다 — 그래야
//    「지금 빨라지는 중」이 읽힌다. 계속 떠 있으면 그건 속도계지 가속이 아니다
//
//  ★ three.js 를 안 쓴다 — `tools/space-speed.js` 가 읽는다.
// ══════════════════════════════════════════════════════════════════════════
import { CRUISE } from './systems-table.js';
import { BOOST } from './boost-table.js';

export const SPEED = {
  /**
   * ★★★ **멈추면 정말 멈춘다.**
   *
   *   ★ 옛 값은 `LEG.coast`(0.45)를 창밖 속도에도 썼다. 그런데 그 값은
   *     「추진을 꺼도 항로는 관성으로 나아간다」는 **항로**의 값이지
   *     **눈**의 값이 아니다. 둘을 같이 쓰면 스로틀 0 과 전속의 차이가
   *     반밖에 안 나고, 그러면 **밀어도 안 빨라진 것처럼** 보인다.
   *   ★★ 0.10 은 「완전히 0 은 아니다」다 — 우주에서 관성은 진짜로 있고,
   *     0 으로 두면 이번엔 **멈춰 선 화면**이 된다 (v57 고증)
   */
  idle: 0.10,
  /** 전속일 때의 배수 */
  full: 1.0,
  /**
   * ★★ **역추진도 흐른다** — 뒤로 가는 것도 가는 것이다.
   *   옛 `legMult` 는 역추진에 0 을 줘서 **별이 멎었다**
   */
  back: 0.55,

  /**
   * ★★★ **별줄 눈금** — 이것이 제일 크게 틀려 있었다.
   *
   *   `sky-table.js STREAK.fast` 가 **663** 이었다. 실제로 나오는 속도는
   *   26(전속) ~ 88(급가속)이므로 **곡선의 13% 자리**에서만 놀았고,
   *   게다가 `bend` 0.32 가 초반을 확 올려서 **11.7 에서 이미 5.72**가
   *   나왔다 — 즉 멈춘 것과 전속이 눈으로 거의 같았다.
   *   ★ 눈금을 **실제 범위**에 맞춘다
   */
  streakFast: 95,
  /** 이보다 느리면 줄을 안 긋는다 (점으로 남는다) */
  streakMin: 3,
  /** 곡선의 휨 — 1 이면 곧다. 0.55 면 느린 쪽이 조금 더 민감하다 */
  streakBend: 0.55,

  // ══ 가속도 쪽 ═══════════════════════════════════════════════════════
  /**
   * ★★★ **이만큼 빨라지면 「최대로 느껴진다」** (mps 매초).
   *   전속(26)까지 스로틀을 미는 데 `THROTTLE.rate` 로 1.4초쯤 걸리므로
   *   초당 19 쯤이 보통이고, 급가속은 그 서너 배다
   */
  accFull: 34,
  /** 가속 신호가 **삭는 시간** (초) — 등속이 되면 사라져야 한다 */
  accFade: 0.55,
  /** 화각이 이만큼까지 열린다 (도) — 가장자리가 빨리 흘러 속도로 읽힌다 */
  fovOpen: 13,
  /** 좌석이 이만큼 밀린다 (유닛) — 몸으로 느끼는 몫 */
  seatPush: 0.085,
  /** 먼지가 이만큼 더 쏟아진다 (배수) */
  dustGain: 1.9,
};

/**
 * ★★★ **창밖이 초당 몇 유닛 흐르나** — **여기가 유일한 답이다.**
 *
 *   ★ 게임도 도구도 이 함수를 부른다. `main.js` 가 제 방식으로 다시
 *     곱하기 시작하면 그때부터 「화면은 빠른데 항로는 안 가는」 것이 난다
 *
 * @param leg   항로 배수 (`throttle.js legOf` 가 준 값 · 0~1)
 * @param back  역추진인가
 * @param boost 급가속 배수 (1 이면 안 씀)
 * @param tow   ★ 끌려가는 속도 (m/s) — 포획으로 **붙으러 갈 때**
 */
export function mpsAt({ leg = 0, back = false, boost = 1, tow = 0 } = {}) {
  const k = back ? SPEED.back : (SPEED.idle + (SPEED.full - SPEED.idle) * Math.max(0, Math.min(1, leg)));
  // ★★ **붙으러 가는 것도 가는 것이다** (사장님 「f로 붙으면 실제로 붙어야지」).
  //   포획이 거리를 줄이는 동안 창밖이 그대로면 **꾸러미가 날아오는** 것으로
  //   보인다. 실제로는 배가 가는 것이므로 그 속도를 여기에 얹는다
  return CRUISE.speed * k * boost + tow;
}

/** 이 속도에서 별줄이 얼마나 긴가 — 새 눈금 */
export function streakAt(mps) {
  if (!(mps > SPEED.streakMin)) return 0;
  const k = (mps - SPEED.streakMin) / (SPEED.streakFast - SPEED.streakMin);
  return +(30 * Math.min(1, Math.max(0, k)) ** SPEED.streakBend).toFixed(2);
}

/**
 * ★★★ **가속도가 얼마나 느껴지나** 0~1.
 *
 *   ★ `d` 는 **이번 걸음의 속도 변화**(mps/초)다. 양수만 센다 —
 *     느려지는 것은 다른 느낌이고, 그건 역추진이 이미 말한다
 */
export const accOf = (d) => Math.max(0, Math.min(1, d / SPEED.accFull));

/**
 * ★★ **가속 신호가 삭는다** — 등속이 되면 사라진다.
 * @param k 지금 값 · @param want 이번 걸음의 목표
 */
export function fadeAcc(k, want, dt) {
  if (want > k) return want;                       // 오를 때는 바로
  return Math.max(want, k - dt / SPEED.accFade);   // 내릴 때만 천천히
}

/** 가속이 화면에 얼마나 나오나 — 화각·좌석·먼지 */
export const feelOf = (k) => ({
  fov: SPEED.fovOpen * k,
  seat: SPEED.seatPush * k,
  dust: 1 + (SPEED.dustGain - 1) * k,
});

/** 사람이 읽는 한 마디 — 계기가 쓴다 */
export function speedWord(mps) {
  if (mps < 5) return '정지';
  if (mps < 18) return '순항';
  if (mps < CRUISE.speed * BOOST.mult * 0.6) return '전속';
  return '★ 급가속';
}
