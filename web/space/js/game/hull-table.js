export const SECTION_BY = Object.fromEntries(SECTIONS.map((s) => [s.key, s]));

/** 이 파츠가 붙은 덩어리들 — 방열판처럼 **둘일 수 있다** */
export const sectionsFor = (slot) => SECTIONS.filter((s) => s.slot === slot);

/** 파츠가 안 붙은 구조물 (조종석) */
export const STRUCTURE = SECTIONS.filter((s) => !s.slot);

/**
 * ★★ **상자가 차지하는 범위** [min, max] — 겹침을 재는 데 쓴다.
 *   껍질은 배 전체이므로 겹침 검사에서 뺀다 (두르는 것이 일이다)
 */
export function boxOf(s) {
  const [x, y, z] = s.at; const [w, h, d] = s.size;
  return { x0: x - w / 2, x1: x + w / 2, y0: y - h / 2, y1: y + h / 2, z0: z - d / 2, z1: z + d / 2 };
}

/** 두 덩어리가 파고드나 — 살짝 닿는 것은 봐준다 (`gap` 만큼) */
export function overlaps(a, b, gap = 0.05) {
  const A = boxOf(a); const B = boxOf(b);
  return A.x0 < B.x1 - gap && B.x0 < A.x1 - gap
    && A.y0 < B.y1 - gap && B.y0 < A.y1 - gap
    && A.z0 < B.z1 - gap && B.z0 < A.z1 - gap;
}

/**
 * ★★ **무게 중심** — 덩어리 부피로 잰다.
 *   기수 쪽으로 쏠리면 도해가 「코가 무거운 배」로 읽힌다
 */
export function balance() {
  let m = 0; let z = 0;
  for (const s of SECTIONS) {
    if (s.kind === 'shell') continue;              // 껍질은 고르게 두른다
    const v = s.size[0] * s.size[1] * s.size[2];
    m += v; z += v * s.at[2];
  }
  return { z: +(z / m).toFixed(3), vol: +m.toFixed(1) };
}

