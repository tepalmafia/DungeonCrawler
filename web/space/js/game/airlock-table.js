// ══════════════════════════════════════════════════════════════════════════
//  에어록 바깥문 — **열고 우주에서 낚는다** (2026-08-05 · 사장님 요청)
//
//  ★ 사장님: 「광물은 문을 열어서 우주에서 낚거나」
//
//    윈치는 이미 있다. 없던 것은 **바깥문**이고, 그건 `MISSIONS.md` 가
//    「아직 안 열린다」고 적어 둔 바로 그것이다 (`CHASE2.md §3-④` 도
//    사출기를 위해 이 문을 기다리고 있었다).
//
//  ★ 문을 다는 것이 왜 「낚기」를 게임으로 만드나
//    지금 채굴은 **에어록에 서서 잡고 있으면 되는** 일이다. 위험은 쌓이지만
//    그건 숫자고, 손이 하는 일은 하나뿐이다. 바깥문이 생기면 그 앞에
//    **결심이 하나** 붙는다:
//
//      **바깥문을 열면 안쪽 문이 잠긴다.**
//
//    실제 에어록이 그렇다 — 두 문이 동시에 열리면 배가 통째로 진공이 된다.
//    그래서 낚는 동안 **에어록에 갇힌다.** 열이 오르든 고장이 나든
//    문을 닫고 나가기 전에는 아무것도 못 한다.
//    「동시에 두 곳에 못 있는다」가 여기서 또 돈다 (PLAN §1).
//
//  ★ 그리고 **열어 둔 채로 잊을 수 없다**
//    문이 열려 있으면 ① 자국이 커지고 ② 열이 빠져나가고(그건 이득이다)
//    ③ **공기가 준다.** 공기가 바닥나면 문이 강제로 닫히고 한동안 못 연다 —
//    벌이 숫자가 아니라 **기다림**이다.
//
//  ★ three.js 를 안 쓴다 — tools/space-airlock.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const LOCK = {
  /** 바깥문을 여는 데 (초). 잡고 돌린다 — 밸브와 같은 손짓 */
  cycle: 3.2,

  /**
   * ★★ **에어록 한 칸의 공기** (0~1). 1 이 기밀이고 0 이면 진공이다.
   *
   *   ★ **v62 에서 뜻이 통째로 바뀌었다** (REAL.md §2-C).
   *     예전에는 이것이 **배 전체 공기**였고, 열어 두면 133초에 걸쳐
   *     줄었다. 그건 에어록이 아니라 **구멍**이다 — 에어록의 정의가
   *     「배와 격리된 칸」인데 격리가 안 되고 있었다. 그리고 배 전체가
   *     죽는 문이면 아무도 안 연다.
   *
   *     지금은 **작은 칸 하나**가 비는 값이다. 0.075 면 12.5초 —
   *     실제 에어록 배기가 10~30초다. **이건 벌이 아니다.** 문을 열면
   *     그 칸이 진공이 되는 것은 그냥 맞는 일이고, 벌은 「우주복 없이
   *     열었다」 쪽에만 붙는다 (`suit-table.js SUIT.grace`).
   */
  airDrain: 0.075,
  /**
   * 닫으면 초당 이만큼 찬다 — 빼는 것보다 **느리다.**
   * 0.045 면 진공에서 기밀까지 21초. 배의 저장 공기를 쓰는 것이라
   * 빼는 것보다 느린 것이 맞다
   */
  airFill: 0.045,
  /** 이 밑이면 **진공으로 친다** — 우주복이 없으면 여기서부터 시간이 간다 */
  airFloor: 0.06,
  /** 강제로 닫힌 뒤 이만큼은 못 연다 (초) — 벌이 기다림이다 */
  lockout: 45,

  /**
   * ★ 열려 있는 동안 자국이 이만큼 오른다.
   *   구멍 뚫린 배는 눈에 띈다 — 「우주에서 스텔스는 불가능하다」와 같은 줄
   *   (`CHASE2.md §2-1`). 윈치 소리(`WINCH.sign` 9)에 **더해진다**
   */
  sign: 14,
  /**
   * 열려 있으면 열이 초당 이만큼 빠진다.
   * ★ **이건 이득이다.** 문을 여는 데 좋은 점이 하나도 없으면 아무도 안 열고,
   *   그러면 이 계통은 벌 덩어리가 된다. 다만 밸브(-5.2)보다 약하다 —
   *   문으로 식히는 것이 밸브보다 낫다면 밸브가 뜻을 잃는다
   */
  heatOut: 1.6,

  /**
   * ★ **바깥문이 열려 있어야 낚는다.**
   *   닫힌 채로 윈치를 잡으면 아무것도 안 온다 — 그리고 왜인지 말한다
   */
  needOpenToHaul: true,
  /** 추진을 켠 채로는 못 연다 — 달리면서 문을 열 수는 없다 */
  needStill: true,

  /**
   * ★★ **우주복이 있어야 나가 있을 수 있다** (v62 · REAL.md §2-C).
   *
   *   막지는 **않는다.** 안 입고도 열린다 — 그래야 한 번 겪고 배운다.
   *   대신 칸이 빈 뒤 `SUIT.grace`(4초) 안에 안 들어오면 배가 억지로
   *   닫고 45초 잠근다. 숫자는 전부 `suit-table.js` 에 있다.
   */
  needSuit: true,
};

/** 왜 못 여나 · 왜 못 낚나 — **조용히 안 되면 「고장」으로 읽힌다** */
export const WHY = {
  thrust: '추진을 끄고 나서 엽니다',
  air: '공기가 모자랍니다 — 채워질 때까지 기다립니다',
  lockout: '기밀이 잡히는 중입니다',
  shut: '바깥문을 열어야 낚을 수 있습니다',
  cycling: '문이 도는 중입니다',
};

export function whyNotOpen(s = {}) {
  if (LOCK.needStill && s.thrust) return 'thrust';
  if ((s.lockout ?? 0) > 0) return 'lockout';
  if ((s.air ?? 1) <= LOCK.airFloor) return 'air';
  return null;
}

/**
 * 에어록 **한 칸**의 공기를 사람 말로 — **숫자로 안 띄운다.**
 *
 * ★ 말도 v62 에서 바뀌었다. 예전 마지막 줄이 「기밀 상실」이었는데,
 *   그건 사고를 뜻하는 말이다. 바깥문을 열어 그 칸이 빈 것은 **사고가
 *   아니라 절차**다 — 「배기 완료」가 맞는 말이다. 사고인 것은 그 안에
 *   **우주복 없이** 서 있는 쪽이고, 그건 따로 말한다
 */
export function airWord(air) {
  if (air > 0.6) return '기밀 정상';
  if (air > 0.3) return '배기 중';
  if (air > LOCK.airFloor) return '거의 진공';
  return '진공 — 배기 완료';
}
