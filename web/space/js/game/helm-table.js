/** 지금 행성에 다가가고 있나 — 조건 넷이 다 맞아야 한다 */
export function closingIn({ manual, region, thrust, off } = {}) {
  return !!(manual && region === 'planet' && thrust && off >= HELM.hitFrom);
}

/** 충돌까지 얼마나 남았나를 사람 말로 — **숫자로 안 띄운다** */
export function hitWord(near) {
  if (near >= 0.99) return '충돌';
  if (near > 0.72) return '충돌 임박 — 지금 되돌리십시오';
  if (near > HELM.warnAt) return '중력원에 끌려갑니다';
  return null;
}

/** 지금 얼마나 벗어나 있나에 따라 구간이 이만큼 나아간다 (0~1 → 배수) */
export const legMult = (off) => 1 - (1 - HELM.slowTo) * Math.max(0, Math.min(1, off));

/** 자국 배수 — 벗어날수록 안 보인다 */
export const signMult = (off) => 1 - (1 - HELM.hideTo) * Math.max(0, Math.min(1, off));

/** 거점에 닿을 수 있나 */
export const canDock = (off) => off <= HELM.portWithin;

/**
 * 사람에게 보이는 한 줄 — 조종석 계기가 쓴다.
 * ★ 숫자로 안 띄운다. 「얼마나 벗어났나」는 **창밖이 말한다** (배가 기운다)
 */
export function offWord(off) {
  if (off < 0.08) return '항로 위';
  if (off < 0.35) return '조금 벗어남';
  if (off < 0.7) return '벗어남';
  return '많이 벗어남';
}


