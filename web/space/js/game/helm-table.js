// ══════════════════════════════════════════════════════════════════════════
//  조종 — **조종간이 늘 먹는다** (2026-08-05 · 사장님 「조종석을 움직일 수 없잖아」)
//
//  ★ 재 보니 사장님이 맞았다
//    조종석은 걸어다닐 수 있다 (닿는 칸 403 — 기관실 다음으로 넓다).
//    문제는 **조종간이 하는 일**이었다:
//
//    | | 값 |
//    |---|---|
//    | 조종간이 뭔가를 하는 때 | **잔해 지대 안에서만** (구간당 1~2회 × 30초) |
//    | 조종석에 매인 시간 | **회차의 6~10%** |
//    | 나머지 90% 동안 조종간 | **잡아도 아무 일도 안 난다** |
//
//    즉 **배에 조종석이 있는데 배를 못 몬다.** 좌우로 바위를 피하는 것은
//    조종이 아니라 회피이고, 그것도 30초짜리다.
//
//  ★ 그렇다고 조종을 늘리면 장르가 바뀐다
//    `CHASE2.md §5` 가 「조종을 늘리기」를 **안 하는 것**에 넣어 뒀다 —
//    조종석에 매인 시간을 늘리면 정비공이 아니라 조종사가 된다.
//    그래서 **매인 시간을 늘리지 않고 조종간이 늘 먹게** 만든다:
//
//      **조종간을 잡으면 항로를 벗어난다.**
//      벗어나면 **느려지고, 대신 자국이 준다.**
//
//    잡고 있어야 벗어나 있으므로 **오래 잡을 이유가 없다** — 필요한
//    만큼만 틀고 놓는다. 매인 시간은 그대로인데 조종간은 늘 살아 있다.
//
//  ★ 왜 「벗어나면 안 들킨다」인가 — 실제 우주에서도 그렇다
//    `CHASE2.md §2-2` 「실제로는 총질이 아니라 궤도다」. 쫓는 쪽은 내
//    **항로를 예측**해서 따라온다. 예측을 벗어나면 다시 찾는 데 시간이
//    걸린다. 대신 나도 목적지에서 멀어지므로 **느려진다.**
//
//  ★ three.js 를 안 쓴다 — tools/space-helm.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const HELM = {
  /**
   * 조종간을 끝까지 밀었을 때 **초당 몇 만큼** 벗어나나 (0~1).
   * ★ 1 이 「완전히 딴 데로 간다」다. 2.9초면 끝까지 벗어난다 —
   *   너무 빠르면 톡 건드린 것과 작정한 것이 같아지고, 너무 느리면
   *   「밀어도 아무 일 없다」가 된다 (지금의 병이 정확히 그것이다)
   */
  turnRate: 0.34,
  /**
   * 놓으면 초당 이만큼 항로로 **돌아온다.**
   * ★ 벗어나는 것보다 **느리다.** 그래야 「틀어 놓고 다른 일 하러 간다」가
   *   성립한다 — 조종석에 매여 있지 않아도 되게 하는 것이 이 판의 전부다
   */
  backRate: 0.12,

  /**
   * 완전히 벗어났을 때 구간 진행이 **이만큼으로 준다.**
   * ★ 0 이면 안 된다 — 아예 안 가면 그건 조종이 아니라 정지다.
   *   `LEG.coast`(추진 끔 = 0.45)보다 덜 아프게 잡았다. 벗어나는 것은
   *   발을 떼는 것보다 가벼운 선택이어야 한다
   */
  slowTo: 0.62,
  /**
   * 완전히 벗어났을 때 자국이 **이만큼으로 준다.**
   * ★ 여기가 이 장치가 파는 것이다. 0.55 면 자국 60 이 33 이 되어
   *   접촉 기준(52) 아래로 내려간다 — **틀면 안 붙는다**가 성립한다
   */
  hideTo: 0.55,

  /**
   * ★ **잔해 지대 안에서는 딴 일을 한다.**
   *   지대에서 조종간은 바위를 피하는 물건이다 (`hazard.lane`).
   *   같은 손잡이가 상황에 따라 다른 일을 하는 것은 이 배의 규약이다
   *   (자세 제어가 죽었을 때도 같은 조종간을 잡는다 — `drift.js`).
   *   그래서 지대 안에서는 **항로 이탈이 안 는다** — 두 가지를 동시에
   *   하면 어느 쪽도 안 된다.
   */
  notInField: true,

  /**
   * 벗어난 채로 거점에 닿으면 **못 닿는다.**
   * 이만큼보다 벗어나 있으면 거점을 지나친다 — 되돌아와야 한다.
   * ★ 「틀어 놓고 잊기」를 막는 유일한 자리다. 자국이 주는 것만 있고
   *   잊는 벌이 없으면 **늘 틀어 놓는 것이 답**이 된다
   */
  portWithin: 0.35,
};

/** 지금 얼마나 벗어나 있나에 따라 구간이 이만큼 나아간다 (0~1 → 배수) */
export const legMult = (off) => 1 - (1 - HELM.slowTo) * Math.max(0, Math.min(1, off));

/** 자국 배수 — 벗어날수록 안 보인다 */
export const signMult = (off) => 1 - (1 - HELM.hideTo) * Math.max(0, Math.min(1, off));

/** 거점에 닿을 수 있나 */
export const canDock = (off) => off <= HELM.portWithin;

/**
 * 사람에게 보이는 한 줄 — 조종석 계기가 쓴다.
 * ★ 숫자로 안 띄운다. 「얼마나 벗어났나」는 **창밖이 말한다** (배가 기운다)
 */
export function offWord(off) {
  if (off < 0.08) return '항로 위';
  if (off < 0.35) return '조금 벗어남';
  if (off < 0.7) return '벗어남';
  return '많이 벗어남';
}
