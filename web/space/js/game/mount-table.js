/** 이 무기가 발사관에 실리나 — **레이저는 기수 고정이다** */
export const GIMBALED = { laser: false, seeker: true, arh: true };
export const isGimbaled = (key) => GIMBALED[key] === true;

/**
 * ★★ 흔들림이 조준 오차에 얹히는 값 (도).
 *   `combat.js fire()` 가 `off` 에 더한다 — 새 판정을 안 만든다
 */
export const spreadOf = (m) => Math.max(0, m?.wob ?? 0);

/** 사람이 읽는 한 마디 — 계기가 이 한 줄만 쓴다 */
export function mountWord(m) {
  if (!m || m.id === null) return '대기';
  if (m.pinned) return '한계 — 기수를 돌리십시오';
  if ((m.wob ?? 0) > MOUNT.shaky) return '불안정';
  return '추적 중';
}
