/**
 * ★ 왜 못 뛰나 — 되면 `null`.
 *
 * @param o.cells  화물칸의 아크 전지 수
 * @param o.sinkAt 열 저장고가 얼마나 찼나 (0~1)
 * @param o.power  축전기 전력이 들어와 있나
 * @param o.cool   남은 재사용 대기 (초)
 * @param o.phase  지금 마디
 * @param o.landed 땅에 내려 있나
 */
export function whyNotJump({ cells = 0, sinkAt = 0, power = true, cool = 0, phase = PHASE.NONE, landed = false } = {}) {
  if (landed) return 'land';
  if (phase !== PHASE.NONE) return 'busy';
  if (cells < ARC.cells) return 'cells';
  if (!power) return 'power';
  if (sinkAt >= ARC.sinkMax) return 'sink';
  if (cool > 0) return 'cool';
  return null;
}

