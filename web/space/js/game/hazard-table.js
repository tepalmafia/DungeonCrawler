// ══════════════════════════════════════════════════════════════════════════
//  부딪히는 것 — **「간다」의 대가** (docs/space/FLYING.md).
//
//  ★ 조종은 「또 하나의 방」이지 게임의 중심이 아니다
//    이 게임은 함장이 아니라 **정비공**이다 (PLAN §1). 조종간을 잡고
//    날아다니는 것이 중심이 되면 이 게임은 다른 게임이 되고, 그 다른 게임은
//    이미 잘 만든 것들이 있어 우리가 못 이긴다.
//
//    그래서 안전핀을 숫자로 박아 둔다 — **조종석에 매인 시간이 구간의
//    15% 를 넘으면 설계가 아니라 장르가 바뀐 것이다.** 넘으면 되돌린다.
//
//  ★ 반사신경이 아니라 **일정 관리**다
//    자리를 비운 사이에 부딪히면 「정비하러 가는 것 자체가 벌」이 되고,
//    그러면 이 게임의 중심(진단과 왕복)이 무너진다. 그래서 위험은
//    **미리 · 크게 · 시간을 두고** 알린다. 30초 예고가 뜨면 하던 일을
//    마치고 조종석으로 돌아간다 — 그게 나머지 전부와 같은 결이다.
//
//  ★ 한 지대에 덩어리가 여럿이다
//    하나만 오면 「한 번 밀면 끝」이라 조종이 형식이 된다. 둘~넷이 서로
//    다른 자리로 오면 **밀었다 되밀어야** 한다. 그게 조종이 조종인 지점이다.
//
//  ★ three.js 를 안 쓴다 — tools/space-fly.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const HAZARD = {
  /** 위험 지대가 오는 간격(초). 구역 밀도가 나눈다 */
  every: [230, 400],
  /** 구간을 떠나고 이만큼은 안 온다 — 거점을 나서자마자 맞으면 억울하다 */
  firstAfter: 85,
  /**
   * ★ **구간당 최대 두 번.** 셋이면 정비할 틈이 없다.
   *   잔해밭은 구간이 길어서 밀도만으로는 셋 넘게 나온다 — 그래서 상한을 둔다.
   */
  maxPerLeg: 2,

  /** 예고 시간(초). 기관실에서 조종석까지 걸어올 시간 + 하던 일 마무리 */
  warn: [26, 38],
  /**
   * ★ 성운에서는 예고가 절반이다 — 센서가 안 듣는다.
   *   성운의 「자국이 묻히지만 나도 못 본다」에 **두 번째 실체**가 붙는다
   *   (지금까지는 추격 거리만 못 읽었다).
   */
  blindMult: 0.5,

  // ★ 2개로 뒀더니 접근이 12초에 끝났다 — 목표는 20~45초다. 12초짜리는
  //   「한 번 밀면 끝」이라 조종이 형식이 된다. 셋 이상이어야 밀었다 되민다
  /** 한 지대에 덩어리 몇 개 */
  rocks: [3, 4],
  /** 덩어리 사이 간격(초) */
  gap: [7.5, 11.5],
  /** 첫 덩어리가 오기까지 (접근이 시작되고) */
  lead: 6,

  /** 배가 좌우로 갈 수 있는 폭 (-1 ~ 1) */
  laneMax: 1,
  /** 이만큼 비켜 있어야 안 부딪힌다 */
  clear: 0.46,
  /** 조종간을 끝까지 밀었을 때 초당 lane 변화 */
  tiltRate: 0.62,
  /** 놓으면 초당 이만큼 가운데로 돌아온다 — 잡고 있어야 한다는 뜻이다 */
  recenter: 0.2,

  /**
   * 부딪히면 — **죽지 않는다. 대신 일이 는다** (PLAN §4-4).
   * 벌이 「숫자 -10」이면 아무도 안 무서워한다. 벌은 **일**이어야 한다.
   */
  hit: { hull: 0.22, heat: 12, fault: true },

  /** 구역별 빈도 배수. 잔해밭의 「대신 부딪힌다」가 여기서 실체가 된다 */
  density: { debris: 1.45, planet: 1.05, empty: 0.8, nebula: 0.9 },
};

/** 성운이면 예고가 짧다 */
export const warnFor = (base, region) => base * (region === 'nebula' ? HAZARD.blindMult : 1);

/** 그 구역에서 위험 지대 사이 간격 */
export const everyFor = (base, region) => base / (HAZARD.density[region] ?? 1);
