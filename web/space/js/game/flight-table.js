/** 조종간이 지금 무엇을 하고 있나 — 화면이 이 말을 쓴다 */
export function attitudeWord(a) {
  const p = Math.abs(a.pitch) > 0.12, y = Math.abs(a.yaw) > 0.25;
  const r = Math.abs(a.roll) > 0.25;
  if (!p && !y && !r) return '수평';
  const bits = [];
  if (p) bits.push(a.pitch > 0 ? '기수 올림' : '기수 내림');
  if (y) bits.push(a.yaw > 0 ? '우현' : '좌현');
  if (r) bits.push('비틀림');
  return bits.join(' · ');
}

/** 한 바퀴를 몇 도 돌았나 — 계기가 숫자로 보여준다 */
export const rollDeg = (roll) => {
  const d = ((roll * 180) / Math.PI) % 360;
  return d < 0 ? d + 360 : d;
};
