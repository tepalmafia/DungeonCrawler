import { KEYS } from './keys-table.js';
import { PICK } from './route-table.js';
import { LAYOUT } from './layout-table.js';
import { ASK } from './loot-table.js';

export const ONBOARD = {
  /**
   * ★★ **넉 장까지.** 다섯이면 안 읽는다 — 가르침을 일곱으로 못박은 것과
   *   같은 까닭이다. 처음 3초에 사람이 담는 것은 그보다 적다
   */
  maxCards: 4,
  /** 한 줄이 이보다 길면 툴팁이 아니라 설명서다 */
  maxLen: 34,
  /** 한 장이 떠 있는 시간 (초) — 다음 장으로 저절로 넘어간다 */
  hold: 6.5,
  /**
   * ★★★ **새 게임에서만 뜬다.** 이어하는 사람은 이미 안다 —
   *   켤 때마다 뜨면 그건 도움말이 아니라 잔소리다
   */
  newGameOnly: true,
  /** 아무 키나 누르면 닫힌다 — 나오는 길은 늘 열어 둔다 */
  anyKeyCloses: true,
  what: '처음 켠 사람의 첫 3초 — 손이 어디에 있나',
};

/**
 * ★★★ **넉 장.** 순서는 「지금 당장 할 수 있는 것」부터다.
 *
 *   ★ `key` 는 **표에서 읽는다** (위 머리말 참고). 여기서 'R' 이라고
 *     적어 두면 표를 고치는 날 조용히 거짓말이 된다
 */
export const CARDS = [
  {
    key: '마우스',
    line: '마우스로 기수를 돌립니다',
    tip: '앉은 채로 다 합니다 — 일어서는 것은 없습니다',
  },
  {
    key: () => `${KEYS.up.code === 'KeyW' ? 'W / S' : KEYS.up.code} · ${KEYS.thrust.code.replace('Key', '')}`,
    line: '속도는 W · S, 추력은 톡',
    tip: '꾹 누르면 급가속입니다',
  },
  {
    key: () => KEYS.fire.code.replace('Key', ''),
    line: '겨누고 눌러 쏩니다',
    tip: '레이저는 기수 고정 · 유도탄은 묶어야 나갑니다',
  },
  {
    key: () => PICK.name,
    line: '거점에서 갈 쪽을 보고 누릅니다',
    tip: '하늘에 후보가 둘 서 있습니다',
  },
];

/** 그 장의 키 (글자) — 함수면 불러서 지금 값을 낸다 */
export const keyOf = (c) => (typeof c.key === 'function' ? c.key() : c.key);

/**
 * ★★ **맨 아래 한 줄** — 「더 있다」를 알려 준다.
 *   ★ 툴팁이 전부인 척하면 나머지를 영영 안 찾는다
 */
export const moreWord = () =>
  `더 보기 F1 · 창 옮기기 ${LAYOUT.keyName} · 회수 ${ASK.yes.replace('Key', '')}/${ASK.no.replace('Key', '')}`;

/** 검사와 화면이 읽는다 */
export const summary = () => ({
  cards: CARDS.length,
  keys: CARDS.map(keyOf),
  longest: Math.max(...CARDS.map((c) => c.line.length)),
  more: moreWord(),
});
