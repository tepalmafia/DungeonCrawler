//
//  ══ 이미 「가르침」이 있는데 왜 또 만드나 ═══════════════════════════════
//
//  `tutor-table.js` 의 가르침 일곱은 **하나씩, 조건이 맞을 때** 뜬다
//  (「항로를 골라야 배가 갑니다」는 거점에 서 있을 때만). 그건 **하는 법**을
//  때맞춰 알려 주는 것이라 그 자리가 옳다.
//
//  ★★ 그런데 사장님이 말씀하신 것은 **처음 3초**다. 창을 켜면 별과 계기가
//    한꺼번에 오는데 「손을 어디에 올리나」가 아무 데도 안 적혀 있었다 —
//    F1 을 눌러야 나오고, **F1 이 있다는 것도 안 알려 줬다.**
//    가르침은 「무엇을 할까」를 말하고, 이것은 **「손이 어디에 있나」**를 말한다.
//
//  ══ ★★★ 키를 **손으로 안 적는다** ═══════════════════════════════════
//
//  이 저장소가 같은 자리에서 세 번 데었다:
//    · v110 — 걷기를 없앴는데 첫 가르침이 「WASD 로 걷습니다」였다
//    · v82  — 항로를 조종석으로 옮겼는데 안내는 「관측실 해도대」였다
//    · v131 — 되돌리기를 Backspace 로 옮겼는데 안내는 R 이라고 했다
//
//  **셋 다 「고쳐 놓고 안내를 안 고쳤다」**이고, 셋 다 **키 이름을 글에
//  박아 두었기 때문**이다. 그래서 여기서는 키를 **표에서 읽어 온다** —
//  `keys-table.js` 가 바뀌면 툴팁이 **저절로** 따라온다. 그리고
//  `tools/space-onboard.js` 가 「적힌 키가 진짜 있는 키인가」를 대조한다.
