// ══════════════════════════════════════════════════════════════════════════
//  ★★ 추진제 — **시계를 맞는 물건에 옮긴다** (v62 · REAL.md §2-D · §4-D)
//
//  ★ 무엇이 틀렸었나
//    식량이 **100 → 0 이 13분**이었고 손 떨림이 10분이었다. 밥 먹고 10분
//    뒤에 손이 떨리는 사람은 없다 — 이건 식량의 시계가 아니다.
//
//    그런데 **이 시계 자체는 필요하다.** 「다음 거점까지 갈 것이 있나」가
//    항로를 고르게 만드는 유일한 통화다 (PLAN §5-1). 즉 **시계는 맞고
//    이름만 틀렸다.** 그래서 지우지 않고 **옮긴다.**
//
//  ★★ **왜 추진제가 맞는 물건인가**
//    도망치는 배는 실제로 추진제가 먼저 바닥난다. 그리고 이 시계는
//    **항로마다 다르게** 흘러야 하는데, 추진제는 그게 자연스럽다 —
//    빠른 길은 많이 태우고 성운은 적게 태운다. 식량으로는 「성운에서
//    덜 먹는다」를 설명할 수가 없었다.
//
//  ★★ **어떻게 옛 실수를 안 되풀이하나**
//    v55 에서 「발만 떼면 영영 안 붙는 게임」이 됐던 적이 있다. 추진을
//    끄면 잃는 게 없었기 때문이다 (`LEG.coast` 가 그때 나왔다).
//    추진제는 그 반대쪽 실수를 부를 수 있다 — **아끼려고 계속 끄고 있으면**
//    구간이 안 나아가고 압박(`PRESS.drift`)이 쌓인다. 즉 **양쪽이 다 손해**다.
//    그게 이 표가 성립하는 이유이고, `space-fuel.js` [4] 가 그걸 잰다.
//
//  ★ 새 계기를 안 만든다. 손목 장치에 한 줄이 늘 뿐이다 —
//    §7 이 「시계는 **열·추진제·식량 셋**으로 끝」이라고 못박아 뒀다.
//
//  ★ three.js 를 안 쓴다 — tools/space-fuel.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════
import { LEG } from './route-table.js';
import { REGION_BY_KEY } from './regions-table.js';

/**
 * ★ 한 회차(12구간)를 **추진만 켜고** 가면 몇 초인가.
 *   추진제 값을 여기서 뽑는다 — 숫자를 손으로 안 적는다.
 */
const RUN = LEG.seconds * LEG.count;

export const FUEL = {
  max: 100,
  start: 100,

  /**
   * ★★ **추진을 켠 동안만** 초당 이만큼 준다 (구역 배수 곱하기 전).
   *
   *   ★ **재고 정했다.** 한 회차가 98분(5880초)이고, 밟고 가는 시간은
   *     그중 절반 남짓이다 — 멈춰서 캐고 고치고 숨는 시간이 나머지다
   *     (`space-fly.js` 가 조종석에 매인 시간을 15% 로 잡아 뒀고, 추진은
   *     그보다 훨씬 오래 켜 둔다). 한 통(100)이 **회차의 3분의 1**을
   *     밟을 만큼이면 회차에 **두 번 채운다** — 거점 12곳 중 두세 곳에서
   *     들르는 이유가 생긴다.
   *
   *   ★ 옛 식량이 하던 일(13분에 바닥)을 그대로 옮기지 **않았다.**
   *     13분짜리 시계는 「거점마다 무조건 들른다」라 고를 것이 없다.
   *     고르는 것이 없으면 그건 시계지 통화가 아니다 (GAP.md §5).
   */
  perSec: 100 / (RUN / 3),

  /** 이 밑이면 경고 — 아직 한 구간은 갈 수 있을 때 알린다 */
  low: 22,

  /**
   * ★★ **바닥나면 추진이 안 걸린다.** 죽지는 않는다 —
   *   구간은 `LEG.coast`(0.45) 로 계속 나아가고, 그동안 압박이 진짜
   *   시간으로 쌓인다. 벌이 「끝」이 아니라 **기다림**인 것이 이 저장소의
   *   규약이다 (기밀 상실 · 정전 · 끼인 문과 같다)
   */
  dryStopsThrust: true,

  /**
   * 거래 한 번에 받는 양 — 광석 30 을 내면 식량·부품과 **같이** 온다.
   * 따로 거래를 만들지 않는다: 접수구가 둘이면 손이 배울 것이 하나 는다
   */
  perTrade: 34,
};

/**
 * ★★ **구역마다 다르게 든다** — 여기가 「항로를 고르게 만드는」 자리다.
 *
 *   구역의 `speed` 를 그대로 쓴다. 빠른 길(빈 공간 1.0 · 행성 곁 1.02)은
 *   짧게 끝나지만 초당 더 태우고, 느린 길(성운 0.78)은 오래 걸리되 덜
 *   태운다. **새 숫자를 안 만든다** — 한 숫자가 여러 일을 하는 편이
 *   두 곳에 적어서 갈라지는 것보다 낫다 (CLAUDE.md).
 *
 *   ★ 그래서 저울이 이렇게 선다:
 *       성운  — 추진제는 아끼는데 **시간**을 쓴다 (압박 drift 가 쌓인다)
 *       빈 공간 — 빨리 지나는데 **추진제**를 쓴다
 *     둘 중 아무거나 골라도 되는 상황이 안 나오는 것이 규칙의 전부다.
 */
export const burnMult = (regionKey) => {
  const r = REGION_BY_KEY[regionKey];
  if (!r) return 1;
  // ★★ **제곱이다. 처음엔 speed 를 그대로 썼다가 도구가 잡았다** (v62).
  //
  //   `space-fuel.js [3]` 이 「어느 길로 가도 25」를 찍었다. 당연했다 —
  //   구간 길이가 `LEG.seconds / speed` 인데 초당 소모를 `speed` 로 두면
  //   **곱해서 정확히 상쇄된다.** 총량이 어디서나 같으면 추진제는
  //   항로를 하나도 안 가른다. 기획서에 「빠른 길은 많이, 성운은 적게」라고
  //   써 놓고 **정확히 아무 차이도 없는 식**을 적어 놓았던 것이다.
  //
  //   맞는 값은 물리에서 나온다: 같은 거리를 v 로 가려면 v 까지 가속하고
  //   다시 줄여야 하므로 **총 추진제가 v 에 비례**한다. 시간이 1/v 이므로
  //   **초당은 v²** 이다. 새 숫자를 안 만들고도 답이 나왔다 —
  //   빠른 길이 총량으로 1.31배 든다 (행성 1.02 vs 성운 0.78).
  return r.speed * r.speed;
};

/** 이 추진제로 몇 구간을 **밟고** 갈 수 있나 — 해도대가 이걸 보여준다 */
export const legsLeftOnFuel = (fuel, regionKey = 'empty') =>
  fuel / (FUEL.perSec * burnMult(regionKey)) / LEG.seconds;

/** 사람 말로 — **숫자로 안 띄운다** */
export function fuelWord(fuel) {
  if (fuel <= 0) return '추진제 없음 — 엔진이 안 걸립니다';
  if (fuel <= FUEL.low) return '추진제가 얼마 없습니다';
  if (fuel < FUEL.max * 0.55) return '추진제 절반';
  return '추진제 충분';
}

/** 바닥났나 */
export const isDry = (fuel) => FUEL.dryStopsThrust && fuel <= 0;
