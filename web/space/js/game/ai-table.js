export const ROOMS = ['조종석', '통로', '정비실', '기관실', '관측실', '온실', '에어록', '작업실', '저장고'];
export const FAULT_WORDS = ['고장', '잘못', '이상', '샙니다', '막혔', '잠겼', '끊겼', '멈췄'];

/** ★ 이 줄이 「어디가 잘못됐나」를 말하고 있나 — **말하면 안 된다** */
export function tellsWhere(text) {
  const s = String(text ?? '');
  return ROOMS.some((r) => s.includes(r)) && FAULT_WORDS.some((f) => s.includes(f));
}

