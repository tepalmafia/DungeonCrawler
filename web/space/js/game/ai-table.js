/** 방위를 말로 — 「좌현/우현」. **각도를 안 읽는다** (계기가 아니라 목소리다) */
export function sideWord(relAz) {
  if (Math.abs(relAz) < 12) return '정면';
  if (Math.abs(relAz) > 150) return '후미';
  return relAz < 0 ? '좌현' : '우현';
}
