//  달리기와 숨 — **편의가 아니라 템포 장치다** (docs/space/PLAN2H.md §7-2)
//
//  ★ 왜 지금 만드나 (2026-08-05 · 사장님 「달리기 모드도 넣어」)
//    `systems-table.js` 에는 이렇게 적혀 있었다:
//
//      speed: 2.9,   // m/s. 뛰지 않는다 — 이 배는 좁다
//
//    **20분짜리에서는 맞았다. 2시간짜리에서는 틀리다.** 이 게임 최대
//    위험이 왕복 노동인데(USER-VIEW §3-1), 2시간 동안 같은 속도로 통로를
//    걷게 두면 그 위험이 여섯 배가 된다.
//
//  ★ 그런데 「빨라진다」만으로는 아무것도 안 생긴다
//    치르는 것이 없으면 **늘 뛰는 것이 답**이고, 그러면 배가 그냥
//    작아진 것이다. 그래서 숨을 붙인다:
//
//      뛴다 → 숨이 빠진다 → 바닥나면 걷기만 → **숨찬 동안 손이 떨린다**
//
//    마지막 한 줄이 핵심이다. 「빨리 가서 느리게 고친다」와 「천천히 가서
//    제대로 고친다」가 **맞바꾸는 계산**이 되어야 이게 장치가 된다.
//
//  ★ 「무겁다」를 무게로 말하지 않는다
//    두 손으로 안는 물건(냉매통·부품 상자)을 들면 **못 뛴다.**
//    `carry-table.js` 가 「안고 있으면 손잡이를 못 잡는다」로 무게를
//    말한 것과 **같은 규약**이다 — 숫자가 아니라 못 하게 되는 일.
//
//  ★ three.js 를 안 쓴다 — tools/space-run.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const RUN = {
  /**
   * 걷기 대비 배수. 통로 13m 가 **4.5초 → 2.8초**.
   * ★ 2.0 배로 하면 배가 절반이 된다. 1.6 은 「빠르다」가 느껴지되
   *   방 사이가 여전히 한 번의 결심인 값이다.
   */
  mult: 1.6,

  /** 숨 (초). 이만큼 뛸 수 있다 */
  breath: 9,
  /**
   * 다 차는 데 걸리는 시간(초). **뛰는 시간보다 길어야** 아껴 쓴다.
   * 9초 뛰고 14초 쉬면 왕복 한 번에 한 구간씩 쓰는 셈이 된다.
   */
  refill: 14,
  /**
   * 숨이 다시 차기 시작하기까지 (초). 멈추자마자 차면 「뛰고 서고」를
   * 반복하는 것이 답이 되고, 그건 조작 요령이지 선택이 아니다.
   */
  restBefore: 1.2,

  /**
   * 숨이 이보다 적으면 **숨찬 것**으로 친다 (0~1).
   * 바닥(0)에서만 벌을 주면 사람은 8.9초까지 뛰고 만다 — 그건 계산이
   * 아니라 눈금 읽기다. 조금 남았을 때부터 손이 떨려야 **재게** 된다.
   *
   * ★ 0.25 에서 올렸다. 검사가 잡아 줬다 — 조종석↔정비실 왕복(25m)을
   *   뛰면 5.4초라 숨이 0.40 밖에 안 빠져서 **아무 대가가 없었다.**
   *   그러면 「빨리 가서 느리게 고친다」라는 맞바꿈이 성립을 안 한다.
   *   0.45 면 **뛰기로 한 결정 자체가 값을 치른다.**
   */
  windedAt: 0.45,
  /**
   * ★ **숨이 바닥나면 여기까지 차야 다시 뛴다** (0~1).
   *
   *   이게 없어서 검사가 [2] 에서 걸렸다 — 바닥난 뒤 `restBefore` 만
   *   지나면 숨이 아주 조금 차고, 그 순간 `breath > 0` 이라 **바로 다시
   *   뛰어졌다.** 「뛰고 서고」를 막으려고 넣은 `restBefore` 가 오히려
   *   그 요령의 박자가 되어 있었다.
   *   한 번 바닥나면 **절반은 차야** 다시 달린다.
   */
  recoverTo: 0.5,
  /**
   * 숨찬 동안 수리 속도 배수.
   * ★ 굶었을 때(`FOOD.handMult`)와 **같은 규약**이다 — 배 안의 모든
   *   「손이 안 듣는다」가 같은 방식이라야 사람이 안 헷갈린다.
   */
  handMult: 0.7,

  /** 좁은 데서 뛰다 스치면 — 이만큼(초) 비틀거린다 */
  stumble: 0.6,
  /** 그때 손에 든 것을 놓치나 */
  dropOnStumble: true,
};

/**
 * 지금 뛸 수 있나.
 *
 * ★ **왜 못 뛰는지가 종류별로 다르다.** 그래야 「고장났나」가 아니라
 *   「아, 이래서」가 된다 (main.js 가 이 열쇠로 말을 고른다).
 *
 * @param s { breath 0~1, holding 종류|null, bothHands 두 손인가, dark 정전인가 }
 * @returns null 이면 뛸 수 있다. 아니면 못 뛰는 이유
 */
export function whyNotRun(s = {}) {
  if (s.bothHands) return 'hands';
  if (s.dark) return 'dark';
  if ((s.breath ?? 1) <= 0) return 'breath';
  return null;
}

/** 못 뛰는 이유를 사람 말로. **조용히 안 막는다** */
export const WHY = {
  hands: '두 손이 찼습니다 — 걸어갑니다',
  dark: '어두워서 못 뜁니다',
  breath: '숨이 찼습니다',
};

/** 숨이 이 값 아래면 손이 떨린다 */
export const isWinded = (breath) => breath <= RUN.windedAt;
