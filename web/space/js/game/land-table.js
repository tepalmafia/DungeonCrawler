/** 진입각이 지금 어떤가 — 조종석 계기와 손목이 쓴다 */
export function tiltWord(tilt, band = LAND.band) {
  const a = Math.abs(tilt);
  if (a < band * 0.45) return '자세 안정';
  if (a < band) return '자세가 흔들립니다';
  return '선체가 탑니다';
}

