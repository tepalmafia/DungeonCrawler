/**
 * 지금 내릴 수 있나 — 안 되면 이유를 돌려준다.
 * @param s { step, chase, offered }
 */
export function whyNotLand(s = {}) {
  if (s.chase) return 'chase';
  if (!s.offered) return 'noPlanet';
  if (s.step === STEP.LANDED) return 'already';
  if (s.step && s.step !== STEP.NONE && s.step !== STEP.FOUND) return 'busy';
  return null;
}

