// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **배가 떠는 모양** — 뼈대 (v131). three 도 DOM 도 안 쓴다.
//
//  ★ 사장님 (2026-08-13) 「**조준경이 빠르게 떨리는데 자연스럽게 바꿔줘.
//    눈 아프다. 현실감있게 하기 위해서 넣은건가?**」
//
//  ══ 답: 그렇습니다. 그리고 **틀린 현실감이었습니다** ═══════════════════
//
//  기관 진동을 넣으려고 `CRUISE.shakeHz = 11.3` 을 두었습니다. 재 보니
//  조준경이 화면에서 **초당 11.3번, 10화소씩** 튀고 있었고 (쫓기면 26화소),
//  그건 「진동」이 아니라 **깜빡임**입니다.
//
//  ★★★ 왜 진짜 조종석에서는 안 그런가 — **머리가 같이 흔들리기 때문**입니다.
//    실제 조종사는 배와 한 몸이라 눈과 HUD 가 **함께** 떨고, 그래서 조준경은
//    눈에 대해 **가만히** 있습니다. 남는 것은 바깥 풍경의 떨림뿐입니다.
//    그런데 화면 앞에 앉은 사람은 머리가 안 떨립니다 — **그림만 떱니다.**
//    전정기관이 상쇄해 줄 것이 없으니 눈이 계속 따라가려 하고, 그게 피로입니다.
//
//  ★★ 게다가 이 배의 조준경은 **배에 붙어 있습니다** (`ship.add(sight.mesh)`).
//    즉 카메라가 떨면 조준경이 화면에서 그대로 떱니다 — 실제와 **정반대**입니다.
//
//  ★ 그래서 「현실감을 위해」 넣은 것이 현실과 반대로 가 있었습니다.
//    고증이 시키는 것은 **더 떠는 것이 아니라 덜 떠는 것**입니다.
//
//  ══ 그러면 무엇을 남기나 ═══════════════════════════════════════════════
//
//  0 으로 두면 배가 죽은 것이 됩니다. 남길 것은 「살아 있다」는 느낌이고,
//  그건 **빠르기가 아니라 느림**에서 옵니다 — 배는 큰 물건이고 큰 물건은
//  천천히 움직입니다. 그래서 **성분을 모두 2.2Hz 아래**로 두고 여러 겹을
//  포갭니다. 주기가 서로 무리수 비라 **무늬가 안 생기고**, 그래서
//  「규칙적으로 흔들린다」가 아니라 「가만히 못 있는다」로 읽힙니다.
// ══════════════════════════════════════════════════════════════════════════

export const LOOK = {
  /**
   * ★★★ **이보다 빠른 성분을 두지 않는다** (Hz).
   *
   *   ★ 작은 진폭의 화면 흔들림이 제일 아픈 구간이 대략 **8~20Hz** 다
   *     (눈이 따라갈 수도, 무시할 수도 없는 자리). v130 까지의 11.3 이
   *     그 한복판이었다. 2.2 는 「배가 뒤척인다」로 읽히는 위쪽 끝이다
   */
  maxHz: 2.2,
  /**
   * ★★★ **조준경이 화면에서 튀어도 되는 폭** (화소 · 세로 760 기준).
   *   재는 자를 「유닛」이 아니라 **화소**로 둔다 — 아픈 것은 미터가
   *   아니라 눈에 보이는 움직임이기 때문이다. v130 은 10 화소였다
   */
  seePx: 3.0,
  /**
   * ★★★ 위아래 폭 (m) — 아래 `parts` 의 합에 곱해진다.
   *   ★ **화소로 골랐다.** 0.0016 을 넣고 재니 4.56 화소라 위 `seePx` 를
   *     넘었다 — 미터로 짐작하지 않고 검사가 시키는 대로 내렸다
   */
  amp: 0.001,
  /** 좌우로 기우뚱하는 폭 (m) — 위아래보다 크고 훨씬 느리다 */
  sway: 0.011,
  /** 기울어지는 몫 (라디안/유닛) — 좌우 흔들림에 딸려 온다 */
  roll: 0.06,
  /**
   * ★★ **여러 겹을 포갠다.** 주기가 서로 정수배가 아니라야 무늬가 안 생긴다
   *   (0.29 · 0.71 · 1.83 은 서로 나누어떨어지지 않는다). 합이 1 이다
   */
  parts: [
    { hz: 0.29, amp: 0.55, what: '배가 크게 뒤척인다' },
    { hz: 0.71, amp: 0.30, what: '그 위의 결' },
    { hz: 1.83, amp: 0.15, what: '제일 빠른 것 — 여기가 상한이다' },
  ],
  /** 좌우는 한 겹이면 된다 — 느리므로 겹칠 것이 없다 */
  swayHz: 0.23,
};

/** 제일 빠른 성분 (Hz) — 검사가 여기서 「눈 아픈 구간을 피했나」를 본다 */
export const topHz = () => Math.max(LOOK.swayHz, ...LOOK.parts.map((p) => p.hz));

/**
 * ★★★ **이 순간 눈이 얼마나 밀렸나.**
 *
 *   ★ 게임도 검사도 **이 함수 하나**를 부른다. `main.js` 가 제 방식으로
 *     사인을 다시 쓰기 시작하면 그때부터 갈라진다
 *
 * @param t   시계 (초)
 * @param mul 배수 — 쫓김·굶주림·급가속이 곱해 온다
 * @returns `{ y, x, roll }` — 위아래(m) · 좌우(m) · 기울기(rad)
 */
export function shakeAt(t, mul = 1) {
  let y = 0;
  for (const p of LOOK.parts) y += p.amp * Math.sin(t * p.hz * Math.PI * 2);
  const x = Math.sin(t * LOOK.swayHz * Math.PI * 2);
  return {
    y: LOOK.amp * mul * y,
    x: LOOK.sway * mul * x,
    roll: LOOK.sway * mul * x * LOOK.roll,
  };
}

/**
 * ★★★ **조준경이 화면에서 몇 화소나 튀나** (마루~골).
 *
 *   ★ 조준경은 **배에 붙어 있으므로**(`world/ship.js`) 눈이 밀린 만큼
 *     화면에서 그대로 밀린다. 그 셈을 여기 한 곳에 둔다 —
 *     검사가 「유닛」이 아니라 **눈에 보이는 값**으로 물을 수 있게
 *
 * @param mul     배수 · @param dist 눈에서 조준경까지 (m)
 * @param fovDeg  세로 화각 · @param h 화면 세로 (화소)
 */
export function seenPx(mul = 1, dist = 0.65, fovDeg = 94, h = 760) {
  const peak = LOOK.amp * mul * LOOK.parts.reduce((s, p) => s + p.amp, 0);
  const deg = (2 * Math.atan((2 * peak) / dist) * 180) / Math.PI;
  return +((deg / fovDeg) * h).toFixed(2);
}

/** 사람이 읽는 한 줄 */
export const shakeWord = () =>
  `배 떨림 — 제일 빠른 것 ${topHz()}Hz · 조준경이 ${seenPx()}화소`;
