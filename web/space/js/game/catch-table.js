/** 사람이 읽는 한 마디 — 계기가 이 한 줄만 쓴다 */
export function catchWord(c) {
  if (!c || c.id === null) return '';
  if (c.arrived) return '포획 — 붙었습니다';
  return `포획 중 ${Math.max(0, c.dist).toFixed(0)}m — K 로 끊습니다`;
}

/** 이 거리를 붙는 데 몇 초 걸리나 — 도구와 계기가 같은 식을 쓴다 */
export const catchTime = (dist) =>
  +(Math.max(0, dist - 0) / CATCH.speed).toFixed(2);
