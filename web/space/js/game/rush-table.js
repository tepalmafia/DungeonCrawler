/** 0..1 사이 섞기 */
const mix = (a, b, k) => a + (b - a) * k;

/**
 * ★★★ **빠르기 하나가 화면 신호 넷을 민다.**
 *
 * @param v 0 = 정지 · 1 = 전속 · 1.75 = 급가속 (곡선의 끝)
 * @returns { dust, len, glow, fov }
 */
export function feelAt(v = 0) {
  const s = Math.max(0, v);
  const one = (f) => {
    if (s <= 1) return mix(f.at0, f.at1, s);
    //  ★ 1 을 넘는 구간(급가속)은 **같은 곡선의 연장**이다. 여기를 딴 식으로
    //    두면 그 순간 「스위치」가 되고, 그게 v143 까지의 병이었다
    const k = Math.min(1, (s - 1) / 0.75);
    return mix(f.at1, f.boost, k);
  };
  return {
    flow: +one(RUSHF.flow).toFixed(3),
    len: +one(RUSHF.len).toFixed(2),
    glow: +one(RUSHF.glow).toFixed(3),
    fov: +one(RUSHF.fov).toFixed(2),
  };
}

/**
 * ★★ **스로틀·급가속을 빠르기 하나로 모은다** — 축을 둘로 안 만든다.
 * @param throttle 0~1 (역추진이면 음수로 온다 — 크기만 쓴다)
 * @param boost    0~1 (R 꾹)
 */
export const speedOf = (throttle = 0, boost = 0) =>
  Math.min(1, Math.abs(throttle)) + Math.max(0, Math.min(1, boost)) * 0.75;

/** 사람이 읽는 말 — 계기가 「지금 얼마나 빠른가」를 글로도 말한다 */
export function rushWord(v = 0) {
  if (v <= 0.02) return '정지';
  if (v < 0.55) return '순항';
  if (v <= 1.02) return '전속';
  return '급가속';
}
