/**
 * ★ 늘리는 것의 사람 이름. **검사가 「냉각제 — sink -18」을 뱉어서 알았다** —
 *   여기 빠진 열쇠는 **날것 그대로 화면에 나온다.** 표를 늘리면 여기도
 *   늘려야 하고, 안 늘리면 도구가 그 자리에서 보여 준다
 */
export const GAIN_NAME = {
  parts: '부품', ore: '광석', arc: '전지', food: '식량',
  coolant: '냉각제', missiles: '미사일', sink: '열',
};

/** 이 물건이 늘리는 것 — `{ key, n }` 목록 */
export const givesOf = (key) => Object.entries(ITEMS[key]?.use ?? {}).map(([k, n]) => ({ key: k, n }));

/**
 * 한 줄 요약. 예: 「광석 ×10 — 파츠를 올린다」
 * ★ 개수가 1 이면 「×1」을 안 적는다 — 눈이 읽을 것이 하나 준다
 */
export function summaryOf(key, count = 1) {
  const g = givesOf(key);
  // ★★ **부호가 뜻을 바꾼다.** 냉각제의 `sink: -18` 은 「열을 −18 준다」가
  //   아니라 **「열을 18 던다」**이다. 마이너스를 그대로 찍으면 사람은
  //   「나쁜 것」으로 읽는다 — 검사가 「냉각제 — sink -18」을 뱉어서 알았다
  const gain = g.map((x) => {
    const nm = GAIN_NAME[x.key] ?? x.key;
    const v = x.n * count;
    return v < 0 ? `${nm} ${-v} 덜기` : `${nm} ${v}`;
  }).join(' · ');
  const use = USE_WORD[g[0]?.key] ?? '';
  return { name: nameOf(key), gain, use, mass: massOf(key) };
}

/** 사람이 읽는 한 줄 (검사와 배너가 같이 쓴다) */
export const summaryLine = (key, count = 1) => {
  const s = summaryOf(key, count);
  return `${s.name}${count > 1 ? ` ×${count}` : ''} — ${s.gain}${s.use ? ` · ${s.use}` : ''}`;
};

/** 물음 한 줄 — **무엇이 나왔는지 같이 말한다.** 「회수?」만 뜨면 못 정한다 */
export function askLine(items) {
  const names = [...new Set(items.map((i) => nameOf(i.key)))].slice(0, 3).join(' · ');
  return `${names || '잔해'} — 회수하겠습니까? (Y / N)`;
}

