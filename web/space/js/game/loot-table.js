//  물음에 「예」라고만 해도 저절로 그 방법이 골라지니, 회수는 늘 **부딪힐
//  만큼 다가가는 일**이 됐다.
//
//  ★★ 고르는 자리를 뒤집는다: **닿는 것 중 제일 멀리서 되는 것**을 고른다.
//    그물은 80m 까지 닿으므로 물체가 **눈에 보이는 거리**에서 감을 수 있다.
//    도킹 팔은 없애지 않는다 — **F 로 일부러 고르는** 빠른 길로 남는다
