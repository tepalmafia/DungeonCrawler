//
//  ★★★ 그리고 **거리를 여기 다시 안 적는다.** 25·80 이 `cargo-table.js
//    WAYS` 에도 있어서 두 곳이었다 — 한쪽만 고치면 「표는 닿는다는데
//    안 걸리는」 상태가 된다
export const wayFor = (dist) => (dist <= WAYS.net.reach ? 'net' : 'bot');
