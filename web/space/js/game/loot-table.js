// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **줍겠습니까 · 무엇을 주웠나** — 표만 (v121). three 를 안 쓴다.
//
//  ★ 사장님 (2026-08-12)
//    「적을 격추하거나 물체를 격추하면 **아이템을 회수하겠습니까? 질문이
//     나오고** 회수하는 것으로. 그리고 **아이템을 먹으면 아이템 요약이
//     뜨도록** 해줘. **형태와 요약.**」
//
//  ══ ★★ 왜 「질문」이 이 게임에 맞나 ═══════════════════════════════════
//
//  회수는 v80 부터 **이 게임의 값**이었다 (`salvage-table.js`):
//  부수는 데 3~7초, 줍는 데 3~6초, 그 사이에 **지원이 온다.** 그래서
//  매번 「이건 줍고 저건 버린다」를 정하게 되고, 그게 「뚫는다」다.
//
//  ★ 그런데 v120 까지 그 결심을 **말해 주는 곳이 없었다.** 부수면 꾸러미가
//    조용히 떠 있고, 아는 사람만 F/G/B 를 눌렀다. 결심이 있는데 **결심을
//    묻지 않는** 상태였고, 사장님이 「질문이 나오고」라고 하신 것이 정확히
//    그 자리다.
//
//  ★★★ 그래서 **질문은 새 결심을 만드는 것이 아니라 이미 있던 결심을
//    드러내는 것**이다. 「예」를 누르면 **이미 있는 회수 셋**(도킹 팔 ·
//    그물 · 로봇)에서 **지금 자리에 맞는 하나**가 골라져 나간다 —
//    새 조작을 안 만든다 (「들어가는 길을 하나만 만들지 않는다」의 반대편:
//    **길을 늘리되 뜻을 늘리지 않는다**).
//
//  ══ ★★ 그리고 「안 줍는다」가 진짜 답일 때가 있어야 한다 ═══════════════
//
//  늘 「예」가 답이면 질문이 아니라 **확인 절차**다. 안 줍는 쪽이 이기는
//  자리를 표가 만든다:
//
//    · 질문은 **몇 초 안에** 사라진다 (`ASK.window`) — 싸우는 중에는
//      물음에 답할 손이 없다
//    · 화물칸이 차 있으면 **버릴 것을 골라야** 한다 (`cargo.js`)
//    · 줍는 동안 **자국이 오른다** (`WAYS[*].sign`) — 훤해진다
//
//  ══ ★★★ 「형태와 요약」 — 왜 도형인가 ════════════════════════════════
//
//  ★ 이 저장소의 절대 규칙은 **「그림은 사장님이 주신다」**이다. 그런데
//    **도형·색·계기·도해는 내 몫**이라고 같은 문서가 적어 두었고,
//    `legend-table.js` 가 이미 적/물건/행성을 **도형과 색**으로 가른다.
//    여기 도형은 그 규약을 **잇는** 것이지 새 그림이 아니다.
//
//  ★★ 그리고 도형이 있어야 **읽기 전에 안다.** 요약을 글로만 띄우면
//    싸우는 중에는 아무도 안 읽는다 — 이 저장소가 손목·상태창에서
//    되풀이해 배운 것이다 (「띠의 길이와 낱말이 판단을 만든다」).
// ══════════════════════════════════════════════════════════════════════════
import { ITEMS, nameOf, massOf } from './cargo-table.js';

/**
 * ★★ **질문** — 부수면 뜬다.
 *
 *  @property window  이 안에 답 안 하면 사라진다 (초). 꾸러미는 남는다 —
 *                    **질문만** 사라진다. 「못 봤다」가 「못 줍는다」가 되면
 *                    그건 벌이지 결심이 아니다
 *  @property yes/no  손가락 둘 — 실제 시뮬의 확인 키와 같은 자리
 *  @property auto    ★ 이 안에 있으면 **묻지 않고 줍는다.** 코앞의 것까지
 *                    물으면 질문이 잔소리가 된다 (도킹 팔 사거리와 같은 값)
 *  @property minGap  질문 사이 최소 간격 (초) — 연달아 부수면 물음이 쌓여
 *                    화면이 물음표로 덮인다
 */
export const ASK = {
  window: 6.0,
  yes: 'KeyY',
  no: 'KeyN',
  auto: 12,
  minGap: 1.2,
};

/**
 * ★★ **주운 뒤 요약 카드.**
 *
 *  @property hold   한 장이 떠 있는 시간 (초)
 *  @property max    한꺼번에 쌓이는 최대 장수 — 넘으면 오래된 것부터 지운다
 *  @property stack  같은 것을 연달아 주우면 **한 장에 개수로** 묶는다
 */
export const CARD = { hold: 3.4, max: 3, stack: true };

/**
 * ★★★ **형태** — 물건 무리마다 도형이 다르다.
 *
 *   ★ `legend-table.js` 가 하늘의 것을 도형으로 가르는 것과 **같은 규약**이다.
 *     거기서 적은 △ · 물건은 ◇ · 행성은 ○ 였다. 화물은 그 아래 갈래이므로
 *     **네모 계열**로 두고 안에서 갈랐다 — 하늘의 것과 안 헷갈려야 한다
 *
 *   · `box`  네모 — 부품처럼 **쌓이는 것**
 *   · `drum` 통  — 액체·가스처럼 **담는 것**
 *   · `cell` 전지 — 칸이 있는 것. 아크 전지
 *   · `pack` 봉지 — 식량처럼 **무른 것**
 */
export const SHAPES = {
  spare: 'box',
  ore: 'box',
  arc: 'cell',
  coolant: 'drum',
  meal: 'pack',
  ration: 'pack',
};
export const shapeOf = (key) => SHAPES[key] ?? 'box';

/** 무리마다 색 — 상태창·범례와 같은 계열로 둔다 */
export const TONES = {
  supply: '#7fd8c0',
  food: '#e8c46a',
};
export const toneOf = (key) => TONES[ITEMS[key]?.group] ?? '#9fb6c8';

/**
 * ★★★ **요약 한 줄** — 「이게 나에게 무엇을 해 주나」.
 *
 *   ★ `cargo-table.js` 의 `use` 를 읽어서 짓는다. 여기서 손으로 적으면
 *     표가 바뀔 때 **말과 값이 갈라진다** — 이 저장소가 제일 자주 밟는
 *     함정이다. 「무엇에 쓰나」만 여기서 더한다
 */
export const USE_WORD = {
  parts: '수리에 쓴다',
  ore: '파츠를 올린다',
  arc: '아크 도약에 쓴다',
  food: '허기를 던다',
  sink: '열을 던다',
  coolant: '열을 던다',
  missiles: '쏠 것이 는다',
};

/**
 * ★ 늘리는 것의 사람 이름. **검사가 「냉각제 — sink -18」을 뱉어서 알았다** —
 *   여기 빠진 열쇠는 **날것 그대로 화면에 나온다.** 표를 늘리면 여기도
 *   늘려야 하고, 안 늘리면 도구가 그 자리에서 보여 준다
 */
export const GAIN_NAME = {
  parts: '부품', ore: '광석', arc: '전지', food: '식량',
  coolant: '냉각제', missiles: '미사일', sink: '열',
};

/** 이 물건이 늘리는 것 — `{ key, n }` 목록 */
export const givesOf = (key) => Object.entries(ITEMS[key]?.use ?? {}).map(([k, n]) => ({ key: k, n }));

/**
 * 한 줄 요약. 예: 「광석 ×10 — 파츠를 올린다」
 * ★ 개수가 1 이면 「×1」을 안 적는다 — 눈이 읽을 것이 하나 준다
 */
export function summaryOf(key, count = 1) {
  const g = givesOf(key);
  // ★★ **부호가 뜻을 바꾼다.** 냉각제의 `sink: -18` 은 「열을 −18 준다」가
  //   아니라 **「열을 18 던다」**이다. 마이너스를 그대로 찍으면 사람은
  //   「나쁜 것」으로 읽는다 — 검사가 「냉각제 — sink -18」을 뱉어서 알았다
  const gain = g.map((x) => {
    const nm = GAIN_NAME[x.key] ?? x.key;
    const v = x.n * count;
    return v < 0 ? `${nm} ${-v} 덜기` : `${nm} ${v}`;
  }).join(' · ');
  const use = USE_WORD[g[0]?.key] ?? '';
  return { name: nameOf(key), gain, use, mass: massOf(key) };
}

/** 사람이 읽는 한 줄 (검사와 배너가 같이 쓴다) */
export const summaryLine = (key, count = 1) => {
  const s = summaryOf(key, count);
  return `${s.name}${count > 1 ? ` ×${count}` : ''} — ${s.gain}${s.use ? ` · ${s.use}` : ''}`;
};

/** 물음 한 줄 — **무엇이 나왔는지 같이 말한다.** 「회수?」만 뜨면 못 정한다 */
export function askLine(items) {
  const names = [...new Set(items.map((i) => nameOf(i.key)))].slice(0, 3).join(' · ');
  return `${names || '잔해'} — 회수하겠습니까? (Y / N)`;
}

/**
 * ★★ **어느 방법으로 줍나** — 거리가 정한다.
 *   사람이 셋 중 고르는 것은 그대로 두되(`WAYS` 의 F/G/B), **「예」는
 *   지금 자리에 맞는 것**을 고른다. 안 그러면 질문이 「그래서 뭘 누르지」가
 *   되어 결심을 하나 더 만든다 — 물어보는 값이 물어보는 뜻보다 커진다
 */
export const wayFor = (dist) => (dist <= 25 ? 'arm' : dist <= 80 ? 'net' : 'bot');
