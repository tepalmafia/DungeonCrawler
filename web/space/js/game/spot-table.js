/** 지금 접히나 — 물었을 때만 접는다 */
export const folds = (locked = false) => (locked ? FOLDED.map((f) => f.key) : []);

/**
 * ★★ 표적 하나 둘레에 지금 몇 개가 그려지나 — 뼈대가 세는 자리.
 *   @param locked 물었나
 *   @returns 표식 이름들
 */
export function marksAround(locked = false) {
  const all = ['glyph', 'rangeRing', 'wobble', 'gate'];
  const off = new Set(folds(locked));
  //  ★ 게이트 상자는 **물었을 때만** 뜬다 (그래서 반대로 걸러진다)
  return all.filter((k) => (k === 'gate' ? locked : !off.has(k)));
}
