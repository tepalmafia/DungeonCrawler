// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **스로틀 — 전진과 역추진** (v101). 숫자만. 규칙은 `throttle.js`.
//
//  ★ 사장님 「w, s 키는 상하좌우가 아닌 **전진 후진**으로 바꿔줘」
//    「**추력은 다른 키로 만들고 역추진을 만들어**」
//
//  ══ v100 에서 제가 접었던 것을 폅니다 ═════════════════════════════════
//
//  v100 에 W/S 를 추력 **켜기/끄기**로 붙이고 「이 배에 역추진은 없다」고
//  적었습니다. 사장님이 「**만들어**」라고 하셨으므로 만듭니다.
//
//  ★★ 그런데 v100 의 그 판단에는 근거가 하나 있었습니다: **켜기/끄기는
//    조작이 아니다.** 두 자리뿐인 값은 고를 것이 없습니다. 스로틀을
//    **축**으로 만들면 그 문제까지 같이 풀립니다 — 얼마나 밀지가 생깁니다.
//
//  ══ ★★★ 역추진이 **무엇을 위한 것인가** ══════════════════════════════
//
//  값이 없으면 「뒤로 가는 단추」일 뿐입니다. 이 배에서 뒤로 가는 것은
//  **거리를 벌리는 일**이고, 그것이 v100 의 발사관과 맞물립니다:
//
//    · 적은 55~85m 를 잡고 싸웁니다 (`KINDS.raider.standoff`)
//    · 레이저는 90m 까지 (`WEAPONS.laser.rMax`) · 유도탄은 더 멀리
//    · 발사관은 짐벌 ±55도라 **동체를 안 돌려도 물고 있습니다**
//
//  ★★★ 그래서 「**뒤로 빼면서 발사관으로 문다**」가 성립합니다 —
//    붙어서 레이저로 훑는 것과 정반대의 싸움 방식이고, v100 이 연
//    「붙을까 뺄까」에 **거리 축**을 하나 더 얹습니다.
//
//  ══ 값 — 공짜가 아닙니다 ═════════════════════════════════════════════
//
//    ① **추진제를 더 먹습니다.** 주 엔진은 뒤에 있으므로 뒤로 가려면
//       배를 돌리거나 보조 추력기를 씁니다 — 어느 쪽이든 비쌉니다
//    ② **항로가 안 나아갑니다.** 12구간을 2시간에 가야 하는데 뒤로
//       빼는 동안은 시계만 흐릅니다
//    ③ **열이 오릅니다** — 보조 추력기도 엔진입니다
//
//  ★ three.js 를 안 씁니다 — `tools/space-throttle.js` 가 읽습니다.
// ══════════════════════════════════════════════════════════════════════════

export const THROTTLE = {
  /**
   * ★★★ **뒤로 얼마나 갈 수 있나** (−1 ~ +1 중 아래쪽 끝).
   *
   *   −0.45 · 앞으로 가는 것의 **절반이 안 됩니다.** 주 엔진이 뒤에
   *   달린 배이므로 당연하고, 그래야 「도망은 뒤로가 아니라 **돌아서**」가
   *   유지됩니다 — 뒤로 전속력이면 360도 선회(v73)를 만든 뜻이 없어집니다
   */
  min: -0.45,
  max: 1,
  /** W/S 한 번에 스로틀이 이만큼 움직입니다 (초당) — 홱 안 바뀝니다 */
  rate: 0.9,
  /**
   * ★★ **가운데로 안 돌아옵니다.** v55 에 사장님이 「놓으면 가운데로
   *   돌아온다」를 고치라고 하신 그 규약입니다 — 이 배는 수동입니다.
   *   되돌리는 것도 손이 합니다
   */
  selfCenter: false,
  /** 이보다 작으면 「멈춤」으로 봅니다 (0 을 딱 맞추기 어렵습니다) */
  dead: 0.06,

  // ── 값 ────────────────────────────────────────────────
  /**
   * ★★★ **역추진은 추진제를 더 먹습니다** (앞으로 갈 때의 배수).
   *   1.8 — 주 엔진이 아니라 보조 추력기로 밀기 때문입니다.
   *   그래서 「계속 뒤로 빼며 싸우기」가 추진제로 막힙니다
   */
  backFuel: 1.8,
  /** 역추진 중에 열이 이만큼 오릅니다 (초당) — 보조 추력기도 엔진입니다 */
  backHeat: 2.6,
  /**
   * ★★ **뒤로 갈 때 적과 벌어지는 속도** (m/초).
   *   적이 다가오는 속도(`TARGET.closing` 5.5 · `closes` 5~22)와 견주면
   *   **느린 적은 떼어 놓고 빠른 적은 못 뗍니다** — 그게 종류를 다섯으로
   *   나눈 뜻과 맞물립니다
   */
  backAway: 7.5,
};

/** 지금 스로틀이 앞인가 (`dead` 밖) */
export const isFwd = (v) => v > THROTTLE.dead;
/** 뒤인가 — **역추진 중** */
export const isBack = (v) => v < -THROTTLE.dead;

/**
 * ★★ **항로가 나아가는 배수** (0~1).
 *   뒤로 갈 때는 **0** 입니다 — 뒤로 간 만큼 항로를 되돌리지는 않습니다.
 *   되돌리면 12구간이 24구간이 되고, 그건 벌이 아니라 지겨움입니다
 */
export function legMult(v, coast) {
  if (isBack(v)) return 0;
  if (!isFwd(v)) return coast;
  // 반쯤 밀면 반쯤 간다 — 관성으로 가는 몫(`coast`) 위에 얹습니다
  return coast + (1 - coast) * Math.min(1, v);
}

/** 사람이 읽는 한 마디 — 계기가 이 한 줄만 씁니다 */
export function throttleWord(v) {
  if (isBack(v)) return '역추진';
  if (!isFwd(v)) return '타성';
  if (v > 0.85) return '전속';
  return '순항';
}
