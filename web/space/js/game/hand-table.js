// ══════════════════════════════════════════════════════════════════════════
//  손 — 자리와 크기. **여기가 다섯 판을 태운 그 숫자다.**
//
//  ★ 왜 표로 빼는가
//    앞 저장소에서 몸을 다섯 판 태웠는데, 마지막에 원인이 나온 것은
//    사장님이 참고 이미지를 한 장 주셨을 때였다 — **스프라이트 액션 RPG 는
//    5등신인데 나는 8등신으로 만들고 있었다.** 즉 틀린 것은 솜씨가 아니라
//    **비율 숫자 하나**였고, 그 숫자가 코드 여기저기 흩어져 있으면
//    「어디를 고쳐야 달라지는지」를 못 찾는다.
//
//    그래서 손은 **숫자를 한 곳에 모아** 둔다. 「손이 크다/작다」·「너무
//    가운데 있다」는 말씀을 들으면 여기 한 줄만 고치면 된다.
//
//  ★ 1인칭 손은 실물 크기로 만들면 안 된다
//    시야각(72°) 때문에 실제 비율대로 넣으면 **멀리 있는 작은 손**으로
//    보인다. 어느 게임이나 1.2~1.5배로 키우고 카메라 가까이 붙인다.
//
//  ★ three.js 를 안 쓴다 — tools 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const HAND = {
  /**
   * 실물 대비 배율. 1.0 이면 「멀리 있는 작은 손」으로 보인다.
   * ★ 1.35 로 시작했다가 1.15 로 내렸다 — 첫 판을 찍어 보니 **소매 통 안에
   *   카메라가 들어가** 화면 아래 절반이 두 개의 구멍이었다.
   */
  scale: 1.15,

  // ★ 자리도 첫 판에서 (z -0.34 / -0.44) 였다. 시야각 72° 에서 0.34m 는
  //   **카메라가 손 안에 있는** 거리다. 뒤로 물리고 아래로 내렸다.
  // ★ **비스듬히 서야 한다.** 두 번째 판에서는 손이 정면을 향해 있어서
  //   소매 끝 마개가 카메라를 마주 봤다 — 손등이 아니라 **통 두 개**가
  //   보였다. `ry` 를 크게 줘서 바깥에서 안쪽을 향하도록 비틀면 손등과
  //   손가락 마디가 보인다. 1인칭 손이 화면 구석에서 들어오는 이유다.
  /** 아무것도 안 할 때 — 화면 아래 구석에서 비스듬히 들어온다 */
  rest: { x: 0.30, y: -0.40, z: -0.48, rx: -0.42, ry: 0.72, rz: 0.30 },
  /** 손잡이에 손을 뻗었을 때 — 앞으로 나가고 손등이 보인다 */
  aim: { x: 0.21, y: -0.27, z: -0.60, rx: -0.16, ry: 0.42, rz: 0.12 },

  /** 뻗고 쥐는 속도(1/초). 느리면 굼뜨고 빠르면 딸깍거린다 */
  reachSpeed: 9,
  gripSpeed: 12,

  /**
   * 굶었을 때 떨리는 폭(m).
   * ★ 「손이 곧 상태창」(PLAN §5-2)이 **처음으로 화면에 나온 자리**다.
   *   체력바를 안 만드는 대신 이걸로 말한다. 크게 흔들면 멀미가 나므로
   *   **눈에 겨우 보이는 만큼**이 맞다
   */
  shake: 0.0045,
};

/**
 * 어떤 손잡이가 **양손**인가.
 *
 * ★ 한 손으로 될 것을 양손으로 만들면 「거창한데 아무 뜻이 없는」 동작이
 *   된다. 실제로 두 손이 필요한 것만 넣는다 — 조종간(좌우로 민다) ·
 *   밸브(큰 바퀴를 돌린다) · 크랭크(힘을 준다) · 윈치(줄을 당긴다).
 *   차단기·해도대·패널은 한 손이면 된다.
 */
export const BOTH_HANDS = new Set(['yoke', 'valve', 'winch']);

/** 조준 이름이 손잡이인가 — `panel:workshop` · `crank:engine` 처럼 뒤가 붙는다 */
export function isGrip(aim) {
  if (!aim) return false;
  return true;
}

/** 그 조준 이름이 양손인가 */
export function bothHands(aim) {
  if (!aim) return false;
  const head = String(aim).split(':')[0];
  return BOTH_HANDS.has(head) || BOTH_HANDS.has(String(aim));
}
