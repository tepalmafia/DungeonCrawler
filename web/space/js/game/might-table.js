// ══════════════════════════════════════════════════════════════════════════
//  전투력 — **싸울지 피할지를 정하는 숫자** (v79)
//
//  ★ 사장님 (2026-08-09):
//    「가는 길에 **나보다 강한 상대나 많은 적들은 피하거나 도망**가고
//     **흩어진 적이나 전투력이 낮은 적은 파괴**하면서 진행」
//    「**상대 우주선의 전투력도 표시**되고 **우리 비행기의 전투력 차이**」
//    「상대우주선을 **격추할때마다 적의 무기나 장갑을 회수**하면서
//     **나도 전투력이 올라가게** 설계하시오」
//
//  ★★ **이 숫자가 없으면 「피한다」가 성립하지 않는다.** 지금까지 이 게임에는
//    「이 적이 나보다 센가」를 사람이 알 방법이 아예 없었다 — 맷집도 화력도
//    표 안에만 있었고, 화면에는 「적 우주선」이라는 이름 하나뿐이었다.
//    그 상태에서 「강하면 피하라」고 하면 그건 **다 붙어 보고 죽어서 배우라**는
//    말이다. 2시간짜리에서 그건 못 할 짓이다.
//
//  ★★★ 그리고 이것이 **목적 한 줄과 붙는다** (`WAR.md`): 뚫는다 · 채운다 ·
//    떨군다. **뚫는다는 다 부순다는 뜻이 아니다** — 뚫는다는 **고른다**는
//    뜻이다. 고르려면 견줄 숫자가 있어야 한다.
//
//  ── 값은 이미 있는 것에서만 뽑는다 ─────────────────────────────────
//
//  새 숫자를 손으로 적지 않는다. 적의 전투력은 `target-table.js KINDS` 의
//  **맷집·화력·속도·떼**에서 계산하고, 내 전투력은 **무기·선체·노획**에서
//  계산한다. 손으로 적으면 밸런스를 고칠 때 반드시 한쪽만 고쳐진다 —
//  이 저장소가 `?v=` 와 `VERSION` 으로 스무 판을 어긋난 채 배포한 적이 있다.
//
//  ★ three.js 를 안 쓴다.
// ══════════════════════════════════════════════════════════════════════════
import { KINDS } from './target-table.js';

/**
 * ★ 적의 전투력을 무엇으로 재나 — **네 가지**다.
 *
 *   맷집  얼마나 오래 버티나 (`hits`)
 *   화력  쏘나 · 얼마나 세게 (`shoots` · `punch`)
 *   속도  얼마나 빨리 붙나 (`closes`) — 빠른 것이 어렵다
 *   떼    한 번에 몇이 오나 (`pack`)
 *
 *   ★ 크기는 **안 센다.** 큰 것은 맞히기도 쉬워서 상쇄된다 —
 *     `hits` 가 이미 그 값을 들고 있다 (포함 10 · 자폭정 1)
 */
export const WEIGH = {
  hit: 1.0,
  gun: 3.0,
  punch: 2.2,
  close: 0.14,
  /** 떼는 **곱이 아니라 제곱근**이다. 셋이 와도 셋 배로 무섭지는 않다 —
   *  하나씩 떼어 잡을 수 있으므로. 그래도 하나보다는 확실히 무섭다 */
  packPow: 0.62,
};

/**
 * ★★★ **적 하나**의 전투력 — 떼는 안 센다.
 *
 *   처음엔 여기서 `pack` 까지 곱했는데, 그러면 **화면이 거짓말을 한다.**
 *   요격기는 셋이 흩어져 오고 광학 창에는 **그중 하나**가 뜬다. 거기에
 *   셋 몫(18.7)을 적으면 「저 한 대가 포함보다 세다」로 읽힌다.
 *   ★ 하나는 `mightOf`, 떼는 `packMight` — **묻는 자리가 다르면 답도 다르다**
 */
export function mightOf(kind) {
  const k = typeof kind === 'string' ? KINDS[kind] : kind;
  if (!k) return 0;
  let m = (k.hits ?? 1) * WEIGH.hit;
  if (k.shoots) m += WEIGH.gun + (k.punch ?? 1) * WEIGH.punch;
  // ★ **들이받는 것의 `punch` 도 센다** — 처음엔 `shoots` 일 때만 셌더니
  //   자폭정이 4.1 로 나왔다. 자폭정은 안 쏘는 대신 **몸이 탄**이고
  //   punch 가 3.2 다 (적 중 제일 세다). 「안 쏘니까 약하다」는 그 적을
  //   만들 때의 뜻과 정반대다 — 재 보고 알았다
  if (k.rams) {
    m += Math.max(0, k.closes ?? 0) * WEIGH.close;
    if (!k.shoots) m += (k.punch ?? 1) * WEIGH.punch;
  }
  return +m.toFixed(1);
}

/**
 * ★★ **떼로 보면** 얼마나 되나 — 레이더가 「지금 몇이 붙었나」를 물을 때.
 * @param n 몇 대인가. 안 주면 표의 `pack`
 */
export function packMight(kind, n = null) {
  const k = typeof kind === 'string' ? KINDS[kind] : kind;
  const c = n ?? k?.pack ?? 1;
  return +(mightOf(kind) * Math.pow(Math.max(1, c), WEIGH.packPow)).toFixed(1);
}

/** 지금 떠 있는 것들을 통째로 — 「이 판을 붙을 만한가」 */
export function threatOf(list) {
  let sum = 0;
  for (const t of list ?? []) sum += mightOf(t.kind);
  // ★ 여럿을 그냥 더하면 다섯 대가 다섯 배로 무서워진다 — 하나씩 떼어
  //   잡을 수 있으므로 실제로는 그보다 덜하다. 떼와 **같은 자**를 쓴다
  const n = Math.max(1, (list ?? []).length);
  return +(sum / n * Math.pow(n, WEIGH.packPow)).toFixed(1);
}

/**
 * ★★ **내 전투력** — 무엇을 들고 있나 + 얼마나 뺏었나.
 *
 *   ★ 선체를 넣는 이유: 맞아 가며 버티는 것도 전투력이다. 그리고 이게
 *     들어가야 **「깎이면 약해진다」**가 성립한다 — 피해가 숫자로만
 *     남지 않고 **다음 판단을 바꾼다**
 */
export const MINE = {
  /** 맨몸 — 아무 무기도 노획도 없을 때 */
  base: 3.0,
  /** 들고 있는 무기 하나당 (`combat-table.js WEAPONS` 의 key) */
  byWeapon: { laser: 1.5, ir: 3.0, arh: 5.0 },
  /** 선체 100 이면 이만큼 (선체가 반이면 절반) */
  perHull: 6.0,
  /**
   * ══ ★★★ v110 — **노획 개수는 죽었다** ══════════════════════════════
   *
   *  여기 `loot: { weapon: 0.9, armor: 0.7 }` 과 `lootPow: 0.62` 가 있었다.
   *  v107 이 전투력을 **부위 장착**(`parts-table.js partsMight`)으로
   *  갈아엎으면서 (사장님 「가」) 이 항은 안 쓰이게 됐는데, **떨어지는 것은
   *  그대로 뒀다** — 회차마다 「노획 무기 108 · 장갑판 288」이 아무 데도
   *  안 붙는 칸으로 들어가고 있었다.
   *
   *  ★★ 그래서 **식과 물건을 같이 걷어냈다.** 식만 지우면 물건이 남아
   *    「주웠는데 안 오르네」가 되고, 물건만 지우면 식이 남아 다음 사람이
   *    그 식을 보고 물건을 다시 만든다
   */
  /**
   * ★ 천장. 없으면 2시간 뒤에 모든 적이 「우세」로 나오고, 그 순간
   *   「피한다」가 게임에서 사라진다. 제일 센 적(요격기 떼 18.7)의
   *   **1.8배**에 맞춰 끝까지 「호각」이 하나는 남게 한다
   */
  cap: 34.0,
};

/**
 * ★ 내 전투력의 **바탕**만 — 무기 목록 · 선체(0~1).
 *
 *   ★★ v110 부터 **여기서 노획을 안 센다.** 진짜 내 전투력은
 *     `parts-table.js partsMight(fit)` 이고, 게임은 `main.js myPower()`
 *     한 곳에서만 그것을 부른다. 이 함수는 「아무것도 안 달았을 때
 *     얼마인가」를 견주는 바닥으로 남는다 — 재는 곳을 둘로 만들지 않으려고
 *     **노획 인자를 지웠다**
 */
export function myMight({ weapons = [], hull = 1 } = {}) {
  let m = MINE.base;
  for (const w of weapons) m += MINE.byWeapon[w] ?? 0;
  m += MINE.perHull * Math.max(0, Math.min(1, hull));
  return +Math.min(MINE.cap, m).toFixed(1);
}

/**
 * ★★★ **견줌** — 이 한 줄이 사람이 읽는 전부다.
 *
 *   비(比)로 가른다. 차(差)로 가르면 초반의 3 차이와 후반의 3 차이가
 *   같은 말이 되는데, 초반엔 그게 목숨이고 후반엔 아무것도 아니다.
 *
 *   ★ 낱말이 **넉 자 안**이다. 조종 중에 곁눈으로 읽는 것이라
 *     길면 안 읽고 색만 본다
 */
export const ODDS = [
  { min: 1.60, key: 'easy', word: '우세', tone: 'good', what: '부순다 — 재료가 나온다' },
  { min: 1.05, key: 'even', word: '호각', tone: 'warn', what: '붙어 볼 만하다. 선체를 보고 정한다' },
  { min: 0.70, key: 'hard', word: '열세', tone: 'bad', what: '이겨도 성한 데가 없다 — 지나칠 자리다' },
  { min: 0.00, key: 'flee', word: '절망', tone: 'bad', what: '**피한다.** 아크를 채우고 빠진다' },
];

export function oddsOf(mine, theirs) {
  const r = (mine || 0) / Math.max(0.1, theirs || 0);
  return ODDS.find((o) => r >= o.min) ?? ODDS[ODDS.length - 1];
}
