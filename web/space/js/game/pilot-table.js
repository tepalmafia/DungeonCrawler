/**
 * 이 검사가 지금 접혀 있나 — 접혔으면 **까닭**을 준다 (아니면 null).
 *
 *   ★ `canStand` 하나만 본다. 걷기가 돌아오면 아홉이 **한꺼번에** 깨어난다 —
 *     도구마다 제 조건을 적기 시작하면 그게 안 된다
 */
export function foldedWhy(name) {
  if (PILOT.canStand) return null;
  const row = FOLDED_CHECKS.find(([n]) => n === name);
  return row ? { what: row[1], why: row[2] } : null;
}

