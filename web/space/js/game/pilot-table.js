/** 고칠 것이 있나 */
export const needsFix = (wear = 0, heat = 0, heatMax = 100) =>
  wear > 0.02 || heat > heatMax * 0.55;

/** 사람이 읽는 한 마디 — 계기가 이 한 줄만 쓴다 */
export function fixWord(o = {}) {
  if (o.busy) return `수리 중 ${(o.left ?? 0).toFixed(1)}초`;
  if (o.cool > 0) return `수리 — ${Math.ceil(o.cool)}초 뒤`;
  return `수리 준비 — 부품 ${FIX.parts}`;
}
