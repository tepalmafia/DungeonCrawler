/**
 * ★★ **한 회차 전체**(12구간)의 길이(초).
 *
 *   ★ **v62 에서 기준을 갈았다** (REAL.md §2-D). 예전에는 **구간 하나**를
 *     기준으로 삼아 「제일 느린 구간의 1.25배」를 버티게 잡았고, 그래서
 *     식량이 **13분에 바닥**났다. 밥 먹고 10분 뒤에 손이 떨리는 사람은 없다.
 *
 *   ★★ **그 값이 틀렸던 게 아니라 낡았던 것이다.** 「구간 기준」은
 *     「20분 회차를 반복한다」던 옛 전제에서 나온 것이고, 그 전제는
 *     2026-08-05 에 **「2시간 한 번의 여정」**으로 바뀌었다 (PLAN2H).
 *     `LEG.count` 는 8 → 12 로 같이 옮겼는데 **식량 식은 안 옮겼다** —
 *     그게 이 저장소가 세 번째 겪는 「낡은 전제가 숫자에 남는」 일이다.
 */
const RUN = LEG.seconds * LEG.count;
/** 남겨 둔다 — 「제일 느린 길에서 굶지 않나」를 도구가 아직 이걸로 잰다 */
const SLOWEST_LEG = LEG.seconds / Math.min(...REGIONS.map((r) => r.speed));

