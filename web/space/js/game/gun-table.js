export const GUN = {
  /** 사다리를 오르는 데 (초). 내려오는 것도 같다 */
  climb: 2.2,
  /**
   * 포탑에서 **한 발 쏘는 데** 걸리는 시간 (초).
   * ★ 연사가 아니다. 한 발마다 「쏠까」가 다시 생겨야 선택이 유지된다
   */
  reload: 3.4,
  /** 조준을 얼마나 정확히 해야 맞나 (0~1 · 1 이면 정면) */
  aimNeed: 0.72,

  /**
   * 한 발에 드는 것.
   * ★ **광석이 먼저, 없으면 부품**이다. 광석은 팔아서 식량·부품이 되는
   *   것이라 「쏘면 다음 거점에서 못 산다」가 되고, 부품까지 쓰기 시작하면
   *   「쏘면 다음 고장을 못 고친다」가 된다 — 벌이 두 단계로 깊어진다
   */
  costOre: 6,
  costParts: 1,

  /** 맞으면 추격자가 이만큼 뒤로 (거리 0~100) */
  hitDist: 17,
  /** 빗나가도 **조금은** 벌어진다 — 피하느라 (0 이면 「빗나감」이 그냥 손해다) */
  missDist: 4,

  /**
   * ★ **쏘면 자국이 이만큼 오른다** (열 단위로 환산해서 얹는다).
   *   총구 섬광은 숨을 수 없다 — 이게 「쏘고 도망」을 막는 유일한 자리다
   */
  flashSign: 26,
  /** 그 밝기가 이 초 동안 남는다 */
  flashFor: 22,

  /** 포탑에 있는 동안 열이 초당 이만큼 더 오른다 — 포도 뜨겁다 */
  heatPerShot: 5,

  /**
   * ★ 포탑에 매인 시간이 회차의 이 비율을 넘으면 **장르가 바뀐 것**이다.
   *   `FLYING.md` 가 조종석에 걸어 둔 안전핀과 같은 규약 —
   *   넘으면 정비공이 아니라 포수다. 도구가 이걸 본다
   */
  seatShareMax: 0.12,
};

/** 쏠 수 있나 — 무엇으로 쏘나 */
export function ammoFor(supply) {
  if ((supply?.ore ?? 0) >= GUN.costOre) return 'ore';
  if ((supply?.parts ?? 0) >= GUN.costParts) return 'parts';
  return null;
}

/** 왜 못 쏘나 — **조용히 안 나가면 「고장났다」로 읽힌다** */
export const WHY = {
  ammo: '실을 것이 없습니다 — 광석이나 부품이 있어야 합니다',
  reload: '재는 중입니다',
  aim: '겨눠야 합니다',
  calm: '쏠 상대가 없습니다',
};

export function whyNotFire(s = {}) {
  if (!s.chasing) return 'calm';
  if (!ammoFor(s.supply)) return 'ammo';
  if ((s.cool ?? 0) > 0) return 'reload';
  if ((s.aim ?? 0) < GUN.aimNeed) return 'aim';
  return null;
}
