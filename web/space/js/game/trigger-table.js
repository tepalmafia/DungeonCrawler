/**
 * ★★★ **당겼다. 나가나?** — 문 하나만 돌려준다 (없으면 null).
 *
 * @param s.dead    배가 멈췄나
 * @param s.paused  창이 열렸거나 멈췄나
 * @param s.seat    조종석에 앉아 있나
 * @param s.why     `whyNotFire`·가림이 준 열쇠 (없으면 null)
 */
export function triggerWhy(s = {}) {
  if (s.dead) return 'dead';
  if (s.paused) return 'paused';
  if (!s.seat) return 'seat';
  return s.why ?? null;
}

