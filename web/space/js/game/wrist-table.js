// ══════════════════════════════════════════════════════════════════════════
//  손목 장치 — **「지금 뭘 해야 하나」와 「내가 뭘 고쳤나」.**
//
//  ★ 왜 필요했나 (2026-08-04 · 사장님)
//    「아직까지 뭘 해야할지 모르겠는데? 그리고 매번 조종석에 가서 확인을
//     하는 게 아니라 손목시계나 기타 장비로 내가 수리한 것을 알 수 있도록
//     해야지」
//
//    맞는 말이고, 원인이 분명하다: **가르침은 일곱 개로 끝난다.**
//    첫 회차가 튜토리얼이라 일곱을 다 떼면 그 뒤로 **아무도 뭘 하라고
//    안 한다.** 그리고 고친 기록은 정비실 진단대에만 있어서, 고치고 돌아서면
//    내가 뭘 했는지 알 길이 없었다.
//
//  ★ 그런데 여기가 위험한 자리다 — **다 보여주면 게임이 죽는다**
//    이 게임의 중심은 「동시에 두 곳에 못 있는다」이다 (GAP.md §3-C).
//    조종석은 거리·자국, 관측실은 항로·압박, 정비실은 계통 마모.
//    손목에 그걸 다 넣으면 **방 일곱을 도는 이유가 통째로 사라지고**
//    조종석 화면 다섯·해도대·진단대가 전부 장식이 된다.
//
//    그래서 선을 긋는다:
//
//      · **한 일(과거)** — 손목에 넣는다. 기억을 돕는 것이지 판단 재료가
//        아니다. 보여줘도 아무 값이 안 샌다
//      · **할 일(지금)** — 손목에 넣는다. 「뭘 해야 할지 모르겠다」는
//        신비가 아니라 **고장 난 게임**이다 (TUTORIAL.md §1-1 과 같은 선)
//      · **배의 상태(거리·자국·열 수치·항로·계통 마모)** — **안 넣는다.**
//        그건 방이 갖는다. 그게 이 게임이다
//
//  ★ 할 일도 **어디인지는 안 말한다**
//    「덜그럭거리는 것이 있습니다」까지다. 어느 방인지는 여전히 귀가 찾는다
//    (PLAN §3-1). 손목은 **「할 일이 있다」를 알려주는 것**이지
//    「어디로 가라」가 아니다.
//
//  ★ three.js 를 안 쓴다 — tools/space-wrist.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════
import { CHASE, SIGN } from './chase-table.js';

/**
 * 추격 중에 **지는 열** — 이 위로 오르면 붙는 속도가 벌어지는 속도를 이긴다.
 *
 * ★ 32 라고 손으로 적지 않는다. `chase-table.js` 의 숫자에서 **풀어 낸다** —
 *   저쪽을 만질 때마다 여기가 어긋나면 손목이 거짓말을 하게 되고,
 *   한 번 거짓말한 계기는 그 뒤로 안 믿는다 (TUTORIAL.md 머리말과 같은 선).
 *
 *   추진+냉각(센서는 전력이 둘뿐이라 자동으로 꺼진다)일 때
 *     벌어짐 = CHASE.thrustGain
 *     붙음   = CHASE.trackBase + (SIGN.base + 열·perHeat + thrust + cool)·trackPerSign
 *   둘이 같아지는 열을 푼다. (구역 배수 trackMult 는 1 로 본다 —
 *   성운이면 더 여유롭고 행성 곁이면 더 빡빡하다)
 */
export const CHASE_HOT = Math.round(
  ((CHASE.thrustGain - CHASE.trackBase) / CHASE.trackPerSign
    - (SIGN.base + SIGN.thrust + SIGN.cool)) / SIGN.perHeat,
);

