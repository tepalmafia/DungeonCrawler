// ══════════════════════════════════════════════════════════════════════════
//  손목 장치 — **「지금 뭘 해야 하나」와 「내가 뭘 고쳤나」.**
//
//  ★ 왜 필요했나 (2026-08-04 · 사장님)
//    「아직까지 뭘 해야할지 모르겠는데? 그리고 매번 조종석에 가서 확인을
//     하는 게 아니라 손목시계나 기타 장비로 내가 수리한 것을 알 수 있도록
//     해야지」
//
//    맞는 말이고, 원인이 분명하다: **가르침은 일곱 개로 끝난다.**
//    첫 회차가 튜토리얼이라 일곱을 다 떼면 그 뒤로 **아무도 뭘 하라고
//    안 한다.** 그리고 고친 기록은 정비실 진단대에만 있어서, 고치고 돌아서면
//    내가 뭘 했는지 알 길이 없었다.
//
//  ★ 그런데 여기가 위험한 자리다 — **다 보여주면 게임이 죽는다**
//    이 게임의 중심은 「동시에 두 곳에 못 있는다」이다 (GAP.md §3-C).
//    조종석은 거리·자국, 관측실은 항로·압박, 정비실은 계통 마모.
//    손목에 그걸 다 넣으면 **방 일곱을 도는 이유가 통째로 사라지고**
//    조종석 화면 다섯·해도대·진단대가 전부 장식이 된다.
//
//    그래서 선을 긋는다:
//
//      · **한 일(과거)** — 손목에 넣는다. 기억을 돕는 것이지 판단 재료가
//        아니다. 보여줘도 아무 값이 안 샌다
//      · **할 일(지금)** — 손목에 넣는다. 「뭘 해야 할지 모르겠다」는
//        신비가 아니라 **고장 난 게임**이다 (TUTORIAL.md §1-1 과 같은 선)
//      · **배의 상태(거리·자국·열 수치·항로·계통 마모)** — **안 넣는다.**
//        그건 방이 갖는다. 그게 이 게임이다
//
//  ★ 할 일도 **어디인지는 안 말한다**
//    「덜그럭거리는 것이 있습니다」까지다. 어느 방인지는 여전히 귀가 찾는다
//    (PLAN §3-1). 손목은 **「할 일이 있다」를 알려주는 것**이지
//    「어디로 가라」가 아니다.
//
//  ★ three.js 를 안 쓴다 — tools/space-wrist.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const WRIST = {
  /** 고친 기록을 몇 개까지 들고 있나 — 화면에 들어가는 만큼 */
  logMax: 6,
  /** 화면에 한 번에 보이는 줄 수 */
  logShow: 4,
  /** 들어 올리는 데 걸리는 시간(초) */
  raise: 0.22,
  /** 한 줄이 이보다 길면 손목 화면에 안 들어간다 */
  maxLen: 22,
};

/**
 * 지금 할 일 — **위에서부터 처음 맞는 것 하나만** 보여준다.
 *
 * ★ 여러 개를 한꺼번에 보여주지 않는다. 목록이 뜨면 그건 할 일 관리가 되고,
 *   이 게임은 손으로 하나씩 하는 게임이다 (가르침이 한 번에 하나인 것과 같다).
 *
 * ★ 순서가 곧 **급한 순서**다. 위에 있을수록 안 하면 판이 망가진다.
 *   `where` 는 **안 적는다** — 「어디인지는 안 말한다」 (PLAN §3-1)
 */
export const JOBS = [
  {
    key: 'jam', urgent: true,
    when: (s) => s.doorJammed,
    say: '문이 안 열립니다',
  },
  {
    key: 'chase', urgent: true,
    when: (s) => s.chasing,
    say: '쫓기는 중입니다',
  },
  {
    key: 'hot', urgent: true,
    // 열이 경고선을 넘었다 — 밸브를 열든 회로를 옮기든 해야 한다
    when: (s) => s.heatHigh,
    say: '열이 높습니다',
  },
  {
    key: 'hazard', urgent: true,
    when: (s) => s.hazardSoon,
    say: '전방에 잔해 — 조종석으로',
  },
  {
    key: 'fault',
    when: (s) => s.faultsOpen > 0,
    // ★ **어디인지 안 말한다.** 몇 개인지까지가 손목이 아는 전부다
    say: (s) => (s.faultsOpen > 1 ? `고장 ${s.faultsOpen}군데` : '고장 한 군데'),
  },
  {
    key: 'hungry',
    when: (s) => s.foodLow,
    say: '식량이 모자랍니다',
  },
  {
    key: 'route',
    when: (s) => s.atPort,
    say: '항로를 고릅니다',
  },
  {
    key: 'thrust',
    when: (s) => !s.thrust,
    say: '추진이 꺼져 있습니다',
  },
  {
    // 아무 일도 없을 때. **「할 일 없음」이 아니라 「지금은 벌 시간」**이라고
    // 말한다 — 이 게임에서 평온은 다음 추격의 준비 시간이다 (PLAN §3)
    key: 'calm',
    when: () => true,
    say: (s) => (s.ore > 0 ? '광석을 싣고 갑니다' : '지금은 조용합니다'),
  },
];

/** 그 상태에서 지금 할 일 하나 */
export function jobFor(s) {
  const j = JOBS.find((x) => x.when(s)) ?? JOBS[JOBS.length - 1];
  return { key: j.key, text: typeof j.say === 'function' ? j.say(s) : j.say, urgent: !!j.urgent };
}
