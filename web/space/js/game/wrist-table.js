/**
 * **지금 손이 하고 있는 일**을 홀로그램이 보여주나 — 그리고 무엇까지.
 *
 * ★ 왜 생겼나 (2026-08-04 · 사장님)
 *   「여기서 열을 내리는게 맞아? 안내창에 진행 상황도 표시해줘.
 *    그래프로 열이 떨어지는지」
 *
 *   기관실 밸브를 잡고 돌리는 화면에서 하신 말씀이다. **밸브가 맞다.**
 *   그런데 게임이 그걸 확인해 주지 않았다 — 열 계기는 조종석에 있으니
 *   돌리는 동안에는 **먹고 있는지 알 수가 없다.** 조용한 손잡이(윈치·접수구)와
 *   같은 병이고, 이건 더 나쁘다: 손잡이는 안 먹으면 아무 일도 안 나는데
 *   밸브는 **먹는데도 안 먹는 것처럼 보인다.**
 *
 * ★ 그런데 이건 「배의 상태를 손목에 안 넣는다」(머리말)와 부딪힌다
 *   부딪히지 않게 선을 다시 긋는다:
 *
 *     · **판단 재료** — 「지금 열이 몇인가, 그래서 어느 항로로 갈까」
 *       → 여전히 **방이 갖는다.** 걸어가서 봐야 한다
 *     · **내 손의 되먹임** — 「내가 지금 돌리는 이것이 먹고 있나」
 *       → 홀로그램이 갖는다. 이건 배의 상태가 아니라 **내 동작의 결과**다
 *
 *   가르는 규칙은 하나다: **잡고 있는 동안에만 뜬다.** 놓으면 사라진다.
 *   그래서 아무 데서나 열을 볼 수 없고, 「동시에 두 곳에 못 있는다」가 산다 —
 *   열 그래프를 보려면 **밸브를 잡고 있어야** 하고, 밸브를 잡고 있으면
 *   조종석에 없다.
 *
 * @param aim  지금 조준선이 잡은 것 (`valve` · `panel:workshop` · `cool` …)
 * @param hold 잡고 있나
 */
export function actShows(aim, hold) {
  if (!hold || !aim) return null;
  const head = String(aim).split(':')[0];
  return {
    /** 진행 막대 — 「얼마나 됐나」. 잡는 것은 전부 시간이 든다 */
    bar: true,
    /**
     * 열 그래프 — **열을 만지는 손잡이일 때만.**
     * 윈치를 잡고 열 그래프가 뜨면 그건 그냥 계기판이 하나 더 생긴 것이다
     */
    heat: HEAT_GRIPS.has(head),
  };
}

/** 열을 만지는 손잡이 — 밸브(냉각수)와 차단기 셋(냉각 회로·추진이 열을 낸다) */
export const HEAT_GRIPS = new Set(['valve', 'thrust', 'cool', 'sensor']);

/** 그 상태에서 지금 할 일 하나 */
export function jobFor(s) {
  const j = JOBS.find((x) => x.when(s)) ?? JOBS[JOBS.length - 1];
  return { key: j.key, text: typeof j.say === 'function' ? j.say(s) : j.say, urgent: !!j.urgent };
}
