/** 그 상태에서 지금 할 일 하나 */
export function jobFor(s) {
  const j = JOBS.find((x) => x.when(s)) ?? JOBS[JOBS.length - 1];
  return { key: j.key, text: typeof j.say === 'function' ? j.say(s) : j.say, urgent: !!j.urgent };
}
