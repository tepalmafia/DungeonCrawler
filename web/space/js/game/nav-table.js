/**
 * ★★★ **길이 어디 있나** — 표적과 **같은 자**로 준다 (`az · el · dist`).
 *
 *   ★ 방향은 **항로점 그대로**다 (`az`). 여기서 딴 방향을 만들면 「마름모는
 *     저기인데 길은 이리로」가 되고, 그게 이 저장소가 네 판을 태운 병이다.
 *   ★★ 그래서 이 함수가 하는 일은 **거리를 나누고 아래로 내리는 것뿐**이다.
 *
 * @param to    `nav.to` (없으면 빈 배열)
 * @param phase 흐른 거리 (m) — 배가 나아간 만큼. 물결이 이만큼 흐른다
 * @param off   기수가 항로점에서 벗어난 각 (도) — 진하기에만 쓴다
 * @returns 가까운 것부터 늘어선 마디들. 그리는 쪽은 이 점들을 이어 띠로 만든다
 */
export function roadOf(to, phase = 0, off = 0) {
  if (!to) return [];
  const dim = navState(off) === 'off' ? ROAD.offDim : 1;
  const ratio = ROAD.far / ROAD.near;
  const out = [];
  for (let i = 0; i <= ROAD.seg; i++) {
    const k = i / ROAD.seg;                 // 0 가까움 ~ 1 멂
    // ★ 로그로 나눈다 — 화면에서 마디 사이가 고르게 보이는 나눔이다
    const d = ROAD.near * (ratio ** k);
    // ★★ **아래로 내린 만큼 고도가 준다.** 거리로 나누므로 멀수록 0 에 붙는다
    const el = to.el - (Math.atan(ROAD.drop / d) * 180) / Math.PI;
    // ★ 물결 — 나아가면 흘러 보인다. 도형을 더하지 않고 흐름만 얻는다
    // ★ 각폭은 못박되 먼 쪽만 조금 좁힌다 — 고르면 깊이가 안 읽힌다
    const degWide = ROAD.wide * (1 + (ROAD.farNarrow - 1) * k);
    const wave = 1 - ROAD.flowDepth * 0.5
      * (1 - Math.cos((2 * Math.PI * (d - phase)) / ROAD.flowLen));
    out.push({
      i,
      az: to.az,
      el: +el.toFixed(4),
      dist: +d.toFixed(2),
      /**
       * ★★ **세상 굵기 (m)** — 각을 못박고 거리로 낸다. 그래야 화면에서
       *   굵기가 고르다 (「고깔이 아니라 줄」)
       */
      width: +(2 * d * Math.tan((degWide * Math.PI) / 360)).toFixed(3),
      /** 이 마디의 각폭 (도) — 검사가 여기서 「고른가」를 잰다 */
      deg: +degWide.toFixed(3),
      /** 축에서 몇 도 아래인가 — 「복판을 비웠나」를 검사가 여기서 본다 */
      below: +(((Math.atan(ROAD.drop / d) * 180) / Math.PI)).toFixed(2),
      alpha: +(ROAD.alpha * (1 + (ROAD.fade - 1) * k) * wave * dim).toFixed(4),
      /** 계기가 쓰는 색 갈래 — 항로점과 **같은 말**을 쓴다 */
      state: navState(off),
    });
  }
  return out;
}

/** −180~180 으로 감는다 */
export const wrapDeg = (d) => ((d + 180) % 360 + 360) % 360 - 180;

/**
 * ★★★ **항로가 나아가는 배수** (0~1).
 *
 * @param off   기수가 항로점에서 몇 도 벗어났나
 * @param auto  자동 항법인가 — **자동이면 늘 1**
 */
export function courseMult(off, auto = false) {
  if (auto) return NAV.autoMult;
  const a = Math.abs(off);
  if (a <= NAV.cone) return 1;
  if (a >= NAV.dead) return 0;
  const k = (a - NAV.cone) / (NAV.dead - NAV.cone);
  return 1 + (NAV.minMult - 1) * k;
}

