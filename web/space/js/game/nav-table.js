//  「계기에는 저기, 창밖에는 여기」가 또 난다 (v91~v98 이 그 병이었다).
//
//  ══ ★★ 그런데 **장르를 안 바꾼다** ═══════════════════════════════════
//
//  「향해야 나아간다」를 그냥 켜면 이 게임이 망가진다: 이 사람은
//  **정비공**이라 회차의 대부분을 조종석 **밖**에서 보낸다
//  (`space-fly.js` 가 「조종석에 매인 시간 15% 이하」를 지킨다).
//  좌석을 비우는 순간 항로가 멎으면 그건 다른 게임이다.
//
//  ★★★ 그래서 **자동 항법이 이미 있는 것을 쓴다** (`helm.auto`):
//
//      자동이면  — 배가 스스로 항로점을 향한다. **지금과 똑같다**
//      수동이면  — **사람이 향해야 나아간다.** 여기가 새로 생기는 것
//
//  즉 이건 자동에서 무언가를 빼앗는 것이 아니라 **수동에 길을 놓는 것**이다.
//  사장님 문장 그대로 「그래야 **수동으로도** 이동할 수 있게」.
//
//  ★ three.js 를 안 쓴다 — `tools/space-nav.js` 가 읽는다.
// ══════════════════════════════════════════════════════════════════════════

