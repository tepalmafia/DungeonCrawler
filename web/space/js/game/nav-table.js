// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **항법 — 갈 곳이 화면에 있다** (v104). 숫자만. 규칙은 `nav.js`.
//
//  ★ 사장님 (2026-08-11)
//    「**항로, 미션을 선택하면 네비게이션이 나오도록 해줘.
//      그래야 수동으로도 이동할 수 있게.**」
//
//  ══ 재 보니 **항로에 방향이 아예 없었다** ═════════════════════════════
//
//  갈래(`route-table.js forkOf`)가 들고 있는 것은 이것뿐이다:
//
//      key · name · what · **seconds** · pressRate · trackMult · signMult
//
//  **어디로 가는지가 없다.** 「간다」가 곧 `rt.t += dt` 였고, 추진을 켜면
//  시계가 돌고 끄면 느려질 뿐이었다. 즉 항로는 **시계**였지 길이 아니었다.
//  기수를 어느 쪽으로 돌려도 구간은 똑같이 흘렀다 — 그래서 사장님이
//  「수동으로도 이동할 수 있게」라고 하셨다. **수동에는 갈 곳이 없었다.**
//
//  ══ ★★★ 그래서 갈래·미션에 **항로점**을 준다 ═════════════════════════
//
//  고르는 순간 하늘의 한 자리(방위·고도)가 정해지고, 조준경이 그것을
//  마름모로 그린다. 화면 밖이면 가장자리가 어느 쪽인지 가리킨다.
//  **표적을 그리는 것과 같은 자(`frame.js`)를 쓴다** — 두 벌로 만들면
//  「계기에는 저기, 창밖에는 여기」가 또 난다 (v91~v98 이 그 병이었다).
//
//  ══ ★★ 그런데 **장르를 안 바꾼다** ═══════════════════════════════════
//
//  「향해야 나아간다」를 그냥 켜면 이 게임이 망가진다: 이 사람은
//  **정비공**이라 회차의 대부분을 조종석 **밖**에서 보낸다
//  (`space-fly.js` 가 「조종석에 매인 시간 15% 이하」를 지킨다).
//  좌석을 비우는 순간 항로가 멎으면 그건 다른 게임이다.
//
//  ★★★ 그래서 **자동 항법이 이미 있는 것을 쓴다** (`helm.auto`):
//
//      자동이면  — 배가 스스로 항로점을 향한다. **지금과 똑같다**
//      수동이면  — **사람이 향해야 나아간다.** 여기가 새로 생기는 것
//
//  즉 이건 자동에서 무언가를 빼앗는 것이 아니라 **수동에 길을 놓는 것**이다.
//  사장님 문장 그대로 「그래야 **수동으로도** 이동할 수 있게」.
//
//  ★ three.js 를 안 쓴다 — `tools/space-nav.js` 가 읽는다.
// ══════════════════════════════════════════════════════════════════════════

export const NAV = {
  /**
   * ★★ **딱 맞춰야 하는 각** (도). 이 안이면 온전히 나아간다.
   *
   *   14 · 락온 유지각(`RADAR.holdCone` 32)보다 좁고 레이저 허용각
   *   (4.2)보다는 훨씬 넓다. 「겨누는 것」보다는 쉽고 「대충 그쪽」보다는
   *   어려운 자리다 — 항로는 조준이 아니라 **방향**이므로
   */
  cone: 14,
  /**
   * ★★★ **이 각을 넘으면 아예 안 나아간다** (도).
   *
   *   ★ 78 로 잡았다. 90(옆) 보다 좁다 — 옆으로 완전히 돌아섰는데
   *     조금이라도 나아가면 그건 「향한다」가 아니다.
   *   ★★ 반대로 이보다 좁게 잡으면(예: 40) **잠깐 적을 쫓는 것**만으로
   *     항로가 멎는다. 전투는 회차의 일부이고, 싸우는 동안 항로가 통째로
   *     서면 「싸우면 손해」가 되어 v70 이 만든 것이 무너진다
   */
  dead: 78,
  /**
   * ★ `cone` 과 `dead` 사이에서 **얼마까지 떨어지나** (0~1).
   *   0.25 — 딴 데를 보고 있어도 관성으로 조금은 간다. 0 으로 두면
   *   갈래를 고른 뒤 한 번도 못 돌아보게 되고, 그러면 정비를 못 한다
   */
  minMult: 0.25,
  /**
   * ★★ **자동 항법이면 늘 1 이다.** 배가 스스로 향하므로.
   *   이 값이 이 계통이 장르를 안 바꾸는 이유 전부다
   */
  autoMult: 1,

  // ── 항로점을 어디에 놓나 ────────────────────────────────
  /**
   * ★ 좌우로 이 범위 안에 놓는다 (도). 뒤에 놓지 않는다 —
   *   갈래를 고른 순간 배는 이미 그쪽으로 가고 있는 중이다
   */
  azSpread: 52,
  /** 위아래로 이 범위 (도). 좌우보다 좁다 — 마우스 세로 폭이 짧다 */
  elSpread: 17,
  /**
   * ★★ 미션(마주치는 것)은 **더 옆에** 놓는다 (도). 항로에서 벗어나야
   *   닿는 것이라 그렇고, 그래야 「들를까 말까」가 진짜 갈림이 된다 —
   *   벗어난 동안은 위 `minMult` 로 느려지므로 **값이 붙는다**
   */
  missionAz: 96,
  /** 미션까지의 거리 (m) — 레이더가 보는 끝자락 */
  missionDist: 240,
};

/** −180~180 으로 감는다 */
export const wrapDeg = (d) => ((d + 180) % 360 + 360) % 360 - 180;

/**
 * ★★★ **항로가 나아가는 배수** (0~1).
 *
 * @param off   기수가 항로점에서 몇 도 벗어났나
 * @param auto  자동 항법인가 — **자동이면 늘 1**
 */
export function courseMult(off, auto = false) {
  if (auto) return NAV.autoMult;
  const a = Math.abs(off);
  if (a <= NAV.cone) return 1;
  if (a >= NAV.dead) return 0;
  const k = (a - NAV.cone) / (NAV.dead - NAV.cone);
  return 1 + (NAV.minMult - 1) * k;
}

/** 사람이 읽는 한 마디 — 계기가 이 한 줄만 쓴다 */
export function navWord(n, off = null) {
  if (!n) return '';
  if (off === null) return `목적지 ${n.name}`;
  const a = Math.abs(off);
  if (a <= NAV.cone) return `${n.name} — 항로 위`;
  if (a >= NAV.dead) return `★ ${n.name} — 항로를 벗어났습니다`;
  return `${n.name} — ${Math.round(a)}° 틀어졌습니다`;
}

/** 계기가 쓰는 색 갈래 — 셋뿐이다 (좋다 · 벗어난다 · 벗어났다) */
export const navState = (off) => {
  const a = Math.abs(off ?? 0);
  return a <= NAV.cone ? 'on' : (a >= NAV.dead ? 'off' : 'drift');
};
