/**
 * ★★★ **어느 쪽으로 · 얼마나** — 레이더와 **같은 말**을 쓴다.
 *
 *   ★ 같은 말을 써야 「레이더의 저것」과 「항로의 저것」이 한 머리에 들어온다.
 *     여기서 새 말투를 만들면 배 안에 방향 부르는 법이 둘이 된다
 *
 * @param azOff 항로점이 기수에서 좌우로 몇 도 (오른쪽이 +)
 * @param elOff 위아래로 몇 도 (위가 +)
 */
/**
 * ★★★ **화면 크기의 항로 지시자** — 조준경 밖에 따로 선다 (v126).
 *
 *   ★ 조준경에도 「가장자리 세모」가 있다 (v104). 그런데 그 판은 화면
 *     복판 **40도**짜리라, 세모가 서는 곳은 **화면 가장자리가 아니라
 *     작은 판의 가장자리**다 — 우주에서 방향을 잃은 사람 눈에는 안 든다.
 *   ★★ 그래서 **카메라에 붙인 판**에 화면 가장자리로 그린다
 *     (`world/navhud.js` · 회수 카드와 같은 규약).
 *
 *   @property showFrom 이 각을 넘게 벗어나면 나온다 (도) — 항로 위일 때는
 *     문(HITS)이 이미 말하므로 조용히 있는다
 *   @property rx,ry    화면 가장자리 타원 (정규 좌표 0~1)
 */
export const NAVHUD = {
  showFrom: 10,
  rx: 0.82, ry: 0.74,
  /** 화살표 크기 (화면 세로 대비) */
  size: 0.075,
  what: '항로 화살표 — 목적지가 화면 밖이면 가장자리에서 그쪽을 가리킨다',
};

/**
 * ★★★ **화살표를 화면 어디에 놓나** (정규 좌표 −1~1).
 *
 *   ★ 각을 여기서 다시 재지 않는다 — `frame.js relOf` 가 준 것을 **방향으로만**
 *     쓴다. 거리는 화면 가장자리로 밀므로 안 쓴다
 */
export function navArrow(azOff, elOff) {
  const a = Math.atan2(elOff, azOff);
  return {
    nx: Math.cos(a) * NAVHUD.rx,
    ny: Math.sin(a) * NAVHUD.ry,
    /** 화살표가 도는 각 (라디안 · 캔버스 기준 y 가 아래) */
    rot: Math.atan2(-elOff, azOff),
  };
}

export const steerWord = (name, azOff, elOff) => callOut(name ?? '목적지', azOff, elOff);

/**
 * 사람이 읽는 한 마디 — 계기가 이 한 줄만 쓴다.
 *
 * ★★ v126 — **어느 쪽인지를 같이 준다.** `off` 만 받던 것을 `rel` 도
 *   받게 했다. 옛 자리(각 하나만 넘기는 곳)도 그대로 돌게 남긴다 —
 *   부르는 곳이 여럿이라 한꺼번에 못 고친다
 */
export function navWord(n, off = null, rel = null) {
  if (!n) return '';
  if (off === null) return `목적지 ${n.name}`;
  const a = Math.abs(off);
  // ★★★ v128 — **아직 안 고른 갈래는 다르게 말한다** (사장님 「왜 항로
  //   네비게이션이 안 나와?」). 거점에 서 있는 동안은 목적지가 아니라
  //   **후보**라, 「항로 위」라고 하면 거짓말이 된다 — 아직 아무 데도 안 간다
  if (n.kind === 'port') {
    const w = rel ? ` — ${steerWord('', rel.az, rel.el).replace(/^\s*—\s*/, '')}` : '';
    return a <= NAV.cone ? `${n.name} — 이쪽입니다 · 고르면 갑니다` : `${n.name} — 고르면 갑니다${w}`;
  }
  if (a <= NAV.cone) return `${n.name} — 항로 위`;
  // ★★★ **벗어날수록 말이 늘어야 한다.** v125 까지는 반대였다 —
  //   78도를 넘으면 각도마저 사라져 「벗어났습니다」만 남았고,
  //   정작 그때가 제일 헤매는 때다
  const where = rel ? ` — ${steerWord('', rel.az, rel.el).replace(/^\s*—\s*/, '')}` : '';
  if (a >= NAV.dead) return `★ ${n.name} — 항로를 벗어났습니다${where}`;
  return `${n.name} — ${Math.round(a)}° 틀어졌습니다${where}`;
}

/** 계기가 쓰는 색 갈래 — 셋뿐이다 (좋다 · 벗어난다 · 벗어났다) */
export const navState = (off) => {
  const a = Math.abs(off ?? 0);
  return a <= NAV.cone ? 'on' : (a >= NAV.dead ? 'off' : 'drift');
};
