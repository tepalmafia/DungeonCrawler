// ══════════════════════════════════════════════════════════════════════════
//  ★★★ **항로 문 — 목적지까지 길이 보인다** (v121)
//
//  ★ 사장님 (2026-08-12) 「**네비게이션을 만들고 항로가 목적지까지 희미하게
//    표시 되도록 해서 내가 목적지로 향하고 있다는 것을 시각적으로 표시**」
//
//  ══ v104 가 만든 것은 **점 하나**였다 ═════════════════════════════════
//
//  항로점(마름모)이 하늘 한 자리에 뜬다. 그것으로 **어디인지**는 알지만
//  **가고 있는지**는 모른다 — 점은 방향만 말하고 길은 안 말한다.
//  사장님 문장의 알맹이가 뒤쪽이다: 「**향하고 있다는 것을** 시각적으로」.
//
//  ══ ★★★ 왜 「선」이 아니라 「문」인가 ═════════════════════════════════
//
//  ★ **곧은 선은 화면에서 점이 된다.** 배에서 목적지로 잇는 선은 눈과
//    한 줄로 서 있으므로, 그 위의 모든 자리가 **같은 화면 좌표**에 찍힌다.
//    「목적지까지 선을 긋는다」를 곧이곧대로 하면 아무것도 안 보인다 —
//    이건 그려 보기 전에 계산으로 알 수 있는 것이라 여기 적어 둔다.
//
//  ★★ 그래서 **굵기를 가진 것**을 늘어놓는다. 세상 크기가 같은 고리를
//    거리마다 놓으면 **가까운 것은 크고 먼 것은 작다** — 겹쳐 보이는
//    동심원이 곧 「길」이고, 그 길 안으로 들어가면 항로 위다.
//    ★ 실기의 **HITS**(Highway In The Sky · 합성시계 표시)가 정확히
//      이것이고, 이유도 같다: 점으로는 「향하고 있나」를 못 말한다.
//
//  ★★★ 그리고 **흐른다.** 문이 다가와 지나가면 「나아가고 있다」가
//    눈으로 보인다 — 멎으면 멎은 것이 보인다. 항로가 시계였던 v103 까지의
//    문제(「기수를 어디로 돌려도 똑같이 흘렀다」)를 **화면에서** 갚는 자리다.
// ══════════════════════════════════════════════════════════════════════════
export const HITS = {
  /** 한 번에 몇 개나 떠 있나 — 늘리면 길이 아니라 벽이 된다 */
  gates: 5,
  /**
   * 제일 가까운 문까지 (m).
   * ★★ v121 — 45 → 35. 문 하나는 **지나가자마자 저 뒤로 감기므로**,
   *   실제로 제일 가까운 문은 늘 `near ~ near+step` 사이를 오간다.
   *   화면으로 재 보니 그래서 제일 큰 문이 화면 반쪽의 0.13 밖에 안 됐다
   *   (표는 0.248 이라고 말하고 있었다) — **표만 읽으면 안 잡히는 것**이다
   */
  near: 35,
  /** 문 사이 (m) */
  step: 50,
  /**
   * ★★ 문 반지름 (m) — **세상 크기다.** 화면 크기로 두면 멀어도 안 줄어들어
   *   원근이 사라지고, 그러면 「길」이 아니라 「겹친 원 다섯」이 된다.
   *   ★ 16m 는 35m 앞에서 약 49도, 235m 앞에서 약 8도다 — 그 벌어짐이 곧 길이다
   *   ★★ v121 — 12 → 16. 화면으로 재고 올렸다 (위 `near` 참고).
   *     배가 지나다닐 문이므로 이보다 좁으면 「길」이 아니라 「과녁」이 된다
   */
  r: 16,
  /**
   * ★★★ **희미하다** (0~1). 사장님 말씀 그대로 「희미하게」 —
   *   길은 **보는 것이 아니라 곁눈에 있는 것**이다. 진하게 그리면
   *   전투 원뿔을 먹고, 그건 이 게임에서 제일 비싼 자리다
   */
  alpha: 0.30,
  /** 제일 먼 문의 진하기 (제일 가까운 것이 1) — 멀수록 삭는다 */
  far: 0.35,
  /** 항로를 벗어나면 이만큼 곱한다 — 벗어나도 **안 없앤다** (돌아갈 길이다) */
  offDim: 0.75,
  what: '항로 문 — 목적지 쪽으로 늘어선 고리. 안으로 들어가면 항로 위다',
};

/**
 * ★★★ **문들이 어디 있나** — 표적과 **같은 자**로 준다 (`az · el · dist`).
 *
 *   ★ 방향은 **항로점 그대로**다. 여기서 딴 방향을 만들면 「마름모는
 *     저기인데 길은 이리로」가 되고, 그게 이 저장소가 네 판을 태운 병이다.
 *   ★★ 그래서 이 함수가 하는 일은 **거리를 나누는 것뿐**이다.
 *
 * @param to    `nav.to` (없으면 빈 배열)
 * @param phase 흐른 거리 (m) — 배가 나아간 만큼 넣는다. 문이 다가와 지나간다
 * @param off   기수가 항로점에서 벗어난 각 (도) — 진하기에만 쓴다
 */
export function gatesOf(to, phase = 0, off = 0) {
  if (!to) return [];
  const span = HITS.gates * HITS.step;
  // ★ 벗어난 만큼 흐려지되 **0 이 되지는 않는다** — 길이 없어지면
  //   벗어났을 때 돌아갈 곳을 잃는다. 벗어났을 때야말로 필요한 것이다
  const dim = navState(off) === 'off' ? HITS.offDim : 1;
  const out = [];
  for (let i = 0; i < HITS.gates; i++) {
    // ★★ **감아서 되돌린다.** 그래야 개수가 안 변하고, 개수가 변하면
    //   「길이 짧아졌다」로 읽힌다 — 남은 거리는 구간이 따로 말한다
    const d = HITS.near + (((i * HITS.step - phase) % span) + span) % span;
    const k = (d - HITS.near) / Math.max(1e-6, span);   // 0 가까움 ~ 1 멂
    out.push({
      /**
       * ★★ **문마다 이름표.** 정렬하면 순서가 바뀌므로, 이것이 없으면
       *   그리는 쪽이 매 프레임 새 물체를 만들게 되고(깜빡인다) 검사도
       *   「같은 문이 다가오나」를 물을 수가 없다 — 첫 판에 없어서
       *   검사가 **지나간 문과 새 문을 견주다** 빨개졌다
       */
      i,
      az: to.az, el: to.el, dist: d,
      /** 세상 반지름 (m) — 화면 크기는 거리가 정한다 */
      r: HITS.r,
      /** 이 문의 각지름 (도) — 검사가 원근을 여기서 잰다 */
      deg: +(2 * Math.atan(HITS.r / d) * 180 / Math.PI).toFixed(2),
      alpha: +(HITS.alpha * (1 + (HITS.far - 1) * k) * dim).toFixed(3),
      /** 계기가 쓰는 색 갈래 — 항로점과 **같은 말**을 쓴다 */
      state: navState(off),
    });
  }
  return out.sort((a, b) => a.dist - b.dist);
}

/** −180~180 으로 감는다 */
export const wrapDeg = (d) => ((d + 180) % 360 + 360) % 360 - 180;

/**
 * ★★★ **항로가 나아가는 배수** (0~1).
 *
 * @param off   기수가 항로점에서 몇 도 벗어났나
 * @param auto  자동 항법인가 — **자동이면 늘 1**
 */
export function courseMult(off, auto = false) {
  if (auto) return NAV.autoMult;
  const a = Math.abs(off);
  if (a <= NAV.cone) return 1;
  if (a >= NAV.dead) return 0;
  const k = (a - NAV.cone) / (NAV.dead - NAV.cone);
  return 1 + (NAV.minMult - 1) * k;
}

/** 사람이 읽는 한 마디 — 계기가 이 한 줄만 쓴다 */
export function navWord(n, off = null) {
  if (!n) return '';
  if (off === null) return `목적지 ${n.name}`;
  const a = Math.abs(off);
  if (a <= NAV.cone) return `${n.name} — 항로 위`;
  if (a >= NAV.dead) return `★ ${n.name} — 항로를 벗어났습니다`;
  return `${n.name} — ${Math.round(a)}° 틀어졌습니다`;
}

/** 계기가 쓰는 색 갈래 — 셋뿐이다 (좋다 · 벗어난다 · 벗어났다) */
export const navState = (off) => {
  const a = Math.abs(off ?? 0);
  return a <= NAV.cone ? 'on' : (a >= NAV.dead ? 'off' : 'drift');
};
