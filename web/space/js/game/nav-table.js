//    사장님이 「오른쪽 왼쪽이 아니고 실제 레이더 시스템을 고증해서」라고
//    하셔서 지은 것). **항법만 그걸 안 쓰고 있었다** — 새로 만들 것이
//    아니라 이미 있는 것을 물리는 자리다
