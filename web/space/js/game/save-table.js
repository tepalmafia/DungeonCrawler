//    있다. 통째로 넘기면 조용히 절반만 저장되고, 그건 **불러온 뒤에야
//    드러난다.** 그래서 저장할 칸을 **여기 한 곳에 적어 둔다** —
//    새 칸이 생기면 여기 추가하지 않는 한 안 저장된다는 것이 분명하다.
//
//  ★ **판본이 다르면 버린다**
//    표가 바뀌면 옛 저장은 뜻이 달라진다. 억지로 읽으면 「이상하게
//    망가진 배」로 시작하고, 그건 버그로 신고된다. **깨끗이 버리고
//    새로 시작하는 편이 낫다** — 다만 버렸다고 말해 준다.
//
//  ★ three.js 를 안 쓴다 — tools/space-save.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

