// ══════════════════════════════════════════════════════════════════════════
//  저장 — **2시간짜리에는 협상 불가다** (docs/space/PLAN2H.md §11-1)
//
//  ★ 왜 이게 1판인가
//    지금까지 저장이 **아예 없었다.** 브라우저를 닫으면 사라진다.
//    20분짜리에서는 견딜 만했지만 2시간짜리에서는 다르다 —
//    그리고 더 큰 문제는 이것이다:
//
//      **저장이 없으면 2시간짜리를 한 번도 끝까지 못 해 본 채로 만든다.**
//
//    그건 이 저장소가 겪은 모든 사고의 원형이다 (POSTMORTEM). 만드는
//    사람이 확인 못 하는 것은 반드시 틀린 채로 남는다.
//
//  ★ **통째로 JSON 하지 않는다 — 칸을 적는다**
//    `route` 에는 난수 발생기(클로저)가, 다른 곳에는 three 객체가 들어
//    있다. 통째로 넘기면 조용히 절반만 저장되고, 그건 **불러온 뒤에야
//    드러난다.** 그래서 저장할 칸을 **여기 한 곳에 적어 둔다** —
//    새 칸이 생기면 여기 추가하지 않는 한 안 저장된다는 것이 분명하다.
//
//  ★ **판본이 다르면 버린다**
//    표가 바뀌면 옛 저장은 뜻이 달라진다. 억지로 읽으면 「이상하게
//    망가진 배」로 시작하고, 그건 버그로 신고된다. **깨끗이 버리고
//    새로 시작하는 편이 낫다** — 다만 버렸다고 말해 준다.
//
//  ★ three.js 를 안 쓴다 — tools/space-save.js 가 브라우저 없이 읽는다.
// ══════════════════════════════════════════════════════════════════════════

