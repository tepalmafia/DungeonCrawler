    const h = rows.length, w = rows[0].length;
    const base = document.createElement('canvas');
    base.width = w; base.height = h;
    const bctx = base.getContext('2d');
    for (let y = 0; y < h; y++) {
      for (let x = 0; x < w; x++) {
        const ch = rows[y][x];
        if (ch === '.') continue;
        bctx.fillStyle = pal[ch] || '#e8e0cf';
        bctx.fillRect(x, y, 1, 1);
      }
    }
    // 실루엣 아웃라인 (스프라이트와 동일 룩)
