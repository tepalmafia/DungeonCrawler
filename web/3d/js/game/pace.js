// 전투 템포 — 「한 마리씩 신중하게 끌어와 오래 싸운다」가 성립하려면
// 한 합 한 합이 눈에 읽혀야 한다. 그래서 공격·이동 속도를 일괄로 낮춘다.
//
// 여기 한 곳만 고치면 플레이어·잡몹·보스가 함께 움직인다.
// 개별 수치(BASE_SPEED, ARCHETYPES[].speed, windup/recover)는 「서로의 차이」를,
// 이 상수는 「전체 템포」를 담당한다 — 둘을 섞지 않아야 조정이 쉽다.
//
// 주의: 시간으로 적힌 값(선딜·후딜·쿨다운)은 속도의 역수를 곱해야 한다.
// 속도 0.7배 = 걸리는 시간 1/0.7 ≈ 1.43배. 여기서 헷갈리면 예고 링과 실제
// 타격 시점이 어긋나 「예고 없이 맞는」 최악의 버그가 된다.

/** 이동 속도 배수. 0.7 = 30% 감소 */
export const MOVE_SCALE = 0.7;

/** 공격 속도 배수. 0.7 = 30% 감소 */
export const ATTACK_SCALE = 0.7;

/** 선딜·후딜처럼 「초」로 적힌 값에 곱한다 (≈1.43배로 늘어난다) */
export const ATTACK_TIME = 1 / ATTACK_SCALE;

// ── 소모품·스킬 재사용 대기 ────────────────────────────────
//
// 물약 8 → 24초. 연달아 들이켜면 「버티는 판단」이 사라진다 —
// 체력이 자원이 되려면 다음 한 모금까지가 멀어야 한다.
export const POTION_CD = 24;

// 스킬 쿨다운 배수. 스킬을 계속 돌리면 평타가 곁다리가 되고,
// 그러면 무기 계열·사거리 설계가 다 무의미해진다. 스킬은 **판단**이어야 한다.
// SKILLS 의 cd 를 하나씩 고치지 않고 여기서 한 번에 곱한다 —
// 개별로 고치면 언젠가 하나를 빠뜨린다.
export const SKILL_CD_SCALE = 2;
