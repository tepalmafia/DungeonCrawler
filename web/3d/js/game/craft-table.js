// ══════════════════════════════════════════════════════════════════════════
//  잔해 · 강화 · 재련 — **장비가 다 찬 뒤에도 쓸 곳** (docs/GRIND.md §4-1)
//
//  ★ 왜 필요한가
//    지금 파밍의 대상은 장비 하나뿐이고 칸은 여덟이다. 금방 찬다.
//    차고 나면 「좋은 게 이미 다 있다」가 되고 노가다가 멈춘다.
//    그리고 조각이 남아돈다 — 시뮬에서 회차 끝에 장비를 여덟 개 살 수 있다.
//
//    강화·재련은 **끝이 없는 소모처**다. 같은 장비를 계속 두드리게 만든다.
//
//  ★ 왜 강화가 벽을 뚫는 축인가
//    적은 회차마다 ×1.55 다. 장비 굴림은 회차에 ×1.34 로 따라가게 고쳤지만
//    (growth-table.itemScale) 그것만으로는 회차마다 1.16배씩 뒤진다.
//    **그 차이가 강화가 메울 몫이고, 그게 곧 「돌 이유」다.**
//    자동으로 따라잡히면 노가다할 게 없고, 아예 못 따라잡으면 벽이다.
//
//  ★ 부서지지 않는다
//    실패하면 값만 날린다. 「부서질까 봐 안 두드린다」가 되면 소모처가
//    소모처 노릇을 못 한다 (docs/GRIND.md §7 「위험은 시간 손실이지
//    자산 손실이면 안 된다」와 같은 이유).
//
//  ★ three 를 안 쓴다 — tools/tiers.js · sim.js 가 읽는다.
// ══════════════════════════════════════════════════════════════════════════

/** 잔해 — 잡몹이 흔하게 떨군다. 조각보다 흔하고, 자동으로 들어온다. */
export const SCRAP = {
  chance: { normal: 0.55, elite: 1, boss: 1 },
  mult: { normal: 1, elite: 3, boss: 8 },
  /** 층·회차가 깊을수록 많이 — 강화 비용도 같이 오르므로 비율은 유지된다 */
  base: (floorNo, tier = 0) => Math.round((3 + floorNo * 1.4) * (1 + tier * 0.5)),
  jitter: [0.8, 1.3],
};

// ── 강화 ────────────────────────────────────────────────────
//
// 한 단계가 **+4%**. 곱셈이 아니라 덧셈으로 쌓는다 — 곱셈이면 상한 근처에서
// 폭발하고, 그러면 상한을 올리는 것이 곧 밸런스 붕괴가 된다.
export const ENHANCE = {
  step: 0.04,
  /** 상한은 회차를 따라 오른다. 이게 「회차를 넘을 이유」의 절반이다. */
  cap: (tier = 0) => 6 + tier * 3,
  /**
   * 성공 확률 — 낮은 단계는 거의 확정, 높아질수록 떨어진다.
   * 0.34 아래로는 안 내린다. 그 아래면 「운이 나쁘면 한 시간」이 되고
   * 그건 노가다가 아니라 벌이다.
   */
  chance: (n) => Math.max(0.34, 1 - n * 0.055),
  /** n → n+1 에 드는 잔해. 이차로 오른다 — 뒤로 갈수록 오래 두드린다 */
  cost: (n) => Math.round(12 + n * 9 + n * n * 2.2),
};

export const plusCap = ENHANCE.cap;
/** 강화 단계 → 장비 수치에 곱할 배수 */
export const plusMult = (n) => 1 + ENHANCE.step * (n || 0);

// ── 재련 ────────────────────────────────────────────────────
//
// 접사 **하나만** 다시 굴린다. 전부 굴리면 그냥 새 장비를 먹는 것과 같고,
// 그러면 「이 물건을 키운다」는 감정이 안 생긴다.
export const REFORGE = {
  /** 잔해 + 조각을 같이 받는다 — 둘 다 남아돌지 않게 */
  scrap: (rarity) => 40 + rarity * 30,
  coin: (rarity) => 60 + rarity * 55,
};
