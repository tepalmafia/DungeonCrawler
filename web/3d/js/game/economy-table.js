/**
 * 바닥 필터 — **많이 떨어뜨리려면 안 볼 것을 안 보이게 해야 한다.**
 *
 * 드랍을 3배로 올리면 인벤토리와 화면이 쓰레기로 찬다. 노가다 게임이 이걸
 * 푸는 방법은 정해져 있다: 많이 떨어뜨리고 **거른다.**
 *
 * 층이 깊을수록 하한이 올라간다 — 5층에서 일반 장비는 이미 볼 일이 없다.
 * 필터는 **이름표만 감춘다.** 아이템은 그대로 있고 Alt 를 누르면 다 보인다 —
 * 지워 버리면 「혹시」가 없어져서 줍는 재미까지 사라진다.
 */
export const FLOOR_FILTER = {
  minRarityByFloor: [0, 0, 0, 1, 1, 1, 2, 2, 2],
  /** 그 층에서 이름표를 띄울 최소 등급 */
  at(floorNo, tier = 0) {
    const i = Math.min(this.minRarityByFloor.length - 1, Math.max(0, floorNo - 1));
    return Math.min(3, this.minRarityByFloor[i] + (tier > 1 ? 1 : 0));
  },
};

