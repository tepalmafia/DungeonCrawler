// 성장 **표** — 레벨이 오르면 무엇이 얼마나 오르는가, 방어도는 얼마나 막는가.
//
// ── 왜 갈라 놨는가 ──────────────────────────────────────────
// 이 식들은 player.js 와 combat.js 안에 흩어져 있었고, 두 파일 다 three 를
// 끌고 오므로 브라우저 밖에서 읽을 수 없었다. 그래서 밸런스를 볼 때마다
// 숫자를 손으로 옮겨 적었고, **옮겨 적은 표는 원본과 갈라진다.**
// (오늘 `?v=3` 과 `VERSION` 이 두 곳에 있어 스무 번 배포되는 동안 어긋나
//  있던 것과 같은 실패다.)
//
// 여기 있는 것은 전부 **순수 함수**다. 게임도 이걸 부르고 tools/sim.js 도
// 이걸 부른다 — 그래서 시뮬레이션 결과가 게임과 어긋날 수가 없다.

/** 레벨 1 기준값과 레벨당 증가분. 한 곳에서만 고친다. */
export const GROWTH = {
  hp: { base: 135, per: 18 },
  mp: { base: 60, per: 7 },
  armor: { base: 2, per: 1.2 },
  dmgMin: { per: 1.6 },        // **타격당이 아니라 초당이다** — perHit() 참조
  dmgMax: { per: 2.4 },
  crit: { base: 5 },
  critMult: { base: 1.8 },
  aspd: { per: 0.012 },
  mpRegen: { base: 3.2, per: 0.35 },
  xp: { first: 24, mul: 1.34, add: 8 },
};

/**
 * 평평한 피해(레벨 보너스·「+피해」 접사)를 **한 대당 얼마로 바꿀지.**
 *
 * 그냥 더하면 빠른 무기가 그 보너스를 더 자주 적용해서 계열 균형이
 * 레벨과 함께 무너진다. 9층에서 단검 92.5 대 대검 77.3 으로 21% 벌어져
 * 있었고, 원인은 무기 표가 아니라 이 한 줄이었다.
 *
 * **무기 속도로만 나눈다.** 최종 공격 속도로 나누면 「+공격 속도」 접사가
 * 스스로를 상쇄해서 아무 효과 없는 접사가 된다.
 */
export const perHit = (weaponSpeed) => 1 / (weaponSpeed || 1);

/**
 * 방어도 감쇠 — D3 계열의 쌍곡선. **절대 100% 가 안 된다.**
 *
 * 분모에 레벨이 들어가서, 같은 방어도라도 레벨이 오르면 덜 막는다.
 * 그래야 방어도가 층마다 계속 필요해진다.
 *
 * ★ `ref` — **회차 눈금.** 이걸 안 넣은 것이 늦은 회차 벽의 진짜 원인이었다.
 *   (`node tools/tiers.js` 로 찾았다. 안 만들었으면 못 봤다.)
 *
 *   분모의 상수(42 + 9L)는 안 자라는데 방어도는 회차마다 ×1.55 로 자란다.
 *   그러면 k 가 1 에 달라붙는다 — 15회차 방어도 18000, 감쇠 **98.8%** 다.
 *   장비를 아무리 키워도 피해가 바닥값 1 로 눌린다. 겉으로는 「내 성장이
 *   모자란가」로 보여서 엉뚱한 데(장비 배율)를 만질 뻔했다.
 *
 *   반대쪽도 같다. 내 방어도도 포화해서 15회차에 **여유 42** 가 나왔다 —
 *   위험이 아예 없어진다. 노가다 게임이라도 안 죽으면 안 재밌다.
 *
 *   눈금을 같이 키우면 둘 다 안 포화한다. 적 방어도는 회차와 같은 배수로
 *   자라니 k 가 **일정**하고, 내 방어도는 장비(×1.42)로만 자라니 회차가
 *   깊을수록 **조금씩 덜 막는다** — 긴장이 유지된다.
 *
 *   `ref = 1` 이면 예전과 똑같다. 1회차는 한 글자도 안 바뀐다.
 */
export function mitigate(raw, armor, level = 1, ref = 1) {
  const k = armor / (armor + (42 + level * 9) * ref);
  return Math.max(1, raw * (1 - k));
}

/** 그 회차의 눈금 — mitigate 의 `ref` 로 넘긴다 */
export const tierRef = (tier = 0) => Math.pow(TIER_POWER, tier);

/** 그 레벨에 도달하는 데 드는 누적 경험치 */
export function xpToLevel(level) {
  let need = GROWTH.xp.first, total = 0;
  for (let l = 1; l < level; l++) {
    total += need;
    need = Math.round(need * GROWTH.xp.mul + GROWTH.xp.add);
  }
  return total;
}

/** 누적 경험치로 레벨을 되돌려 준다 — 시뮬이 층마다 레벨을 알아야 한다 */
export function levelAtXp(xp) {
  let lv = 1, need = GROWTH.xp.first, acc = 0;
  while (acc + need <= xp) { acc += need; lv++; need = Math.round(need * GROWTH.xp.mul + GROWTH.xp.add); }
  return lv;
}

/**
 * 적의 층 배수. **피해는 체력보다 빨리 오른다.**
 *
 * 셋 다 powerMult 를 그냥 곱했더니 층이 깊어져도 긴장이 안 올랐다 —
 * 「내가 죽는 시간 ÷ 적을 죽이는 시간」이 1층 8.8 · 9층 7.6 이었다.
 * 플레이어도 레벨과 장비로 같은 비율로 세지기 때문이다.
 *
 * 지수 1.24 면 1층은 그대로(1^1.24 = 1)이고 9층만 4.60 → 6.9 다 —
 * **초반은 안 건드리고 후반만 조인다.**
 */
export const DMG_EXP = 1.24;
export const enemyDmgMult = (powerMult) => Math.pow(powerMult, DMG_EXP);

/**
 * 전 종족 체력 배수.
 *
 * 1.3 이었다 — 「한 마리씩 끌어와 오래 싸운다」는 예전 설계의 값이고,
 * 그때는 그게 맞았다. 지금 목적은 반대다: 잡몹 하나가 **1.5~3초**에 죽고
 * 그 사이가 촘촘해야 한다 (docs/GRIND.md §2). 실측 TTK 가 5~9초였다.
 *
 * 0.5 로 내렸더니 1층은 2.1초로 좋았는데 **6층이 4.1초**였다 — 한 회차를
 * 여섯 층으로 줄이면서 같은 배수 폭을 여섯 칸에 압축한 탓이다. 요약을
 * 1층으로만 내면 이걸 못 본다(그래서 시뮬이 전 층의 최악을 찍게 고쳤다).
 * 0.36 + 층 배수 상한 4.6 → 4.0 으로 **전 층 1.5~2.5초**에 들어온다.
 *
 * 0.42 → 0.38 → 0.36 으로 세 번 내렸다. 0.42 는 「한 마리 잡는 시간」만
 * 보면 통과였는데 **「처치 리듬」(TTK + 이동 1.4초)이 4.3초**로 목표를
 * 넘겼다 — 지표를 하나만 보면 안 보이는 실패다. 0.38 은 4.04 로 경계에
 * 딱 걸쳤고, 경계에 걸친 값은 다음에 뭘 조금만 만져도 뒤집힌다.
 * (0.42 로는 2.9초라 「처치 리듬」(TTK + 이동 1.4초)이 4.3초로 목표를
 *  0.3초 넘겼다. 한 마리 잡는 시간만 보면 통과라 안 보이는 실패다.)
 *
 * **개체 체력을 내린 만큼 마릿수를 올린다** (enemies.js 스폰). 층 전체의
 * 체력 총량은 오히려 늘어나므로 「쉬워진다」가 아니라 「촘촘해진다」다.
 */
export const HP_SCALE = 0.36;

/**
 * 아이템 롤 배율 — 층과 티어가 깊을수록 값이 커진다.
 *
 * **회차 몫이 덧셈이었다 (+0.55/회차). 그게 벽의 절반이었다.**
 * 적은 회차마다 ×1.55 로 곱해지는데 장비는 3.10 → 3.65 → 4.20 으로
 * 더해지기만 했다. `node tools/tiers.js` 로 재 보니 **3회차(약 40분)에서
 * 한 마리 잡는 데 4초, 여유 1.25** 였다 — 목적이 「계속 도는 것」인데
 * 40분에서 못 돌게 된다.
 *
 * 회차 몫을 곱셈으로 바꾼다. 1.42 는 적의 1.55 보다 **일부러 낮다** —
 * 자동으로 다 따라잡히면 강화·재련이 할 일이 없어지고, 그러면 장비가
 * 여덟 칸 차는 순간 노가다가 멈춘다. 남는 1.16배/회차가 **손으로 메울 몫**이다
 * (game/craft-table.js).
 *
 * 층 몫(+0.42)은 그대로다 — 1회차는 한 글자도 안 바뀐다 (tier 0 이면 지수가 0).
 */
export const itemScale = (floorNo, tier = 0) => (1 + (floorNo - 1) * 0.42) * Math.pow(1.42, tier);

// ── 회차(tier) — **끝을 없애는 축** ─────────────────────────
//
// 예전에는 `powerMult + tier × 0.35` 였다. 덧셈이라, 9층(4.60)을 깨고
// 2회차 1층으로 넘어가면 배수가 **1.35 로 뚝 떨어졌다.** 아홉 층을 올라온
// 캐릭터가 갑자기 세 배 약한 적을 만나는 셈이라, 「더 깊이」가 아니라
// 「처음부터 다시, 그런데 시시하게」가 됐다.
//
// 곱셈으로 바꾼다. 1.55 를 고른 이유: 한 회차가 층 아홉 개(1.00 → 4.60,
// 4.6배)를 통째로 덮으면 2회차 1층이 1회차 9층과 똑같아져서 **회차를 넘는
// 맛이 없다.** 1.55 면 2회차 1층이 1회차 3층쯤이고 2회차 5층에서 1회차
// 9층을 넘어선다 — 잠깐 숨을 고르고 곧 더 깊어진다.
//
// ★ 여기 「3~4회차부터 벽에 부딪히지만 그때까지는 정상이다」라고 적어 두고
//   **한 번도 재 본 적이 없었다.** 나중에 `tools/tiers.js` 를 만들어 재 보니
//   실제로는 **3회차(약 40분)에 한 마리 4초 · 여유 1.25** 였다 —
//   목적이 「시간 가는 줄 모르고 계속 도는 것」인데 40분에서 못 돌게 된다.
//   적어 두는 것과 재는 것은 다르다. 지금은 셋을 고쳐서 뚫었다:
//     · itemScale 회차 몫을 덧셈 → 곱셈 (×1.42/회차)
//     · mitigate 에 회차 눈금(ref) — 감쇠식이 포화해 피해가 0 이 되던 것
//     · 강화(craft-table) · 무한 성장(paragon-table) — 손으로 메우는 축
//   `node tools/tiers.js` 로 언제든 다시 잰다.
export const TIER_POWER = 1.55;
export const tierPower = (floorMult, tier = 0) => floorMult * Math.pow(TIER_POWER, tier);

