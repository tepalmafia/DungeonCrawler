/**
 * 네 갈래. **곱셈 배수**로 돌려준다 — 장비 접사(덧셈)와 섞이지 않게.
 *
 * `per` 는 1점당 비율이다. 힘 1% 가 민첩 0.5% 의 두 배로 보이지만,
 * 공격 속도는 피해와 곱해지는 축이라 실제 값어치는 비슷하다.
 */
export const PARAGON = {
  str: { name: '힘', what: '피해', per: 0.010, css: '#e08a5a' },
  agi: { name: '민첩', what: '공격 속도', per: 0.005, css: '#7fc47a' },
  vit: { name: '체력', what: '최대 체력', per: 0.012, css: '#e05a6a' },
  luck: { name: '행운', what: '드랍 등급 · 조각', per: 0.006, css: '#d8b45e' },
};

export const PARA_KEYS = Object.keys(PARAGON);

/**
 * 이 게임의 레벨이 실질적으로 멈추는 자리.
 *
 * 여기까지는 지금처럼 레벨이 오르고 **스킬 포인트**가 나온다.
 * 넘어가면 경험치가 통째로 무한 성장 주머니로 간다 — 그래야 레벨 숫자가
 * 의미 없이 커지는 대신 **쓸 수 있는 것**이 붙는다.
 *
 * **30 으로 뒀다가 20 으로 내렸다.** 경험치 곡선이 ×1.34 라 12회차를 돌아도
 * 레벨이 25 였다 — 무한 성장이 **영영 안 열리는 죽은 칸**이었다.
 * (tools/tiers.js 의 「무한성장」 칸이 전부 0 으로 찍혀서 알았다. 안 쟀으면
 *  「넣었는데 왜 아무 일도 안 일어나지」로 남았을 것이다.)
 *
 * 20 이면 스킬 칸 20개를 다 찍을 만큼의 포인트가 나오고(레벨 19점 + 보스),
 * 4~5회차쯤 도달한다 — 벽이 오는 자리와 같다.
 */
export const LEVEL_SOFT_CAP = 20;

/** n번째 점(0부터)에 드는 경험치. **선형으로만 오른다.** */
export const PARA_COST = { first: 420, add: 26 };
export const paraCost = (n) => PARA_COST.first + n * PARA_COST.add;

/** 누적 경험치 → 점수. 누적 비용이 등차수열이라 근을 풀어도 되지만,
 *  칸이 수만 개가 될 일이 없으므로 그냥 센다 (읽기 쉬운 쪽). */
export function paraPointsAt(xp) {
  let n = 0, acc = 0;
  while (acc + paraCost(n) <= xp) { acc += paraCost(n); n++; }
  return n;
}

/** 다음 점까지 얼마나 남았나 — UI 의 막대가 읽는다 */
export function paraProgress(xp) {
  let n = 0, acc = 0;
  while (acc + paraCost(n) <= xp) { acc += paraCost(n); n++; }
  return { points: n, into: xp - acc, need: paraCost(n) };
}

/** 그 갈래에 몇 점 찍었을 때의 배수. 안 찍었으면 정확히 1 이다. */
export const paraMult = (key, pts) => 1 + (PARAGON[key]?.per ?? 0) * (pts || 0);
